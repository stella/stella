import { renderToStaticMarkup } from "react-dom/server";

import { describe, expect, test } from "bun:test";

import { AiLabel } from "./ai-label";

const DISCLOSURE = "Generated by stella, not by the court.";

const markup = renderToStaticMarkup(
  <AiLabel disclosure={DISCLOSURE} label="AI topics" />,
);

describe("AiLabel", () => {
  test("is a native button named by its visible words", () => {
    const trigger = /<button[^>]*>/u.exec(markup)?.[0] ?? "";

    expect(trigger).toContain('type="button"');
    expect(trigger).toContain('data-slot="ai-label"');
    expect(trigger).toContain('aria-expanded="false"');
    expect(trigger).toContain('aria-haspopup="dialog"');
    expect(trigger).not.toContain("aria-label");
    expect(markup).toContain("AI topics</button>");
  });

  test("keeps the line's own type and adds no chrome", () => {
    const trigger = /<button[^>]*class="([^"]*)"/u.exec(markup)?.[1] ?? "";

    for (const inherited of [
      "[font:inherit]",
      "[text-transform:inherit]",
      "tracking-[inherit]",
      "text-inherit",
    ]) {
      expect(trigger).toContain(inherited);
    }
    expect(trigger).not.toMatch(/\b(bg-|border|shadow)/u);
  });

  test("the sparkle is decoration", () => {
    expect(markup).toMatch(/<svg[^>]*aria-hidden="true"/u);
  });

  test("the disclosure waits for the reader to ask", () => {
    expect(markup).not.toContain(DISCLOSURE);
  });
});
