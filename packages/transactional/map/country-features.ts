import type { CountryCode } from "@stll/country-codes";

/**
 * Which features of the base map (Natural Earth's 1:50m Admin 0 countries, as
 * `world-atlas` ships them) draw each country. A feature is found by its ISO
 * 3166-1 numeric id, or by its name for the few that carry no id.
 *
 * The map shades the country the edge reported, never one guessed from the
 * point: an IP location on a coast or a small island often falls in the sea at
 * this scale. The test binds this table to the base map in both directions,
 * so every selector finds a feature and every feature belongs to a country or
 * to `UNASSIGNED_FEATURES`.
 */

export type FeatureSelector =
  { by: "isoNumeric"; id: string } | { by: "name"; name: UnnumberedFeature };

export type CountryOnMap =
  | {
      type: "drawn";
      features: readonly [FeatureSelector, ...FeatureSelector[]];
    }
  /** Too small to appear at this scale; the map shades nothing. */
  | { type: "notDrawn" };

/** Natural Earth features without an ISO numeric id. */
const UNNUMBERED_FEATURES = [
  "Kosovo",
  "N. Cyprus",
  "Somaliland",
  "Indian Ocean Ter.",
  "Siachen Glacier",
] as const;

type UnnumberedFeature = (typeof UNNUMBERED_FEATURES)[number];

/** Features no country code shades: the glacier is disputed between two. */
export const UNASSIGNED_FEATURES: readonly UnnumberedFeature[] = [
  "Siachen Glacier",
];

const iso = (id: string): FeatureSelector => ({ by: "isoNumeric", id });

const named = (name: UnnumberedFeature): FeatureSelector => ({
  by: "name",
  name,
});

const drawn = (
  first: FeatureSelector,
  ...rest: FeatureSelector[]
): CountryOnMap => ({ type: "drawn", features: [first, ...rest] });

const NOT_DRAWN: CountryOnMap = { type: "notDrawn" };

