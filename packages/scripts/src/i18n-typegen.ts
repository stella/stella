#!/usr/bin/env bun
/**
 * Generates a TypeScript declaration file for the English
 * locale that preserves string literal types. This enables
 * use-intl to parse ICU variables at the type level and
 * enforce interpolation parameters.
 *
 * Usage: i18n-typegen <langs-dir> [--check] [--compact]
 *
 * --check    Verify the on-disk messages.gen.ts matches what
 *            would be generated from en.json. Exits non-zero on
 *            drift without writing.
 * --compact  Strip static prose from message literals while
 *            preserving all ICU placeholders, select/plural branches
 *            and rich tags so use-intl enforces identical parameter
 *            types with far fewer TypeScript instantiations.
 */
import { parse, TYPE } from "@formatjs/icu-messageformat-parser";
import type { MessageFormatElement } from "@formatjs/icu-messageformat-parser";
import { Result } from "better-result";
import path from "node:path";

type JsonValue = string | JsonObject;
type JsonObject = {
  [key: string]: JsonValue;
};

const isJsonObject = (value: unknown): value is JsonObject =>
  typeof value === "object" &&
  value !== null &&
  !Array.isArray(value) &&
  Object.values(value).every(
    (entry): entry is JsonValue =>
      typeof entry === "string" || isJsonObject(entry),
  );

const parseMessages = (json: string): JsonObject => {
  const parsed: unknown = JSON.parse(json);
  if (!isJsonObject(parsed)) {
    console.error(
      "Expected en.json to contain only nested objects and strings",
    );
    process.exit(1);
  }

  return parsed;
};

const compactElements = (elements: readonly MessageFormatElement[]): string => {
  let out = "";
  for (const el of elements) {
    switch (el.type) {
      case TYPE.literal:
      case TYPE.pound:
        break;
      case TYPE.argument:
        out += `{${el.value}}`;
        break;
      case TYPE.number:
        out += `{${el.value}, number}`;
        break;
      case TYPE.date:
        out += `{${el.value}, date}`;
        break;
      case TYPE.time:
        out += `{${el.value}, time}`;
        break;
      case TYPE.select: {
        const opts = Object.entries(el.options)
          .map(([key, opt]) => `${key} {${compactElements(opt.value)}}`)
          .join(" ");
        out += `{${el.value}, select, ${opts}}`;
        break;
      }
      case TYPE.plural: {
        const kind = el.pluralType === "ordinal" ? "selectordinal" : "plural";
        const nested = Object.values(el.options)
          .map((opt) => compactElements(opt.value))
          .join("");
        out += `{${el.value}, ${kind}, other {#${nested}}}`;
        break;
      }
      case TYPE.tag:
        out += `<${el.value}>${compactElements(el.children)}</${el.value}>`;
        break;
    }
  }
  return out;
};

const compactMessage = (value: string): string => {
  if (!value.includes("{") && !value.includes("<")) {
    return "";
  }
  return Result.try(() =>
    compactElements(parse(value, { ignoreTag: false })),
  ).unwrapOr(value);
};

const args = process.argv.slice(2);
const langsDir = args.find((a) => !a.startsWith("--"));
const checkOnly = args.includes("--check");
const compact = args.includes("--compact");

if (!langsDir) {
  console.error("Usage: i18n-typegen <langs-dir> [--check] [--compact]");
  process.exit(1);
}

const inputPath = path.resolve(langsDir, "en.json");
const outputPath = path.resolve(langsDir, "messages.gen.ts");

const json = await Bun.file(inputPath).text();
const messages = parseMessages(json);

const indent = (depth: number) => "  ".repeat(depth);

let keyCount = 0;

const toLiteral = (value: JsonValue, depth: number): string => {
  if (typeof value === "string") {
    if (!compact) {
      return JSON.stringify(value);
    }
    const compacted = compactMessage(value);
    return compacted === "" ? "string" : JSON.stringify(compacted);
  }

  if (typeof value === "object" && !Array.isArray(value)) {
    const entries = Object.entries(value);
    if (entries.length === 0) {
      return "Record<string, never>";
    }

    const lines = entries.map(([key, val]) => {
      keyCount++;
      return `${indent(depth + 1)}${JSON.stringify(key)}: ${toLiteral(val, depth + 1)};`;
    });
    return `{\n${lines.join("\n")}\n${indent(depth)}}`;
  }

  return "never";
};

const declaration = `// Auto-generated by generate-i18n-types.ts
// Do not edit manually.

type Messages = ${toLiteral(messages, 0)};

export type { Messages as default };
`;

// Matching outputs stay untouched: concurrent generation can otherwise expose
// a truncated file to consumers verifying prepared source hashes.
const outputFile = Bun.file(outputPath);
const existing = (await outputFile.exists()) ? await outputFile.text() : "";

if (checkOnly) {
  if (existing !== declaration) {
    console.error(
      `Error: ${outputPath} is out of sync with en.json. Run \`bun run typegen\`.`,
    );
    process.exit(1);
  }
  console.log(`${outputPath} is in sync (${keyCount} keys)`);
} else {
  if (existing !== declaration) {
    await Bun.write(outputPath, declaration);
  }
  console.log(`Generated ${outputPath} (${keyCount} keys)`);
}
