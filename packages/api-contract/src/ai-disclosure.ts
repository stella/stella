/**
 * What a reader is told about content stella generated, by the kind of
 * content it is.
 *
 * A closed set: every place that marks generated content names one of these
 * contexts, never free text, so the wording is chosen once per context and
 * translated once per locale. The web and the shared reader render
 * `messageKey` from their catalogues; agents (MCP tools, the CLI) receive the
 * English `text` beside the content it describes. The English catalogue entry
 * for each `messageKey` is held equal to `text` by a test, so the two cannot
 * drift.
 *
 * A new context (chat answers, tabular review, review suggestions…) is a new
 * entry here with its own wording, not a reuse of one written for something
 * else.
 */
export const AI_DISCLOSURES = {
  caseLaw: {
    messageKey: "aiDisclosure.caseLaw",
    text:
      "AI summaries, notes and analyses of court decisions are generated by " +
      "stella, not endorsed by the courts, and do not represent the courts' " +
      "own reasoning; they are aids for legal professionals, and the " +
      "decision text remains the authoritative source.",
  },
  billingDrafts: {
    messageKey: "aiDisclosure.billingDrafts",
    text:
      "AI billing drafts are suggestions stella generates from the entries " +
      "you selected, your earlier entries on the matter and the billing " +
      "guidelines. Review each entry before you create it.",
  },
} as const satisfies Record<
  string,
  { messageKey: `aiDisclosure.${string}`; text: string }
>;

export type AiDisclosureContext = keyof typeof AI_DISCLOSURES;

export type AiDisclosureMessageKey =
  (typeof AI_DISCLOSURES)[AiDisclosureContext]["messageKey"];

/** The disclosure as an agent receives it, beside the generated content. */
export type AiDisclosure<C extends AiDisclosureContext = AiDisclosureContext> =
  {
    context: C;
    text: (typeof AI_DISCLOSURES)[C]["text"];
  };

export const aiDisclosure = <C extends AiDisclosureContext>(
  context: C,
): AiDisclosure<C> => ({ context, text: AI_DISCLOSURES[context].text });
