/** A card's quoted runs: whether each is marked cited, and its paragraphs. */
const quotedRuns = (markup: string) =>
  Array.from(
    markup.matchAll(
      /<div(?: class="[^"]*")?( data-cited="")? data-slot="provision-card-quote">(.*?)<\/div>/gu,
    ),
    ([, cited, body = ""]) => ({
      cited: cited !== undefined,
      texts: Array.from(
        body.matchAll(/<p[^>]*>(.*?)<\/p>/gu),
        ([, paragraph]) => paragraph,
      ),
    }),
  );

