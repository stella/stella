export type OrgScopeTableDefinition = {
  table: PgTable;
  organizationId: SQL;
  workspaceId: SQL;
  rowId: SQL;
} & (
  | { identityKind: "primary-key" }
  | { identityKind: "unique-index"; identityIndexName: string }
);

const workspaceOrganization = (workspaceId: SQL) => sql`(
  SELECT scope_workspace.organization_id FROM public.workspaces scope_workspace
  WHERE scope_workspace.id = ${workspaceId}
)`;

const threadOrganization = (threadId: SQL) => sql`(
  SELECT scope_thread.organization_id FROM public.chat_threads scope_thread
  WHERE scope_thread.id = ${threadId}
)`;

const threadWorkspace = (threadId: SQL) => sql`(
  SELECT scope_thread.workspace_id FROM public.chat_threads scope_thread
  WHERE scope_thread.id = ${threadId}
)`;

const messageThread = (messageId: SQL) => sql`(
  SELECT scope_message.thread_id FROM public.chat_messages scope_message
  WHERE scope_message.id = ${messageId}
)`;

