/**
 * An agent reading a decision's analysis is told the same thing the web
 * reader's AI mark tells a person: the analysis is stella's, not the court's.
 */

import { describe, expect, test } from "bun:test";

import { AI_DISCLOSURES, aiDisclosure } from "@stll/api-contract/ai-disclosure";

import generateDecisionAnalysis from "./generate";

describe("case-law analysis disclosure for agents", () => {
  test("the tool description names the field and what it means", () => {
    const { description } = generateDecisionAnalysis.config;

    expect(description).toContain("aiDisclosure");
    expect(description).toContain("generated by stella, not by the court");
  });

  test("the disclosure carries its closed context and the shared sentence", () => {
    expect(aiDisclosure("caseLaw")).toEqual({
      context: "caseLaw",
      text: AI_DISCLOSURES.caseLaw.text,
    });
  });
});
