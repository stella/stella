const REASONS_HEADING_RE = /^uzasadnienie\b/iu;
// The editor numbers the reasons on from the operative points when they
// share one outline ("V. UZASADNIENIE" after point IV).
const NUMBERED_REASONS_HEADING_RE = /^[IVXLC]+\s*[.)]\s*uzasadnienie$/iu;
const HOLDING_HEADING_RE =
  /^(?:orzeka|postanawia|uchwala|zarządza)\s*(?::\s*)?$/iu;
const HOLDING_ITEM_RE = /^(?:[IVXLC]+\s*[.)]|[0-9]+\s*[.)]|[a-z][)])\s*/u;
const OPERATIVE_VERB_RE =
  /^(?:oddala|zmienia|uchyla|zasądza|stwierdza|umarza|utrzymuje|nakazuje|odrzuca|ustala|przyznaje|zwraca się|przekazuje|nie obciąża|znosi)\b/iu;
const CLOSING_RE =
  /^[A-ZĄĆĘŁŃÓŚŹŻ][\p{L} .-]+,\s+dnia\s+\d{1,2}\s+\p{L}+\s+\d{4}\s*r?\.?$/u;
const SIGNATURE_RE =
  /^(?:SSA|SSA del\.|SSO|SSR|sędzia|Sędzia|Przewodniczący|Przewodnicząca|Prezes|sprawozdawca)\b/u;

type ParserSection = "preamble" | "holding" | "reasoning";

type ParserState = {
  blocks: Block[];
  blockIndex: number;
  blockIdCounter: number;
  section: ParserSection;
  sawDecisionTitle: boolean;
  decisionTitle: string | undefined;
  superscripts: boolean;
  markup: PlDecisionMarkup | undefined;
  /** A list item's marker, waiting to open the item's first paragraph. */
  pendingMarker: Inline[] | undefined;
  listMarkers: WeakMap<Element, WeakMap<Element, string | null>>;
  listItemBoundaries: WeakMap<Element, boolean>;
};

const hasHtmlTags = (content: string): boolean =>
  /<[a-z][\s\S]*>/iu.test(content);

const normalizeWhitespace = (text: string): string =>
  text
    .replace(/\u00a0/gu, " ")
    .replace(/(?<![ \t])[ \t]+\n/gu, "\n")
    .trim();

const normalizeLegacyPlainText = (text: string): string =>
  text
    .replace(/\r\n/gu, "\n")
    .replace(/\u00a0/gu, " ")
    .replace(/\t+/gu, " ")
    .split("\n")
    .map((line) => line.replace(/ {2,}/gu, " ").trim())
    .join("\n")
    .replace(/\n{3,}/gu, "\n\n")
    .trim();

const isDecisionTitleText = (text: string): boolean =>
  DECISION_TITLES.has(text.trim().toLocaleUpperCase("pl-PL"));

const normalizeDecisionTitle = (
  decisionType: string | undefined,
): string | undefined => {
  if (!decisionType) {
    return undefined;
  }

  const key = decisionType.toLocaleLowerCase("pl-PL");
  if (includes(POLISH_DECISION_TITLE_KEYS, key)) {
    return POLISH_DECISION_TITLE_MAP[key];
  }
  return undefined;
};

const createState = (
  superscripts: boolean,
  markup: PlDecisionMarkup | undefined,
): ParserState => ({
  blocks: [],
  blockIndex: 0,
  blockIdCounter: 0,
  section: "preamble",
  sawDecisionTitle: false,
  decisionTitle: undefined,
  superscripts,
  markup,
  pendingMarker: undefined,
  listMarkers: new WeakMap(),
  listItemBoundaries: new WeakMap(),
});

const nextBlockId = (state: ParserState): string => {
  state.blockIdCounter += 1;
  return `b${state.blockIdCounter}`;
};

const pushHeading = (
  state: ParserState,
  level: 1 | 2 | 3,
  plainText: string,
  role: "decision-title" | "section-heading",
  inlines: Inline[],
): void => {
  state.blockIndex += 1;
  state.blocks.push({
    id: nextBlockId(state),
    anchorId: `h-${state.blockIndex}`,
    type: "heading",
    level,
    role,
    inlines,
    plainText,
  });
};

const pushParagraph = (
  state: ParserState,
  plainText: string,
  inlines: Inline[],
  role?: ParagraphRole,
): void => {
  state.blockIndex += 1;
  state.blocks.push({
    id: nextBlockId(state),
    anchorId: `p-${state.blockIndex}`,
    type: "paragraph",
    ...(role && { role }),
    inlines,
    plainText,
  });
};

const pushTable = (
  state: ParserState,
  rows: TableCell[][],
  plainText: string,
): void => {
  state.blockIndex += 1;
  state.blocks.push({
    id: nextBlockId(state),
    anchorId: `t-${state.blockIndex}`,
    type: "table",
    role: "metadata-table",
    rows,
    plainText,
  });
};

const textInline = (text: string, anonymized = false): Inline[] =>
  text
    ? [
        {
          type: "text",
          text,
          ...(anonymized && { anonymized: true as const }),
        },
      ]
    : [];

/**
 * A run with every `\n` its text keeps made a line break. The document's
 * whitespace is rendered before the walk (`renderHtmlWhiteSpace`), so a line
 * break left in the text is one the source preserves (`<pre>`, `white-space:
 * pre-wrap`); every other is already a space.
 */
const lineBreaksOf = (inlines: readonly Inline[]): Inline[] =>
  inlines.flatMap((inline): Inline[] => {
    if (inline.type === "text") {
      if (!inline.text.includes("\n")) {
        return [inline];
      }
      return inline.text
        .split("\n")
        .flatMap((line, index): Inline[] => [
          ...(index === 0 ? [] : [{ type: "line-break" as const }]),
          ...(line === "" ? [] : [{ ...inline, text: line }]),
        ]);
    }
    return hasInlineChildren(inline)
      ? [{ ...inline, children: lineBreaksOf(inline.children) }]
      : [inline];
  });

/**
 * A run without the line breaks at either edge, inside formatting too: the
 * line a block's edge ends prints nothing of its own.
 */
const trimLineBreaks = (inlines: readonly Inline[]): Inline[] => {
  const trimEdge = (run: readonly Inline[], fromEnd: boolean): Inline[] => {
    const items = fromEnd ? [...run].toReversed() : [...run];
    while (items.length > 0) {
      const edge = items[0];
      if (edge?.type === "line-break") {
        items.shift();
        continue;
      }
      if (edge !== undefined && hasInlineChildren(edge)) {
        const children = trimEdge(edge.children, fromEnd);
        if (children.length === 0) {
          items.shift();
          continue;
        }
        items[0] = { ...edge, children };
      }
      break;
    }
    return fromEnd ? items.toReversed() : items;
  };
  return trimEdge(trimEdge(inlines, false), true);
};

/**
 * A publisher's own conventions, read off the walked run before a kept `\n`
 * becomes a line break: until then a line-break inline is a `<br>`.
 */
const readMarkupInlines = (state: ParserState, inlines: Inline[]): Inline[] =>
  state.markup === PL_DECISION_MARKUP.COMMON_COURT
    ? readCommonCourtInlines(inlines)
    : inlines;

/** An element's inlines, over a document whose whitespace is rendered. */
const walkInlines = (
  $: cheerio.CheerioAPI,
  el: cheerio.Cheerio<AnyNode>,
  state: ParserState,
): Inline[] =>
  trimLineBreaks(
    lineBreaksOf(
      readMarkupInlines(
        state,
        walkInlinesShared($, el, {
          sanitizeHref: sanitizeUrl,
          anonymized: false,
          superscripts: state.superscripts,
        }),
      ),
    ),
  );

/** `marker`, a space, then `inlines`: a list item as it is printed. */
const withMarker = (marker: Inline[], inlines: Inline[]): Inline[] => {
  const joined = [...marker];
  appendTextInline(joined, " ");
  for (const inline of inlines) {
    if (inline.type === "text") {
      appendTextInline(joined, inline.text, inline.anonymized === true);
    } else {
      joined.push(inline);
    }
  }
  return joined;
};

const alphabeticOrdinal = (ordinal: number): string => {
  let rest = ordinal;
  let text = "";
  while (rest > 0) {
    rest -= 1;
    text = String.fromCodePoint(97 + (rest % 26)) + text;
    rest = Math.floor(rest / 26);
  }
  return text;
};

const ROMAN_DIGITS = [
  [1000, "M"],
  [900, "CM"],
  [500, "D"],
  [400, "CD"],
  [100, "C"],
  [90, "XC"],
  [50, "L"],
  [40, "XL"],
  [10, "X"],
  [9, "IX"],
  [5, "V"],
  [4, "IV"],
  [1, "I"],
] as const;

const romanOrdinal = (ordinal: number): string => {
  let rest = ordinal;
  let text = "";
  for (const [value, digits] of ROMAN_DIGITS) {
    while (rest >= value) {
      text += digits;
      rest -= value;
    }
  }
  return text;
};

const ORDERED_LIST_STYLE_KEYS = ["1", "a", "A", "i", "I"] as const;

type OrderedListType = (typeof ORDERED_LIST_STYLE_KEYS)[number];

/**
 * How each `<ol type>` prints a counter, and the counters it can print: CSS
 * counts alphabetically from 1 and in Roman numerals from 1 to 3999, and
 * prints a counter outside its style's range in decimal.
 */
const ORDERED_LIST_STYLE = {
  "1": { range: [-Infinity, Infinity], print: String },
  a: { range: [1, Infinity], print: alphabeticOrdinal },
  A: {
    range: [1, Infinity],
    print: (ordinal: number): string =>
      alphabeticOrdinal(ordinal).toLocaleUpperCase("pl-PL"),
  },
  i: {
    range: [1, 3999],
    print: (ordinal: number): string => romanOrdinal(ordinal).toLowerCase(),
  },
  I: { range: [1, 3999], print: romanOrdinal },
} as const satisfies Record<
  OrderedListType,
  { range: readonly [number, number]; print: (ordinal: number) => string }
>;

const counterText = (type: OrderedListType, ordinal: number): string => {
  const {
    range: [min, max],
    print,
  } = ORDERED_LIST_STYLE[type];
  return ordinal >= min && ordinal <= max ? print(ordinal) : String(ordinal);
};

/**
 * CSS `list-style-type` keywords: the `type` each counts in, or null for a
 * keyword that prints no number (`none`, and the bullets).
 */
const CSS_LIST_STYLE_TYPES: Readonly<Record<string, OrderedListType | null>> = {
  none: null,
  disc: null,
  circle: null,
  square: null,
  decimal: "1",
  "lower-alpha": "a",
  "lower-latin": "a",
  "upper-alpha": "A",
  "upper-latin": "A",
  "lower-roman": "i",
  "upper-roman": "I",
};

/** `list-style` shorthand parts that name no counter style. */
const LIST_STYLE_OTHER_PART = /^(?:inside|outside|url\(.*\))$/u;

/**
 * The counting an element's inline style states: a type, null where it
 * prints no number, undefined where the style states none this reader knows.
 * The `list-style` shorthand without a counter style resets it to `disc`,
 * which prints no number.
 */
const cssListStyleOf = (element: Element): OrderedListType | null | undefined =>
  inlineStyleValue<OrderedListType | null>(element, (property, value) => {
    if (property === "list-style-type") {
      return Object.hasOwn(CSS_LIST_STYLE_TYPES, value)
        ? { value: CSS_LIST_STYLE_TYPES[value] ?? null }
        : undefined;
    }
    if (property !== "list-style") {
      return undefined;
    }
    const parts = value.split(/\s+/u);
    const counter = parts.find((part) =>
      Object.hasOwn(CSS_LIST_STYLE_TYPES, part),
    );
    if (counter !== undefined) {
      return { value: CSS_LIST_STYLE_TYPES[counter] ?? null };
    }
    return parts.every((part) => LIST_STYLE_OTHER_PART.test(part))
      ? { value: null }
      : undefined;
  })?.value;

/**
 * An integer attribute as HTML states it, or undefined. A value past the
 * safe integer range is not one a list counts from: a browser stores it in a
 * 32-bit field, and arithmetic on it here would stop being exact.
 */
const integerAttribute = (value: string | undefined): number | undefined =>
  value === undefined
    ? undefined
    : parseIntegerToken(value.trim()).unwrapOr(undefined);

/**
 * The number a browser prints before an `<li>` of an `<ol>`: the list's
 * `start` (or its length, `reversed`), stepped once per item, reset by an
 * item's own `value`, set in the list's `type` unless an inline
 * `list-style-type` says otherwise. A list item outside an ordered list, or
 * styled to print no number, prints none.
 */
const orderedListMarker = (
  state: ParserState,
  item: Element,
): string | undefined => {
  const list = item.parent;
  if (list === null || !isTag(list) || list.tagName.toLowerCase() !== "ol") {
    return undefined;
  }
  const cached = state.listMarkers.get(list);
  if (cached !== undefined) {
    const marker = cached.get(item);
    if (marker === undefined) {
      return panic("Ordered list item is missing its computed marker");
    }
    return marker ?? undefined;
  }
  const items = list.children.filter(
    (child): child is Element =>
      isTag(child) && child.tagName.toLowerCase() === "li",
  );
  const reversed = list.attribs["reversed"] !== undefined;
  const step = reversed ? -1 : 1;
  let ordinal =
    integerAttribute(list.attribs["start"]) ?? (reversed ? items.length : 1);
  // An inline style outranks the `type` attribute, the item's its list's.
  // (`null`, no number, is a statement and must not fall through.)
  const typeAttribute = list.attribs["type"] ?? "1";
  const attributeType: OrderedListType = includes(
    ORDERED_LIST_STYLE_KEYS,
    typeAttribute,
  )
    ? typeAttribute
    : "1";
  const listStyle = cssListStyleOf(list);
  const markers = new WeakMap<Element, string | null>();
  // One walk per list: finding each item's preceding counters separately
  // makes a long publisher list quadratic in its number of items.
  for (const sibling of items) {
    ordinal = integerAttribute(sibling.attribs["value"]) ?? ordinal;
    const itemStyle = cssListStyleOf(sibling);
    const stated = itemStyle === undefined ? listStyle : itemStyle;
    const type = stated === undefined ? attributeType : stated;
    markers.set(
      sibling,
      type === null ? null : `${counterText(type, ordinal)}.`,
    );
    ordinal += step;
  }
  state.listMarkers.set(list, markers);
  const marker = markers.get(item);
  if (marker === undefined) {
    return panic("Ordered list item is missing its computed marker");
  }
  return marker ?? undefined;
};

const inferParagraphRole = (
  state: ParserState,
  plainText: string,
  isBold = false,
): ParagraphRole | undefined => {
  if (CASE_NUMBER_RE.test(plainText)) {
    return "case-number";
  }

  if (state.section === "reasoning") {
    if (CLOSING_RE.test(plainText)) {
      return "closing";
    }

    if (plainText.length <= 120 && SIGNATURE_RE.test(plainText)) {
      return "signature";
    }

    return "argumentation";
  }

  if (
    state.section === "holding" ||
    HOLDING_ITEM_RE.test(plainText) ||
    OPERATIVE_VERB_RE.test(plainText)
  ) {
    return "holding";
  }

  if (isBold && state.sawDecisionTitle) {
    return "holding";
  }

  return "intro";
};

const handleHeadingText = (
  state: ParserState,
  plainText: string,
  inlines: Inline[],
): boolean => {
  if (isDecisionTitleText(plainText)) {
    const normalizedPlainText = plainText.trim().toLocaleUpperCase("pl-PL");
    if (
      state.sawDecisionTitle &&
      state.decisionTitle?.trim().toLocaleUpperCase("pl-PL") ===
        normalizedPlainText
    ) {
      if (REASONS_HEADING_RE.test(plainText)) {
        state.section = "reasoning";
      }
      return true;
    }

    if (REASONS_HEADING_RE.test(plainText) && state.sawDecisionTitle) {
      pushHeading(state, 2, plainText, "section-heading", inlines);
      state.section = "reasoning";
      return true;
    }

    pushHeading(state, 1, plainText, "decision-title", inlines);
    state.sawDecisionTitle = true;
    state.decisionTitle = plainText;
    if (REASONS_HEADING_RE.test(plainText)) {
      state.section = "reasoning";
    }
    return true;
  }

  if (
    REASONS_HEADING_RE.test(plainText) ||
    (state.markup === PL_DECISION_MARKUP.COMMON_COURT &&
      NUMBERED_REASONS_HEADING_RE.test(plainText))
  ) {
    pushHeading(state, 2, plainText, "section-heading", inlines);
    state.section = "reasoning";
    return true;
  }

  if (HOLDING_HEADING_RE.test(plainText)) {
    pushHeading(state, 2, plainText, "section-heading", inlines);
    state.section = "holding";
    return true;
  }

  return false;
};

/** Push a paragraph for an element's inlines; whether it held any text. */
const parseParagraphElement = (
  $: cheerio.CheerioAPI,
  state: ParserState,
  node: cheerio.Cheerio<AnyNode>,
  marker?: string,
): boolean => {
  const inlines = walkInlines($, node, state);
  const plainText = normalizeWhitespace(inlinesToPlainText(inlines));

  if (!plainText) {
    return false;
  }

  // A list's printed number, or a common court's `<dt>` marker waiting for
  // the item's first paragraph.
  const pending = state.pendingMarker;
  state.pendingMarker = undefined;
  const itemMarker = marker === undefined ? pending : textInline(marker);

  if (
    itemMarker === undefined &&
    handleHeadingText(state, plainText, inlines)
  ) {
    return true;
  }

  // The role is read from the item's own words; the number its list prints
  // before it is the list's, not a holding marker the item states.
  const role = inferParagraphRole(
    state,
    plainText,
    node.is("strong, b") || node.children("strong, b").length > 0,
  );

  if (role === "holding") {
    state.section = "holding";
  }

  if (itemMarker === undefined) {
    pushParagraph(state, plainText, inlines, role);
    return true;
  }
  const marked = withMarker(itemMarker, inlines);
  pushParagraph(
    state,
    normalizeWhitespace(inlinesToPlainText(marked)),
    marked,
    role,
  );
  return true;
};

const parseTableElement = (
  $: cheerio.CheerioAPI,
  state: ParserState,
  node: cheerio.Cheerio<AnyNode>,
): void => {
  node.children("caption").each((_, caption) => {
    const inlines = walkInlines($, $(caption), state);
    const plainText = normalizeWhitespace(inlinesToPlainText(inlines));
    if (plainText) {
      pushParagraph(state, plainText, inlines);
    }
  });
  let rows: TableCell[][] = [];
  const flushRows = (): void => {
    if (rows.length === 0) {
      return;
    }
    const plainText = rows
      .map((row) => row.map((cell) => cell.plainText).join(" | "))
      .join("\n");
    pushTable(state, rows, plainText);
    rows = [];
  };

  const tableRows = ownTableRows(node);
  const hasSpanningRows = tableRows.toArray().some((row) =>
    $(row)
      .children("th, td")
      .toArray()
      .some((cell) => {
        const span = integerAttribute(cell.attribs["rowspan"]);
        return span === 0 || (span !== undefined && span > 1);
      }),
  );
  tableRows.each((_, row) => {
    const rowCells = $(row).children("th, td");
    // The courts' editor frames text in a table: a judgment's reasons in one
    // cell, a form's part heading across a whole row. A single explicit cell
    // is prose only when no spanning cell links the table's rows.
    if (
      state.markup === PL_DECISION_MARKUP.COMMON_COURT &&
      !hasSpanningRows &&
      rowCells.length === 1
    ) {
      flushRows();
      parseChildren($, state, rowCells.first());
      return;
    }
    const cells: TableCell[] = [];
    rowCells.each((__, cell) => {
      const inlines = walkInlines($, $(cell), state);
      const plainText = normalizeWhitespace(inlinesToPlainText(inlines));
      const colSpan = integerAttribute(cell.attribs["colspan"]);
      const rowSpan = integerAttribute(cell.attribs["rowspan"]);
      const parsed: TableCell = { inlines, plainText };
      if (state.markup === PL_DECISION_MARKUP.COMMON_COURT) {
        if (colSpan !== undefined && colSpan > 1) {
          parsed.colSpan = colSpan;
        }
        if (rowSpan !== undefined && rowSpan > 1) {
          parsed.rowSpan = rowSpan;
        }
      }
      cells.push(parsed);
    });

    if (cells.length > 0) {
      rows.push(cells);
    }
  });

  flushRows();
};

/**
 * Children of a list item read as blocks of their own: lists, paragraphs,
 * headings, preformatted text and tables, unless an inline `display` keeps
 * them in the line. Any other child is part of the item's text.
 */
const LIST_ITEM_BLOCK_TAGS: ReadonlySet<string> = new Set([
  "h1",
  "h2",
  "h3",
  "h4",
  "h5",
  "h6",
  "ol",
  "p",
  "pre",
  "table",
  "ul",
]);

const isListItemBlock = (node: Element): boolean =>
  LIST_ITEM_BLOCK_TAGS.has(node.tagName.toLowerCase()) && isHtmlBlock(node);

const listItemBoundary = (
  state: ParserState,
  node: AnyNode,
): Element | undefined => {
  if (!isTag(node) || isExcludedHtmlTag(node.tagName.toLowerCase())) {
    return undefined;
  }
  const cached = state.listItemBoundaries.get(node);
  if (cached !== undefined) {
    return cached ? node : undefined;
  }
  const boundary =
    isListItemBlock(node) ||
    node.children.some((child) => listItemBoundary(state, child) !== undefined);
  state.listItemBoundaries.set(node, boundary);
  return boundary ? node : undefined;
};

type ParseListItemContentOptions = {
  $: cheerio.CheerioAPI;
  state: ParserState;
  item: Element;
  marker: string | undefined;
};

/**
 * A list item: its number opens its first text. Text around a nested list or
 * another block is a paragraph of its own, and the nested blocks are read in
 * source order, so a nested list's items count on their own counter.
 */
const parseListItemContent = ({
  $,
  state,
  item,
  marker: initialMarker,
}: ParseListItemContentOptions): string | undefined => {
  let marker = initialMarker;
  const children = item.children;
  if (!children.some((child) => listItemBoundary(state, child) !== undefined)) {
    return parseParagraphElement($, state, $(item), marker)
      ? undefined
      : marker;
  }
  // The item's inline children from `start` up to `end`, read as one
  // paragraph through a detached element holding just those nodes. It does
  // not adopt them (their parent stays the item), and nothing is copied, so
  // reading every run of an item visits each child once.
  let start = 0;
  const readInline = (end: number): void => {
    if (end > start) {
      const segment = new Element(
        item.name,
        item.attribs,
        children.slice(start, end),
      );
      if (parseParagraphElement($, state, $(segment), marker)) {
        marker = undefined;
      }
    }
  };
  for (const [index, node] of children.entries()) {
    const child = listItemBoundary(state, node);
    if (child === undefined) {
      continue;
    }
    readInline(index);
    start = index + 1;
    if (!isListItemBlock(child)) {
      marker = parseListItemContent({ $, state, item: child, marker });
      continue;
    }
    if (marker !== undefined && child.tagName.toLowerCase() === "p") {
      if (parseParagraphElement($, state, $(child), marker)) {
        marker = undefined;
      }
      continue;
    }
    if (marker !== undefined) {
      // The number stands on its own line ahead of the block it opens.
      pushParagraph(
        state,
        marker,
        textInline(marker),
        inferParagraphRole(state, ""),
      );
      marker = undefined;
    }
    parseNode($, state, child);
  }
  readInline(children.length);
  return marker;
};

const parseNode = (
  $: cheerio.CheerioAPI,
  state: ParserState,
  node: AnyNode,
): void => {
  if (isText(node)) {
    const inlines = lineBreaksOf(textInline(node.data));
    const text = normalizeWhitespace(inlinesToPlainText(inlines));
    if (!text) {
      return;
    }

    pushParagraph(state, text, inlines, inferParagraphRole(state, text));
    return;
  }

  if (!isTag(node)) {
    return;
  }

  const $node = $(node);
  const tag = node.tagName.toLowerCase();

  // isTag() also matches <script>/<style>; never emit their raw text.
  if (isExcludedHtmlTag(tag)) {
    return;
  }

  if (tag === "p" || tag === "pre") {
    parseParagraphElement($, state, $node);
    return;
  }

  if (tag === "li") {
    parseListItemContent({
      $,
      state,
      item: node,
      marker: orderedListMarker(state, node),
    });
    return;
  }

  if (/^h[1-6]$/u.test(tag)) {
    const inlines = walkInlines($, $node, state);
    const plainText = normalizeWhitespace(inlinesToPlainText(inlines));
    if (!plainText) {
      return;
    }

    if (handleHeadingText(state, plainText, inlines)) {
      return;
    }

    pushHeading(
      state,
      tag === "h1" || tag === "h2" ? 2 : 3,
      plainText,
      "section-heading",
      inlines,
    );
    return;
  }

  if (tag === "table") {
    parseTableElement($, state, $node);
    return;
  }

  if (state.markup === PL_DECISION_MARKUP.COMMON_COURT && tag === "dt") {
    // The item's marker opens the item's first paragraph, as printed.
    flushPendingMarker(state);
    const marker = walkInlines($, $node, state);
    state.pendingMarker =
      inlinesToPlainText(marker).trim().length > 0 ? marker : undefined;
    return;
  }

  parseChildren($, state, $node);
  if (tag === "dd" || tag === "dl") {
    flushPendingMarker(state);
  }
};

/** A marker no paragraph took, kept as a paragraph of its own. */
const flushPendingMarker = (state: ParserState): void => {
  const marker = state.pendingMarker;
  state.pendingMarker = undefined;
  if (marker === undefined) {
    return;
  }
  const plainText = normalizeWhitespace(inlinesToPlainText(marker));
  pushParagraph(state, plainText, marker, inferParagraphRole(state, plainText));
};

/** Elements a common court's container sets as blocks of their own. */
const COMMON_COURT_BLOCK_TAGS: ReadonlySet<string> = new Set([
  "article",
  "blockquote",
  "center",
  "dd",
  "div",
  "dl",
  "dt",
  "footer",
  "h1",
  "h2",
  "h3",
  "h4",
  "h5",
  "h6",
  "header",
  "li",
  "main",
  "ol",
  "p",
  "pre",
  "section",
  "table",
  "ul",
]);
const COMMON_COURT_BLOCK_SELECTOR = [...COMMON_COURT_BLOCK_TAGS].join(", ");

const commonCourtBlock = (
  $: cheerio.CheerioAPI,
  node: AnyNode,
): Element | undefined =>
  isTag(node) &&
  ((COMMON_COURT_BLOCK_TAGS.has(node.tagName.toLowerCase()) &&
    isHtmlBlock(node)) ||
    $(node).find(COMMON_COURT_BLOCK_SELECTOR).length > 0)
    ? node
    : undefined;

/**
 * A common court's container, read as HTML lays it out: each run of text
 * and inline elements between blocks is one paragraph, its inline marks
 * kept ("art. 353<sup>1</sup> k.c." straight in a cell is one line, not
 * three), and each block is read where it stands.
 */
function parseCommonCourtChildren(
  $: cheerio.CheerioAPI,
  state: ParserState,
  root: cheerio.Cheerio<AnyNode>,
): void {
  let run: AnyNode[] = [];
  const flush = (): void => {
    if (run.length === 0) {
      return;
    }
    const wrapper = $("<span></span>").append($(run).clone());
    run = [];
    parseParagraphElement($, state, wrapper);
  };
  for (const node of root.contents().toArray()) {
    if (commonCourtBlock($, node) !== undefined) {
      flush();
      parseNode($, state, node);
    } else {
      run.push(node);
    }
  }
  flush();
}

function parseChildren(
  $: cheerio.CheerioAPI,
  state: ParserState,
  root: cheerio.Cheerio<AnyNode>,
): void {
  if (state.markup === PL_DECISION_MARKUP.COMMON_COURT) {
    parseCommonCourtChildren($, state, root);
    return;
  }
  root.contents().each((_, node) => {
    parseNode($, state, node);
  });
}

const plainTextParagraphsToInlines = (text: string): Inline[] => {
  const lines = text.split("\n");
  const inlines: Inline[] = [];

  for (let index = 0; index < lines.length; index += 1) {
    const line = lines[index]?.trim();
    if (!line) {
      continue;
    }

    appendTextInline(inlines, line);
    if (index < lines.length - 1) {
      inlines.push({ type: "line-break" });
    }
  }

  return inlines;
};

const parsePlainText = (state: ParserState, content: string): void => {
  const paragraphs = content.split(/\n{2,}/u).flatMap((paragraph) => {
    const normalized = normalizeWhitespace(paragraph);
    return normalized ? [normalized] : [];
  });

  for (const paragraph of paragraphs) {
    const inlines = plainTextParagraphsToInlines(paragraph);

    if (handleHeadingText(state, paragraph, inlines)) {
      continue;
    }

    const role = inferParagraphRole(state, paragraph);
    if (role === "holding") {
      state.section = "holding";
    }

    pushParagraph(state, paragraph, inlines, role);
  }
};

/** Elements whose opening SAOS's serializer never marks: blocks. */
const SERIALIZER_BLOCK_TAGS: ReadonlySet<string> = new Set([
  ...COMMON_COURT_BLOCK_TAGS,
  "body",
  "html",
  "td",
  "th",
  "tr",
]);

/**
 * Remove the newline SAOS's serializer opens every inline element with.
 *
 * SAOS writes `<em>\n<!-- -->ex tunc</em>`: a newline, then an empty
 * comment, then the element's own text. Read as text, the newline splits a
 * word marked in part ("Biura<u>\n<!-- -->mi</u>" is "Biurami") and sets a
 * space inside every superscript. Whatever the court wrote follows the
 * comment, so only that exact opening is removed: a lone newline as the
 * first child of an inline element, directly before an empty comment.
 * Whitespace anywhere else before a comment ("<b>Sąd</b> <!-- --><b>…") is
 * the court's.
 */
const dropSerializerNewlines = ($: cheerio.CheerioAPI): void => {
  const furniture: AnyNode[] = [];
  // A stack, not recursion: court HTML can nest deeper than the call stack.
  const pending: AnyNode[] = $.root().toArray();
  for (let node = pending.pop(); node !== undefined; node = pending.pop()) {
    if (hasChildren(node)) {
      pending.push(...node.children);
      continue;
    }
    const previous = node.prev;
    if (
      isComment(node) &&
      node.data.trim().length === 0 &&
      previous !== null &&
      isText(previous) &&
      previous.data === "\n" &&
      previous.prev === null &&
      previous.parent !== null &&
      isTag(previous.parent) &&
      !SERIALIZER_BLOCK_TAGS.has(previous.parent.tagName.toLowerCase())
    ) {
      furniture.push(previous);
    }
  }
  $(furniture).remove();
};

const enforcePlainTextExpansionBudget = (
  content: string,
  budget: NonNullable<ParsePlDecisionInput["htmlExpansionBudget"]> | undefined,
): void => {
  if (budget === undefined) {
    return;
  }

  // Every line break, CRLF included, can become a line string in
  // normalization and a paragraph after the split, so lines bound both.
  let lines = 0;
  for (let index = 0; index < content.length; index += 1) {
    if (content.codePointAt(index) !== 10) {
      continue;
    }
    lines += 1;
    if (lines > budget.maxDomAllocations) {
      budget.reject("KIO plaintext exceeds DOM allocation budget");
    }
  }
};

export const parsePlDecisionContent = (
  input: ParsePlDecisionInput,
): ParsePlDecisionOutput => {
  const loadHtml = input.loadHtml ?? load;
  const state = createState(input.superscripts === true, input.markup);
  const title = normalizeDecisionTitle(input.decisionType);

  if (title) {
    pushHeading(state, 1, title, "decision-title", textInline(title));
    state.sawDecisionTitle = true;
    state.decisionTitle = title;
    if (title === POLISH_DECISION_TITLE_MAP.uzasadnienie) {
      state.section = "reasoning";
    }
  }

  if (hasHtmlTags(input.content)) {
    const $ = loadHtml(input.content);
    const root = $("body").length > 0 ? $("body") : $.root();
    if (state.markup === PL_DECISION_MARKUP.COMMON_COURT) {
      // Before the whitespace is rendered: the serializer's newline is not
      // whitespace the document has, and rendering would make it a space.
      dropSerializerNewlines($);
    }
    const parsed = $.root().get(0);
    if (parsed !== undefined) {
      renderHtmlWhiteSpace(parsed);
    }
    parseChildren($, state, root);
    validateAndLog(
      { parser: "pl-courts", caseNumber: input.caseNumber },
      input.content,
      state.blocks,
      { document: $ },
    );
  } else {
    enforcePlainTextExpansionBudget(input.content, input.htmlExpansionBudget);
    const normalizedContent = normalizeLegacyPlainText(
      stripHtml(input.content),
    );
    const paragraphs = normalizedContent
      .split(/\n{2,}/u)
      .flatMap((paragraph) => {
        const normalized = normalizeWhitespace(paragraph);
        return normalized ? [normalized] : [];
      });
    const validationHtml = buildValidationHtml(paragraphs);
    // Check expansion before allocating paragraph ASTs for bounded sources.
    const sourceDocument = input.loadHtml?.(validationHtml);
    parsePlainText(state, normalizedContent);
    validateAndLog(
      { parser: "pl-courts", caseNumber: input.caseNumber },
      validationHtml,
      state.blocks,
      sourceDocument === undefined ? {} : { document: sourceDocument },
    );
  }

  const fulltext = state.blocks
    .flatMap((block) => (block.plainText ? [block.plainText] : []))
    .join("\n\n");

  const documentAst: DocumentAst = {
    version: 1,
    source: {
      system: input.sourceSystem ?? "saos.org.pl",
      documentId: input.documentId,
      webUrl: input.sourceUrl ?? "",
      printUrl: input.documentUrl ?? "",
    },
    metadata: {
      caseNumber: input.caseNumber,
      ecli: input.ecli ?? null,
      court: input.court,
      decisionDate: input.decisionDate ?? null,
      decisionType: input.decisionType ?? null,
      keywords: input.keywords,
      statutes: input.statutes,
    },
    blocks: state.blocks,
  };

  return {
    documentAst,
    fulltext,
  };
};
