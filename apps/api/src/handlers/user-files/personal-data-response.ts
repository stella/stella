import type { userFiles } from "@/api/db/schema";
import type {
  UnbackedProjectionKeys,
  UnprojectedColumns,
} from "@/api/lib/projection-totality";

// Storage keys and scan metadata remain internal. The archive path is derived
// from the persisted UUID, never from an uploaded filename.
export const toPersonalUserFileResponse = (
  row: typeof userFiles.$inferSelect,
) => ({
  id: row.id,
  threadId: row.threadId,
  fileName: row.fileName,
  mimeType: row.mimeType,
  sizeBytes: row.sizeBytes,
  archivePath: `files/${row.id}`,
  createdAt: row.createdAt.toISOString(),
});

type PersonalUserFileResponse = ReturnType<typeof toPersonalUserFileResponse>;
// `archivePath` locates the file bytes in the archive; it is derived from `id`.
type UserFileExportRow = typeof userFiles.$inferSelect &
  Pick<PersonalUserFileResponse, "archivePath">;

// Columns intentionally left out of the account export.
const UNEXPORTED_USER_FILE_COLUMNS = [
  // The exporting account itself; every exported file is its own.
  "userId",
  // Object-storage key: internal infrastructure, replaced by `archivePath`.
  "s3Key",
  // Internal dedupe hash of the bytes, which the archive carries in full.
  "sha256Hex",
  // Derived preview assets generated by the system, not uploaded data.
  "thumbnailFileId",
  "placeholder",
  // Malware-scanner metadata.
  "scanWarnings",
  // Machine-extracted text of the file, whose bytes the archive carries.
  "extractedText",
  // Moves only on those internal derivations; the upload is immutable.
  "updatedAt",
] as const satisfies readonly (keyof UserFileExportRow)[];

// Totality guard, bidirectional: every schema column must be exported or
// explicitly excused above, and the export cannot carry a field that traces
// back to no real column.
type MissingExportedUserFileColumn = UnprojectedColumns<
  UserFileExportRow,
  PersonalUserFileResponse,
  (typeof UNEXPORTED_USER_FILE_COLUMNS)[number]
>;
type UnexpectedExportedUserFileColumn = UnbackedProjectionKeys<
  UserFileExportRow,
  PersonalUserFileResponse,
  (typeof UNEXPORTED_USER_FILE_COLUMNS)[number]
>;

true satisfies MissingExportedUserFileColumn extends never ? true : never;
true satisfies UnexpectedExportedUserFileColumn extends never ? true : never;
