/**
 * Total over the languages that have one, so a new corpus language has to
 * author a list rather than silently inherit no exclusions.
 */
export const FUNCTION_WORDS = {
  cs: new Set<string>(CZECH_FUNCTION_WORDS),
  de: new Set<string>(GERMAN_FUNCTION_WORDS),
  en: new Set<string>(ENGLISH_FUNCTION_WORDS),
  hu: new Set<string>(HUNGARIAN_FUNCTION_WORDS),
  pl: new Set<string>(POLISH_FUNCTION_WORDS),
  sk: new Set<string>(SLOVAK_FUNCTION_WORDS),
} as const satisfies Record<FunctionWordLanguage, ReadonlySet<string>>;

/**
 * The comparison key a token is looked up by: NFC, lower-cased, accents
 * kept. The one place the rule lives, so the lists and the lookup cannot
 * disagree about what "the same word" means.
 */
export const functionWordKey = (token: string): string =>
  token.normalize("NFC").toLowerCase();

/**
 * Whether a list is authored for this language. Asked of the map itself
 * rather than of {@link FUNCTION_WORD_LANGUAGES}, so the narrowing is the
 * same fact as the lookup below succeeding.
 */
const isFunctionWordLanguage = (
  language: MorphologyLanguage,
): language is FunctionWordLanguage => Object.hasOwn(FUNCTION_WORDS, language);

/**
 * The function words to drop from a query in this language, or null where
 * nothing is dropped: a language the corpus does not serve, or a request
 * whose scope names no language at all (an unscoped search spans every
 * jurisdiction of a generation, so no one language describes its text).
 */
export const functionWordsFor = (
  language: MorphologyLanguage | null,
): ReadonlySet<string> | null => {
  if (language === null || !isFunctionWordLanguage(language)) {
    return null;
  }
  return FUNCTION_WORDS[language];
};
