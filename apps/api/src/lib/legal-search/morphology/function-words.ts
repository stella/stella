/**
 * Function words per corpus language: the words a reader's question is built
 * out of rather than the words it is about.
 *
 * Why this exists. Every token of a free-text query is AND-ed, so a
 * nine-word question like "jak velký musí být dluh na nájemném pro výpověď z
 * nájmu" asks the engine for decisions carrying all nine, and no judgment is
 * written the way a question is asked. The content words are in the corpus;
 * "jak", "musí", "být", "pro" and "na" are what empty the result set. So the
 * query builder keeps the content words required and drops these.
 *
 * Dropped entirely, not kept as an optional alternative. The clause this
 * builder emits is a conjunction of required terms, so a word is either
 * required or absent from it. Absent costs the ranking almost nothing: these
 * are the highest-frequency words in the corpus, so their contribution to a
 * relevance score is near zero either way.
 *
 * ## Lower-cased and NFC, accents kept — deliberately not ASCII-folded
 *
 * The index folds accents (`FOLDED_TOKENIZER`), and matching these lists the
 * same way would be the obvious choice. It is wrong here: Czech "být" (to
 * be) and "byt" (a flat) fold to the same token, and so do Slovak "byť" and
 * "byt". A flat is the subject of most tenancy disputes in the corpus, so a
 * folded list drops a content word from every query about one. Matching with
 * accents kept drops only what the reader unambiguously wrote as a function
 * word; a reader who types no diacritics keeps a word the clause then
 * requires, which is the pre-existing behaviour and never worse than losing
 * the noun. `function-words.test.ts` pins the collision so the rule cannot
 * be "simplified" back to folding.
 *
 * ## Polarity words are never function words
 *
 * A word whose removal can make the query match decisions asserting the
 * OPPOSITE proposition stays required, however grammatical it looks. So the
 * negations ("ne", "není", "nie", "nicht", "not") and the privatives ("bez",
 * "kromě", "ohne", "without") are deliberately absent from every list below:
 * "smlouva je neplatná bez podpisu" read without "bez" is a claim about
 * contracts WITH a signature, and a reader researching one proposition must
 * never be handed the other. Loosening a query is the point of this module;
 * inverting one is a different thing entirely, and `function-words.test.ts`
 * holds the class out of every language.
 *
 * ## Coverage, not discrimination
 *
 * Words shared by Czech and Slovak appear in both lists. This is the
 * opposite of `LANGUAGE_STOPWORDS` in `lib/templates/template-languages.ts`,
 * whose sets are deliberately pairwise disjoint because it detects which
 * language a document is written in; that list must not be reused here, and
 * this one must not be reused there.
 */

import { CORPUS_MORPHOLOGY_LANGUAGES } from "@/api/lib/legal-search/morphology/corpus-language";
import type { MorphologyLanguage } from "@/api/lib/legal-search/morphology/stem";

/**
 * Languages whose function words a query may drop: every language the
 * corpus's own jurisdictions are written in, plus English, each once.
 *
 * English is listed explicitly as well because the multi-language EU index
 * spans 24 languages under one jurisdiction, so it has no jurisdiction
 * language, and its queries stem — and drop function words — only under the
 * language a request names.
 *
 * Derived from the jurisdiction set rather than hand-listed, so a new
 * single-language corpus cannot land without a list: {@link FUNCTION_WORDS}
 * is total over this union and fails to compile until one is authored.
 */
export const FUNCTION_WORD_LANGUAGES = [
  ...new Set([...CORPUS_MORPHOLOGY_LANGUAGES, "en" as const]),
] satisfies readonly MorphologyLanguage[];

export type FunctionWordLanguage = (typeof FUNCTION_WORD_LANGUAGES)[number];

