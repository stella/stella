const DECLARED_CLASSES = new Map(Object.entries(ROUTE_LATENCY_CLASSES));

type RouteLatencyClassInput = { method: string; route: string };

const routeLatencyClass = ({
  method,
  route,
}: RouteLatencyClassInput): RequestClass => {
  // Unmatched requests have no registered handler to classify.
  if (route === "unmatched") {
    return "crud";
  }
  // The census test pins this table to every route the API registers, so a
  // served route always has a declaration. Only a sub-application mounted on
  // its own (handler tests) reaches the fallback; failing the request over a
  // metric label would turn a telemetry gap into an outage.
  return (
    DECLARED_CLASSES.get(`${method} ${route}`) ??
    DECLARED_CLASSES.get(`ALL ${route}`) ??
    "crud"
  );
};

/** A model call moves a completed request into the AI latency series. */
export const requestClassAtCompletion = (
  input: RouteLatencyClassInput,
): RequestClass => {
  const declared = routeLatencyClass(input);
  return isAiRequest() ? "ai" : declared;
};
