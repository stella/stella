import {
  composedMetadataUrlSchema,
  METADATA_URL_SCHEMAS,
} from "@/api/handlers/case-law/ingestion/metadata-url-schemas";

/** Render a new migration when a source declares another URL-bearing leaf. */
export const plainTextSourceUrlContractSql = () => {
  const contracts = Object.fromEntries(
    Object.entries(METADATA_URL_SCHEMAS).map(([adapter, schema]) => [
      adapter,
      { base: schema ?? {}, composed: composedMetadataUrlSchema(schema) },
    ]),
  );
  return `-- requires: 20261027160100_uk_fcl_metadata_url_contract
SET lock_timeout = '5s';
SET statement_timeout = '30s';

-- Generated by scripts/generate-plain-text-url-contract.ts from the source schemas.
-- Source identity selects the contract; only declared string URL leaves are exempt.
-- Replacing this function changes no table, trigger or stored row.
CREATE OR REPLACE FUNCTION plain_text_source_url_schema(source uuid, composed boolean DEFAULT false) RETURNS jsonb
LANGUAGE sql STABLE
SET search_path FROM CURRENT
RETURN COALESCE(
  ($url_schemas$${JSON.stringify(contracts, null, 2)}$url_schemas$::jsonb ->
    (SELECT adapter_key FROM case_law_sources WHERE id = source) ->
    CASE WHEN composed THEN 'composed' ELSE 'base' END),
  '{}'::jsonb
);
`;
};

if (import.meta.main) {
  process.stdout.write(plainTextSourceUrlContractSql());
}
