import { getColumns, isTable } from "drizzle-orm";

import { compareCodeUnit } from "@stll/collation";

import {
  formattedLikeRepository,
  writeOrCheckArtifacts,
} from "../../../scripts/generated-artifacts";
import * as agentAuthSchema from "../src/db/agent-auth-schema";
import * as authSchema from "../src/db/auth-schema";
import * as schema from "../src/db/schema";

/** Inspect the real Drizzle columns, including suffixed lifecycle names. */
export const statusColumns = (exports: Readonly<Record<string, unknown>>) => {
  const inventory = new Map<string, string[]>();
  for (const [name, table] of Object.entries(exports).toSorted(([a], [b]) =>
    compareCodeUnit(a, b),
  )) {
    if (!isTable(table)) {
      continue;
    }
    const columns = Object.keys(getColumns(table))
      .filter((column) => /(?:status|state|phase)$/iu.test(column))
      .toSorted();
    if (columns.length > 0) {
      inventory.set(name, columns);
    }
  }
  return Object.fromEntries(inventory);
};

if (import.meta.main) {
  const contents = await formattedLikeRepository(
    `// GENERATED by apps/api/scripts/generate-status-tables.ts. Do not edit.\n\nexport const STATUS_COLUMNS = ${JSON.stringify(statusColumns({ ...schema, ...authSchema, ...agentAuthSchema }))} as const;\n\nexport type StatusTable = keyof typeof STATUS_COLUMNS;\n`,
    "ts",
  );
  process.exitCode = await writeOrCheckArtifacts(
    [
      {
        path: new URL("../src/lib/db/status-tables.gen.ts", import.meta.url)
          .pathname,
        contents,
      },
    ],
    {
      write: process.argv.includes("--write"),
      matched: "the Drizzle status columns",
    },
  );
}
