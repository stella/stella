import { panic } from "better-result";
import { getColumns, getTableName, isTable, isView } from "drizzle-orm";

import { compareCodeUnit } from "@stll/collation";

import {
  formattedLikeRepository,
  writeOrCheckArtifacts,
} from "../../../scripts/generated-artifacts";
import * as agentAuthSchema from "../src/db/agent-auth-schema";
import * as authSchema from "../src/db/auth-schema";
import * as schema from "../src/db/schema";
import {
  ENUM_COLUMN_ROLE,
  ENUM_COLUMN_ROLES,
} from "../src/lib/db/enum-column-roles";
import type { EnumColumnRole } from "../src/lib/db/enum-column-roles";

type EnumColumnRoleMap = Readonly<
  Record<string, Readonly<Record<string, EnumColumnRole>>>
>;

const LIFECYCLE_NAME = /(?:status|state|phase)$/iu;

const enumValuesOf = (column: unknown): readonly unknown[] =>
  typeof column === "object" &&
  column !== null &&
  "enumValues" in column &&
  Array.isArray(column.enumValues)
    ? column.enumValues
    : [];

const sqlNameOf = (column: unknown): string | undefined =>
  typeof column === "object" &&
  column !== null &&
  "name" in column &&
  typeof column.name === "string"
    ? column.name
    : undefined;

/**
 * Inspect lifecycle columns on all relations and separately on writable
 * tables. A lifecycle column is named like one, or is an enum-valued column
 * the role map classifies as one; every other enum-valued table column must
 * be classified too, so a lifecycle cannot hide behind its name.
 */
export const statusColumnMaps = (
  exports: Readonly<Record<string, unknown>>,
  roles: EnumColumnRoleMap,
) => {
  const inventory = new Map<string, string[]>();
  const writable = new Map<string, string[]>();
  const enumColumns = new Map<string, string[]>();
  const inventoryRelation = ({
    name,
    relation,
    columns,
  }: {
    name: string;
    relation: unknown;
    columns: readonly string[];
  }) => {
    if (columns.length === 0) {
      return;
    }
    const sorted = columns.toSorted();
    inventory.set(name, sorted);
    if (isTable(relation)) {
      writable.set(name, sorted);
    }
  };
  for (const [name, relation] of Object.entries(exports).toSorted(([a], [b]) =>
    compareCodeUnit(a, b),
  )) {
    if (!isTable(relation) && !isView(relation)) {
      continue;
    }
    const relationColumns = getColumns(relation);
    const keys = Object.keys(relationColumns);
    const named = keys.filter((column) => LIFECYCLE_NAME.test(column));
    const unnamedEnums = keys.filter(
      (column) =>
        !LIFECYCLE_NAME.test(column) &&
        enumValuesOf(relationColumns[column]).length > 1,
    );
    if (!isTable(relation) || unnamedEnums.length === 0) {
      inventoryRelation({ name, relation, columns: named });
      continue;
    }
    // Roles name schema columns as SQL does: the census enumerates them, it
    // does not read them, so code scanners never mistake it for a use.
    const tableName = getTableName(relation);
    const sqlName = (column: string) =>
      sqlNameOf(relationColumns[column]) ??
      panic(`Column ${name}.${column} has no SQL name`);
    const classified = unnamedEnums.filter((column) => {
      const role =
        roles[tableName]?.[sqlName(column)] ??
        panic(
          `Classify ${tableName}.${sqlName(column)} in apps/api/src/lib/db/enum-column-roles.ts as a lifecycle or an attribute`,
        );
      return role === ENUM_COLUMN_ROLE.lifecycle;
    });
    enumColumns.set(tableName, unnamedEnums.map(sqlName).toSorted());
    inventoryRelation({ name, relation, columns: [...named, ...classified] });
  }
  return {
    statusColumns: Object.fromEntries(inventory),
    writableStatusColumns: Object.fromEntries(writable),
    enumColumns: Object.fromEntries(enumColumns),
  };
};

if (import.meta.main) {
  const { statusColumns, writableStatusColumns, enumColumns } =
    statusColumnMaps(
      { ...schema, ...authSchema, ...agentAuthSchema },
      ENUM_COLUMN_ROLES,
    );
  const contents = await formattedLikeRepository(
    `// GENERATED by apps/api/scripts/generate-status-tables.ts. Do not edit.\n\nexport const STATUS_COLUMNS = ${JSON.stringify(statusColumns)} as const;\n\nexport const WRITABLE_STATUS_COLUMNS = ${JSON.stringify(writableStatusColumns)} as const;\n\nexport type StatusTable = keyof typeof WRITABLE_STATUS_COLUMNS;\n\nexport const ENUM_COLUMNS = ${JSON.stringify(enumColumns)} as const;\n`,
    "ts",
  );
  process.exitCode = await writeOrCheckArtifacts(
    [
      {
        path: new URL("../src/lib/db/status-tables.gen.ts", import.meta.url)
          .pathname,
        contents,
      },
    ],
    {
      write: process.argv.includes("--write"),
      matched: "the Drizzle status columns",
    },
  );
}
