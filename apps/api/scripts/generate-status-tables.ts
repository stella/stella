import { getColumns, isTable, isView } from "drizzle-orm";

import { compareCodeUnit } from "@stll/collation";

import {
  formattedLikeRepository,
  writeOrCheckArtifacts,
} from "../../../scripts/generated-artifacts";
import * as agentAuthSchema from "../src/db/agent-auth-schema";
import * as authSchema from "../src/db/auth-schema";
import * as schema from "../src/db/schema";

/** Inspect lifecycle columns on all relations and separately on writable tables. */
export const statusColumnMaps = (
  exports: Readonly<Record<string, unknown>>,
) => {
  const inventory = new Map<string, string[]>();
  const writable = new Map<string, string[]>();
  for (const [name, relation] of Object.entries(exports).toSorted(([a], [b]) =>
    compareCodeUnit(a, b),
  )) {
    if (!isTable(relation) && !isView(relation)) {
      continue;
    }
    const columns = Object.keys(getColumns(relation))
      .filter((column) => /(?:status|state|phase)$/iu.test(column))
      .toSorted();
    if (columns.length === 0) {
      continue;
    }
    inventory.set(name, columns);
    if (isTable(relation)) {
      writable.set(name, columns);
    }
  }
  return {
    statusColumns: Object.fromEntries(inventory),
    writableStatusColumns: Object.fromEntries(writable),
  };
};

if (import.meta.main) {
  const { statusColumns, writableStatusColumns } = statusColumnMaps({
    ...schema,
    ...authSchema,
    ...agentAuthSchema,
  });
  const contents = await formattedLikeRepository(
    `// GENERATED by apps/api/scripts/generate-status-tables.ts. Do not edit.\n\nexport const STATUS_COLUMNS = ${JSON.stringify(statusColumns)} as const;\n\nexport const WRITABLE_STATUS_COLUMNS = ${JSON.stringify(writableStatusColumns)} as const;\n\nexport type StatusTable = keyof typeof WRITABLE_STATUS_COLUMNS;\n`,
    "ts",
  );
  process.exitCode = await writeOrCheckArtifacts(
    [
      {
        path: new URL("../src/lib/db/status-tables.gen.ts", import.meta.url)
          .pathname,
        contents,
      },
    ],
    {
      write: process.argv.includes("--write"),
      matched: "the Drizzle status columns",
    },
  );
}
