// Embed committed shards in Bun bundles; no filesystem reads remain in the API.
import { panic } from "better-result";
import { mkdir, rm, writeFile } from "node:fs/promises";

import { readRuntimeMode } from "@stll/runtime-mode";

import { readCapabilityCatalog } from "../../../packages/cli/src/capability-catalog-data";
import { CAPABILITY_RUNTIME_INPUTS } from "../../../packages/scripts/src/generated-files";
import { withGeneratedOutputCache } from "../../../packages/scripts/src/generated-output-cache";
import { hasPreparedGeneratedSources } from "../../../packages/scripts/src/prepared-generated-sources";
import { serializeDispatchModule } from "./lib/capability-catalog";

export const generateCapabilityRuntime = async (
  root = new URL("../../../", import.meta.url),
): Promise<void> => {
  const directory = new URL("apps/api/src/mcp/generated/", root);
  const entries = readCapabilityCatalog(
    new URL("packages/cli/capabilities/", root),
  );
  await mkdir(new URL("capability-dispatch/", directory), { recursive: true });
  const ids = [];
  for (const entry of entries) {
    if (
      typeof entry !== "object" ||
      entry === null ||
      !("id" in entry) ||
      typeof entry.id !== "string"
    ) {
      panic("Capability runtime requires a catalog entry id");
    }
    const handler = "handler" in entry ? entry.handler : undefined;
    if (
      typeof handler !== "object" ||
      handler === null ||
      !("importPath" in handler) ||
      typeof handler.importPath !== "string"
    ) {
      panic(`Capability ${entry.id} has no handler import`);
    }
    const exportName = "exportName" in handler ? handler.exportName : undefined;
    if (exportName !== undefined && typeof exportName !== "string") {
      panic(`Capability ${entry.id} has invalid handler export`);
    }
    const featureAccess =
      "featureAccess" in entry ? entry.featureAccess : undefined;
    const featureId = "featureId" in entry ? entry.featureId : undefined;
    if (
      featureAccess !== undefined &&
      ((featureAccess !== "required" && featureAccess !== "conditional") ||
        typeof featureId !== "string")
    ) {
      panic(`Capability ${entry.id} has invalid feature access`);
    }
    const contents = serializeDispatchModule([
      {
        id: entry.id,
        importPath: handler.importPath,
        exportName,
        featureAccess:
          (featureAccess === "required" || featureAccess === "conditional") &&
          typeof featureId === "string"
            ? { type: featureAccess, featureId }
            : undefined,
      },
    ]);
    await writeFile(
      new URL(`capability-dispatch/${entry.id}.ts`, directory),
      contents,
    );
    ids.push(entry.id);
  }
  for (const file of new Bun.Glob("*.ts").scanSync({
    cwd: new URL("capability-dispatch/", directory).pathname,
  })) {
    if (!ids.includes(file.slice(0, -3))) {
      await rm(new URL(`capability-dispatch/${file}`, directory));
    }
  }
  const header =
    "// GENERATED by apps/api/scripts/generate-capability-runtime.ts. Do not edit.\n";
  const catalogImports = ids
    .map(
      (id, index) =>
        `import capability${index} from ${JSON.stringify(`../../../../../packages/cli/capabilities/${id}.json`)};`,
    )
    .join("\n");
  await writeFile(
    new URL("capability-catalog.ts", directory),
    `${header}${catalogImports}\n\nexport default [${ids.map((_id, index) => `(({ handler: _handler, ...capability }) => capability)(capability${index})`).join(",")}];\n`,
  );
  const features = entries.flatMap((entry) => {
    if (
      typeof entry !== "object" ||
      entry === null ||
      !("id" in entry) ||
      typeof entry.id !== "string"
    ) {
      return panic("Capability feature bindings require a catalog entry id");
    }
    if (!("featureId" in entry)) {
      return [];
    }
    if (typeof entry.featureId !== "string") {
      return panic("Capability feature bindings require a string feature id");
    }
    return [[entry.id, entry.featureId]];
  });
  // Emit the repository formatter's shape (one entry per line) directly: the
  // API image builds this file without the repository's scripts.
  const bindingEntries = features
    .map(
      ([id, featureId]) =>
        `  [${JSON.stringify(id)}, ${JSON.stringify(featureId)}],\n`,
    )
    .join("");
  await writeFile(
    new URL("capability-feature-bindings.ts", directory),
    `${header}export const CAPABILITY_FEATURE_BINDINGS = new Map<string, string>(${features.length === 0 ? "" : `[\n${bindingEntries}]`});\n`,
  );
  const dispatchImports = ids
    .map(
      (id, index) =>
        `import { CAPABILITY_DISPATCH as dispatch${index} } from ${JSON.stringify(`./capability-dispatch/${id}`)};`,
    )
    .join("\n");
  await writeFile(
    new URL("capability-dispatch.ts", directory),
    `${header}${dispatchImports}\n\nexport type CapabilityDispatchEntry = { load: () => Promise<Record<string, unknown>>; exportName?: string; featureId?: string; featureAccess?: "required" | "conditional" };\nexport const CAPABILITY_DISPATCH = {${ids.map((_id, index) => `...dispatch${index}`).join(",")}} as const satisfies Record<string, CapabilityDispatchEntry>;\n`,
  );
};

if (
  import.meta.main &&
  !hasPreparedGeneratedSources(new URL("../../../", import.meta.url).pathname)
) {
  const root = new URL("../../../", import.meta.url).pathname;
  await withGeneratedOutputCache({
    root,
    name: "capability-runtime",
    environment: readRuntimeMode().nodeEnv,
    inputs: CAPABILITY_RUNTIME_INPUTS,
    outputs: ["apps/api/src/mcp/generated/**/*.ts"],
    generate: generateCapabilityRuntime,
  });
}
