// Embed committed shards in Bun bundles; no filesystem reads remain in the API.
import { panic } from "better-result";
import { readdirSync } from "node:fs";
import { writeFile } from "node:fs/promises";

import { readCapabilityCatalog } from "../../../packages/cli/src/capability-catalog-data";
import { hasPreparedGeneratedSources } from "../../../packages/scripts/src/prepared-generated-sources";

export const generateCapabilityRuntime = async (
  root = new URL("../../../", import.meta.url),
): Promise<void> => {
  const directory = new URL("apps/api/src/mcp/generated/", root);
  const entries = readCapabilityCatalog(
    new URL("packages/cli/capabilities/", root),
  );
  const ids = entries.map((entry) => {
    if (
      typeof entry !== "object" ||
      entry === null ||
      !("id" in entry) ||
      typeof entry.id !== "string"
    ) {
      return panic("Capability runtime requires a catalog entry id");
    }
    return entry.id;
  });
  const dispatchFiles = readdirSync(
    new URL("capability-dispatch/", directory),
  ).toSorted();
  if (
    JSON.stringify(dispatchFiles) !==
    JSON.stringify(ids.map((id) => `${id}.ts`).toSorted())
  ) {
    panic(
      "Capability catalog and dispatch shards differ; regenerate the capability catalog",
    );
  }
  const header =
    "// GENERATED by apps/api/scripts/generate-capability-runtime.ts. Do not edit.\n";
  const catalogImports = ids
    .map(
      (id, index) =>
        `import capability${index} from ${JSON.stringify(`../../../../../packages/cli/capabilities/${id}.json`)};`,
    )
    .join("\n");
  await writeFile(
    new URL("capability-catalog.ts", directory),
    `${header}${catalogImports}\n\nexport default [${ids.map((_id, index) => `capability${index}`).join(",")}];\n`,
  );
  const features = entries.flatMap((entry) => {
    if (
      typeof entry !== "object" ||
      entry === null ||
      !("id" in entry) ||
      typeof entry.id !== "string"
    ) {
      return panic("Capability feature bindings require a catalog entry id");
    }
    if (!("featureId" in entry)) {
      return [];
    }
    if (typeof entry.featureId !== "string") {
      return panic("Capability feature bindings require a string feature id");
    }
    return [[entry.id, entry.featureId]];
  });
  await writeFile(
    new URL("capability-feature-bindings.ts", directory),
    `${header}export const CAPABILITY_FEATURE_BINDINGS = new Map<string, string>(${features.length === 0 ? "" : JSON.stringify(features)});\n`,
  );
  const dispatchImports = ids
    .map(
      (id, index) =>
        `import { CAPABILITY_DISPATCH as dispatch${index} } from ${JSON.stringify(`./capability-dispatch/${id}`)};`,
    )
    .join("\n");
  await writeFile(
    new URL("capability-dispatch.ts", directory),
    `${header}${dispatchImports}\n\nexport type CapabilityDispatchEntry = { load: () => Promise<Record<string, unknown>>; exportName?: string; featureId?: string; featureAccess?: "required" | "conditional" };\nexport const CAPABILITY_DISPATCH = {${ids.map((_id, index) => `...dispatch${index}`).join(",")}} as const satisfies Record<string, CapabilityDispatchEntry>;\n`,
  );
};

if (
  import.meta.main &&
  !hasPreparedGeneratedSources(new URL("../../../", import.meta.url).pathname)
) {
  await generateCapabilityRuntime();
}
