// Embed freshly derived contract data; only the npm package consumes shards.
import { panic } from "better-result";
import { mkdir, rm, writeFile } from "node:fs/promises";

import { serializeDispatchModule } from "./capability-catalog";
import { buildCapabilityHandlerIndex } from "./capability-handler-index";
import { serializeCapabilityJson } from "./capability-shards";

export const writeCapabilityRuntime = async (
  entries: readonly unknown[],
  root = new URL("../../../../", import.meta.url),
): Promise<void> => {
  const directory = new URL("apps/api/src/mcp/generated/", root);
  const ids = entries.map((entry) => {
    if (
      typeof entry !== "object" ||
      entry === null ||
      !("id" in entry) ||
      typeof entry.id !== "string"
    ) {
      panic("Capability runtime requires a catalog entry id");
    }
    return entry.id;
  });
  const handlers = await buildCapabilityHandlerIndex(root.pathname, ids);
  await mkdir(new URL("capability-dispatch/", directory), { recursive: true });
  for (const entry of entries) {
    if (
      typeof entry !== "object" ||
      entry === null ||
      !("id" in entry) ||
      typeof entry.id !== "string"
    ) {
      panic("Capability runtime requires a catalog entry id");
    }
    const handler =
      handlers.get(entry.id) ??
      panic(`Capability ${entry.id} has no handler source export`);
    const { exportName } = handler;
    const featureAccess =
      "featureAccess" in entry ? entry.featureAccess : undefined;
    const featureId = "featureId" in entry ? entry.featureId : undefined;
    if (
      featureAccess !== undefined &&
      ((featureAccess !== "required" && featureAccess !== "conditional") ||
        typeof featureId !== "string")
    ) {
      panic(`Capability ${entry.id} has invalid feature access`);
    }
    const contents = serializeDispatchModule([
      {
        id: entry.id,
        importPath: handler.importPath,
        exportName,
        featureAccess:
          (featureAccess === "required" || featureAccess === "conditional") &&
          typeof featureId === "string"
            ? { type: featureAccess, featureId }
            : undefined,
      },
    ]);
    await writeFile(
      new URL(`capability-dispatch/${entry.id}.ts`, directory),
      contents,
    );
  }
  for (const file of new Bun.Glob("*.ts").scanSync({
    cwd: new URL("capability-dispatch/", directory).pathname,
  })) {
    if (!ids.includes(file.slice(0, -3))) {
      await rm(new URL(`capability-dispatch/${file}`, directory));
    }
  }
  await writeCapabilityCatalogRuntime(entries, root);
  const dispatchImports = ids
    .map(
      (id, index) =>
        `import { CAPABILITY_DISPATCH as dispatch${index} } from ${JSON.stringify(`./capability-dispatch/${id}`)};`,
    )
    .join("\n");
  await writeFile(
    new URL("capability-dispatch.ts", directory),
    `// GENERATED by apps/api/scripts/generate-capability-runtime.ts. Do not edit.\n${dispatchImports}\n\nexport type CapabilityDispatchEntry = { load: () => Promise<Record<string, unknown>>; exportName?: string; featureId?: string; featureAccess?: "required" | "conditional" };\nexport const CAPABILITY_DISPATCH = {${ids.map((_id, index) => `...dispatch${index}`).join(",")}} as const satisfies Record<string, CapabilityDispatchEntry>;\n`,
  );
};

export const writeCapabilityCatalogRuntime = async (
  entries: readonly unknown[],
  root = new URL("../../../../", import.meta.url),
): Promise<void> => {
  const directory = new URL("apps/api/src/mcp/generated/", root);
  await mkdir(directory, { recursive: true });
  const header =
    "// GENERATED by apps/api/scripts/generate-capability-runtime.ts. Do not edit.\n";
  await writeFile(
    new URL("capability-catalog.ts", directory),
    `${header}const catalog: readonly { readonly id: string; readonly [key: string]: unknown }[] = ${serializeCapabilityJson(entries)};\nexport default catalog;\n`,
  );
  const features = entries.flatMap((entry) => {
    if (
      typeof entry !== "object" ||
      entry === null ||
      !("id" in entry) ||
      typeof entry.id !== "string"
    ) {
      return panic("Capability feature bindings require a catalog entry id");
    }
    if (!("featureId" in entry) || entry.featureId === undefined) {
      return [];
    }
    if (typeof entry.featureId !== "string") {
      return panic("Capability feature bindings require a string feature id");
    }
    return [[entry.id, entry.featureId]];
  });
  // Emit the repository formatter's shape (one entry per line) directly: the
  // API image builds this file without the repository's scripts.
  const bindingEntries = features
    .map(
      ([id, featureId]) =>
        `  [${JSON.stringify(id)}, ${JSON.stringify(featureId)}],\n`,
    )
    .join("");
  await writeFile(
    new URL("capability-feature-bindings.ts", directory),
    `${header}export const CAPABILITY_FEATURE_BINDINGS = new Map<string, string>(${features.length === 0 ? "" : `[\n${bindingEntries}]`});\n`,
  );
};
