import { panic } from "better-result";
import path from "node:path";

import { compareCodeUnit } from "@stll/collation";
import {
  collectIdempotentCreateRoutes,
  CREATE_ROUTES_MARKER,
} from "@stll/scripts/src/idempotent-create-routes";

import { apiRoutes } from "@/api/api-routes";

import {
  formattedLikeRepository,
  writeOrCheckArtifacts,
} from "../../../scripts/generated-artifacts";
import { deriveCapabilityId } from "./lib/capability-catalog";
import { discoverSafeHandlers } from "./lib/enumerate-safe-handlers";

export const mountedCreateRouteCensus = async () => {
  const discovery = await discoverSafeHandlers();
  if (discovery.importErrors.length > 0) {
    panic(
      `Cannot discover create route owners: ${JSON.stringify(discovery.importErrors)}`,
    );
  }
  return collectIdempotentCreateRoutes({
    routes: apiRoutes,
    endpoints: discovery.endpoints.map((endpoint) => ({
      definition: endpoint.definition,
      file: endpoint.file.replace(/^apps\/api\//u, ""),
      create:
        endpoint.file.endsWith("/create.ts") ||
        deriveCapabilityId(endpoint).endsWith(".create"),
    })),
  });
};

if (import.meta.main) {
  const routes = await mountedCreateRouteCensus();
  if (process.argv.includes("--write") || process.argv.includes("--check")) {
    const replay = routes
      .filter((route) => route.replay)
      .map(({ method, path: routePath }) => ({ method, path: routePath }))
      .toSorted((left, right) =>
        compareCodeUnit(
          `${left.method} ${left.path}`,
          `${right.method} ${right.path}`,
        ),
      );
    process.exitCode = await writeOrCheckArtifacts(
      [
        {
          path: path.resolve(
            import.meta.dirname,
            "../../web/src/lib/idempotency/replay-routes.gen.ts",
          ),
          contents: await formattedLikeRepository(
            `// Generated by apps/api/scripts/idempotent-create-routes.ts; do not edit.\nimport type { RequestReplayRoute } from "@stll/api-client";\n\nexport const REPLAY_CAPABLE_ROUTES = ${JSON.stringify(replay)} as const satisfies readonly RequestReplayRoute[];\n`,
            ".ts",
          ),
        },
      ],
      {
        write: process.argv.includes("--write"),
        matched: "mounted request replay policies",
      },
    );
  } else {
    console.log(`${CREATE_ROUTES_MARKER}${JSON.stringify(routes)}`);
  }
  process.exit(process.exitCode ?? 0);
}
