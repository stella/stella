import {
  formattedLikeRepository,
  writeOrCheckArtifacts,
} from "../../../scripts/generated-artifacts";
import { userOwnedTableNames } from "../src/lib/account-export/schema-census";

export const accountExportTableNames = userOwnedTableNames;

if (import.meta.main) {
  const tableNames = accountExportTableNames();
  const contents = await formattedLikeRepository(
    `// GENERATED by apps/api/scripts/generate-account-export-tables.ts. Do not edit.\n\nexport const USER_OWNED_TABLE_NAMES = ${JSON.stringify(tableNames)} as const;\n\nexport type UserOwnedTableName = (typeof USER_OWNED_TABLE_NAMES)[number];\n`,
    "ts",
  );
  process.exitCode = await writeOrCheckArtifacts(
    [
      {
        path: new URL(
          "../src/lib/account-export/user-owned-tables.gen.ts",
          import.meta.url,
        ).pathname,
        contents,
      },
    ],
    {
      write: process.argv.includes("--write"),
      matched: "the schema-derived user-owned tables",
    },
  );
}
