import { getTableName, isTable } from "drizzle-orm";

import { compareCodeUnit } from "@stll/collation";

import {
  formattedLikeRepository,
  writeOrCheckArtifacts,
} from "../../../scripts/generated-artifacts";
import * as agentAuthSchema from "../src/db/agent-auth-schema";
import * as authSchema from "../src/db/auth-schema";
import * as schema from "../src/db/schema";

/** Each exported Drizzle table's SQL relation name, keyed by its export. */
export const tableRelationMap = (
  exports: Readonly<Record<string, unknown>>,
): Record<string, string> =>
  Object.fromEntries(
    Object.entries(exports)
      .flatMap(([name, relation]): [string, string][] =>
        isTable(relation) ? [[name, getTableName(relation)]] : [],
      )
      .toSorted(([left], [right]) => compareCodeUnit(left, right)),
  );

if (import.meta.main) {
  const relations = tableRelationMap({
    ...schema,
    ...authSchema,
    ...agentAuthSchema,
  });
  const contents = await formattedLikeRepository(
    `// GENERATED by apps/api/scripts/generate-table-relations.ts. Do not edit.\n\nexport const TABLE_RELATIONS = ${JSON.stringify(relations)} as const;\n`,
    "ts",
  );
  process.exitCode = await writeOrCheckArtifacts(
    [
      {
        path: new URL("../src/lib/db/table-relations.gen.ts", import.meta.url)
          .pathname,
        contents,
      },
    ],
    {
      write: process.argv.includes("--write"),
      matched: "the Drizzle table relation names",
    },
  );
}
