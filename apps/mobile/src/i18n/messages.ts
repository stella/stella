const resolveDeviceLocale = (): UiLocale => {
  const deviceLocale = Intl.DateTimeFormat().resolvedOptions().locale;
  return resolveUiLocale(deviceLocale) ?? "en";
};

export const getMobileLocale = resolveDeviceLocale;

export const mobileMessage = (
  key: MobileMessageKey,
  locale = resolveDeviceLocale(),
): string => mobileMessages[locale][key];

export const mobileMessageWithEmail = (
  key: "codeSentTo",
  emailAddress: string,
  locale = resolveDeviceLocale(),
): string =>
  mobileMessage(key, locale)
    .replace("<email>", "")
    .replace("</email>", "")
    .replace("{emailAddress}", () => emailAddress);

