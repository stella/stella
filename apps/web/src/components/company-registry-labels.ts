type Details = NonNullable<RegistryHit["details"]>;
type Registry = Details["registry"];
type RecordOf<D> = D extends unknown ? D[Exclude<keyof D, "registry">] : never;
type NestedKey<Value> = Value extends readonly (infer Item)[]
  ? NestedKey<Item>
  : Value extends object
    ? { [Key in keyof Value]-?: Key | NestedKey<Value[Key]> }[keyof Value]
    : never;
type LabelMaps = {
  [Detail in Details as Detail["registry"]]: Record<
    Extract<NestedKey<RecordOf<Detail>>, string>,
    string
  >;
};

