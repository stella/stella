export const registryDetailLabel = ({
  registry,
  key,
}: {
  registry: Registry;
  key: string;
}): string => {
  const labels: Record<string, string> = DETAIL_LABELS[registry];
  const label = Object.hasOwn(labels, key) ? labels[key] : undefined;
  if (label === undefined) {
    return panic(`Missing ${registry} registry field label: ${key}`);
  }
  return label;
};
