import { GlobalRegistrator } from "@happy-dom/global-registrator";
import { afterAll, expect, test } from "bun:test";

GlobalRegistrator.register({
  settings: {
    enableJavaScriptEvaluation: true,
    // Only trusted, locally generated React recovery scripts execute here.
    suppressInsecureJavaScriptEnvironmentWarning: true,
  },
});

const { Suspense } = await import("react");
const { hydrateRoot } = await import("react-dom/client");
const { act, waitFor } = await import("@testing-library/react");
const { createMemoryHistory, createRootRoute, createRouter } =
  await import("@tanstack/react-router");
const { attachRouterServerSsrUtils, bindSsrResponseToRequest } =
  await import("@tanstack/react-router/ssr/server");
const { renderSsrResponse } = await import("./ssr-renderer");
const { fetchBoundedSsrResponse, SsrStreamTimeoutError } =
  await import("./ssr-response-stream");

afterAll(async () => {
  await GlobalRegistrator.unregister();
});

test("SSR deadline forwards React recovery instructions so pending boundaries hydrate", async () => {
  const router = createRouter({
    routeTree: createRootRoute(),
    history: createMemoryHistory({ initialEntries: ["/"] }),
    isServer: true,
  });
  attachRouterServerSsrUtils({ router, manifest: undefined });
  await router.load();
  const renderErrors: unknown[] = [];
  const streamErrors: unknown[] = [];
  const recoveryErrors: unknown[] = [];
  const pending = new Promise<never>(() => {});
  const clientContent = "Client recovered content";
  const serverFallback = "Pending server content";
  let client = false;
  const DeferredContent = () => {
    if (!client) {
      throw pending;
    }
    return <p>{clientContent}</p>;
  };
  const content = (
    <Suspense fallback={<p>{serverFallback}</p>}>
      <DeferredContent />
    </Suspense>
  );
  const response = await fetchBoundedSsrResponse({
    request: new Request("https://stella.test/", {
      headers: {
        "User-Agent":
          "Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/129.0.0.0 Safari/537.36",
      },
    }),
    fetchResponse: async (renderRequest, rendererSignal) => {
      await router.serverSsr?.dehydrate({ signal: renderRequest.signal });
      const rendered = await renderSsrResponse({
        request: renderRequest,
        rendererSignal,
        router,
        responseHeaders: new Headers({
          "Content-Type": "text/html; charset=utf-8",
        }),
        children: (
          <html lang="en">
            <head />
            <body>
              <div id="ssr-recovery">{content}</div>
            </body>
          </html>
        ),
        reportError: (error) => {
          renderErrors.push(error);
        },
      });
      if (rendered.isErr()) {
        throw rendered.error;
      }
      return bindSsrResponseToRequest(
        router,
        rendered.value,
        renderRequest.signal,
      ).response;
    },
    reportError: (error) => streamErrors.push(error),
    lifetimeMs: 100,
  });
  const body = response.body;
  expect(body).not.toBeNull();
  if (!body) {
    throw new TypeError("SSR recovery response body missing");
  }
  const reader = body.getReader();
  const shell = new TextDecoder().decode((await reader.read()).value);
  expect(shell).toContain("<!--$?-->");
  expect(shell).toContain(serverFallback);
  expect(renderErrors).toEqual([]);
  let html = shell;
  while (true) {
    const chunk = await reader.read();
    if (chunk.done) {
      break;
    }
    html += new TextDecoder().decode(chunk.value);
  }
  expect(html).toContain("$RX(");
  expect(streamErrors).toHaveLength(1);
  expect(streamErrors.at(0)).toBeInstanceOf(SsrStreamTimeoutError);
  expect(renderErrors).toEqual(streamErrors);
  expect(router.serverSsr).toBeUndefined();

  // document.write executes React's inline recovery scripts, as the HTML parser does.
  document.open();
  // safe-html: Generated by React from the trusted JSX fixture above; no external input.
  document.write(html);
  document.close();
  const container = document.querySelector("#ssr-recovery");
  expect(container).not.toBeNull();
  if (!container) {
    throw new TypeError("SSR recovery container missing");
  }
  expect(container.innerHTML).toContain("<!--$!-->");
  expect(container.textContent).toBe(serverFallback);
  client = true;
  const root = hydrateRoot(container, content, {
    onRecoverableError: (error) => recoveryErrors.push(error),
  });
  try {
    await waitFor(() => {
      expect(container.textContent).toBe(clientContent);
    });
    expect(recoveryErrors).toHaveLength(1);
  } finally {
    act(() => root.unmount());
    container.remove();
  }
});

test("SSR renderer releases router state when a component fails before the shell", async () => {
  const router = createRouter({
    routeTree: createRootRoute(),
    history: createMemoryHistory({ initialEntries: ["/"] }),
    isServer: true,
  });
  attachRouterServerSsrUtils({ router, manifest: undefined });
  const errors: unknown[] = [];
  const failure = new TypeError("Server component failed before shell");
  const FailingContent = () => {
    throw failure;
  };
  const result = await renderSsrResponse({
    request: new Request("https://stella.test/"),
    rendererSignal: new AbortController().signal,
    router,
    responseHeaders: new Headers(),
    children: <FailingContent />,
    reportError: (error) => {
      errors.push(error);
    },
  });
  expect(result.isErr()).toBe(true);
  if (result.isErr()) {
    expect(result.error).toBe(failure);
  }
  expect(errors).toEqual([failure]);
  expect(router.serverSsr).toBeUndefined();
});
