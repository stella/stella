import type { GeneratorPlugin } from "@tanstack/router-generator";
import { panic, Result } from "better-result";
import { readFileSync, renameSync, writeFileSync } from "node:fs";
import path from "node:path";

export const routeTemplateManifest = (tree: string): string => {
  const body = /export interface FileRoutesByFullPath \{([\s\S]*?)\n\}/u
    .exec(tree)
    ?.at(1);
  if (body === undefined) {
    return panic("Generated route tree has no full-path interface");
  }
  const templates = Array.from(
    body.matchAll(/^[\t ]+['"]([^'"]+)['"]: /gmu),
    (match) => match.at(1) ?? panic("Route template capture is missing"),
  );
  if (templates.length === 0) {
    return panic("Generated route tree has no full-path entries");
  }
  return `// Generated by scripts/generate-route-tree.ts; do not edit.\nexport const WEB_ROUTE_TEMPLATES = ${JSON.stringify(templates.toSorted(), null, 2)} as const;\n`;
};
export const refreshRouteTemplateManifest = (
  generatedRouteTree: string,
): void => {
  const destination =
    path.basename(generatedRouteTree) === "routeTree.gen.ts"
      ? path.join(path.dirname(generatedRouteTree), "route-templates.gen.ts")
      : `${generatedRouteTree}.templates.ts`;
  const manifest = routeTemplateManifest(
    readFileSync(generatedRouteTree, "utf-8"),
  );
  const previous = Result.try(() =>
    readFileSync(destination, "utf-8"),
  ).unwrapOr(null);
  if (manifest !== previous) {
    // Watchers and concurrent generator runs read this file; a rename within
    // the directory replaces it in one step, so no reader sees a partial one.
    const staging = `${destination}.${process.pid}.tmp`;
    writeFileSync(staging, manifest);
    renameSync(staging, destination);
  }
};

/** TanStack skips its change hook on unchanged runs, including Vite watch runs. */
export const routeTemplateManifestPlugin = (generatedRouteTree: string) =>
  ({
    name: "stella-route-templates",
    init: ({ generator }) => {
      const run = generator.run.bind(generator);
      // Scope the completion hook to this instance; preserve run's receiver and arguments.
      generator.run = async (...args) => {
        await run(...args);
        refreshRouteTemplateManifest(generatedRouteTree);
      };
    },
  }) satisfies GeneratorPlugin;
