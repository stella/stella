impl ClipboardManager {
  pub fn new() -> Self {
    Self {
      capture_status: ClipboardCaptureStatus::Active,
      groups: Vec::new(),
      image_discovery_status: ClipboardImageCleanupStatus::Idle,
      items: Vec::new(),
      pending_image_blob_ids: BTreeSet::new(),
      persistence: ClipboardPersistence::Initializing,
      retention: ClipboardRetention::default(),
      source_app_visuals: HashMap::new(),
      suppressed_content: None,
      welcome: ClipboardWelcome::new(),
    }
  }

  /// Applies a load resolved off the mutex. Mutations are rejected while the
  /// manager is `Initializing`, so nothing in memory can be overwritten here.
  pub fn install(&mut self, load: ClipboardLoad) {
    self.persistence = match load {
      ClipboardLoad::MemoryOnly => {
        self.image_discovery_status = ClipboardImageCleanupStatus::Idle;
        self.pending_image_blob_ids.clear();
        ClipboardPersistence::MemoryOnly
      }
      ClipboardLoad::DeletionOnly(path) => {
        self.image_discovery_status = ClipboardImageCleanupStatus::Idle;
        self.pending_image_blob_ids.clear();
        ClipboardPersistence::DeletionOnly(path)
      }
      ClipboardLoad::Encrypted {
        image_discovery_status,
        store,
        state,
      } => {
        self.image_discovery_status = image_discovery_status;
        if let Some(state) = state {
          self.capture_status = state.capture_status;
          self.groups = state.groups;
          self.retention = state.retention;
          // Retention pruning during load can leave the persisted visuals
          // stale; only those still backing an item may occupy the capped
          // map, or they would block icons for new source apps.
          let referenced_keys: HashSet<&str> = state
            .items
            .iter()
            .filter_map(ClipboardItem::source_visual_key)
            .collect();
          self.source_app_visuals = state
            .source_app_visuals
            .into_iter()
            .filter(|visual| referenced_keys.contains(visual.key.as_str()))
            .map(|visual| (visual.key.clone(), visual))
            .collect();
          self.items = state.items;
          self.pending_image_blob_ids = state.pending_image_blob_ids;
        } else {
          self.pending_image_blob_ids.clear();
        }
        ClipboardPersistence::Encrypted(store)
      }
    };
  }

  pub fn snapshot(&self) -> ClipboardSnapshot {
    let mut source_app_visuals = self
      .source_app_visuals
      .values()
      .cloned()
      .collect::<Vec<_>>();
    source_app_visuals.sort_by(|left, right| left.key.cmp(&right.key));
    ClipboardSnapshot {
      capture_status: self.capture_status,
      groups: self.groups.clone(),
      items: self.items.iter().map(ClipboardItem::for_webview).collect(),
      persistence: self.persistence.status_with_image_cleanup(
        if self.pending_image_blob_ids.is_empty()
          && self.image_discovery_status == ClipboardImageCleanupStatus::Idle
        {
          ClipboardImageCleanupStatus::Idle
        } else {
          ClipboardImageCleanupStatus::PendingRetry
        },
      ),
      retention: self.retention,
      source_app_visuals,
      welcome_status: self.welcome.status(),
    }
  }

  pub fn complete_welcome(&mut self) -> Result<(), String> {
    self.welcome.complete()
  }

  pub fn set_capture_status(
    &mut self,
    status: ClipboardCaptureStatus,
  ) -> Result<(), String> {
    let checkpoint = self.checkpoint();
    self.capture_status = status;
    self.persist_or_restore(checkpoint)
  }

  pub fn set_retention(&mut self, retention: ClipboardRetention) -> Result<(), String> {
    if matches!(&self.persistence, ClipboardPersistence::DeletionOnly(_)) {
      return Err("clipboard history is unavailable".to_string());
    }
    let checkpoint = self.checkpoint();
    self.retention = retention;
    prune_items(&mut self.items, retention, Utc::now());
    self.persist_or_restore(checkpoint)
  }

  pub fn delete_item(&mut self, id: &str) -> Result<bool, String> {
    let original_len = self.items.len();
    let checkpoint = self.checkpoint();
    self.items.retain(|item| item.id() != id);
    let changed = original_len != self.items.len();
    if !changed {
      return Ok(false);
    }
    self.persist_or_restore(checkpoint)?;
    Ok(true)
  }

  pub fn duplicate_item(&mut self, id: &str) -> Result<bool, String> {
    self.duplicate_item_at(id, Utc::now())
  }

  fn duplicate_item_at(
    &mut self,
    id: &str,
    copied_at: DateTime<Utc>,
  ) -> Result<bool, String> {
    let Some(item) = self.items.iter().find(|item| item.id() == id).cloned() else {
      return Ok(false);
    };
    let checkpoint = self.checkpoint();
    let duplicate = item.duplicate_at(copied_at);
    self.items.insert(0, duplicate);
    prune_items(&mut self.items, self.retention, copied_at);
    self.persist_or_restore(checkpoint)?;
    Ok(true)
  }

  /// A clip copied back from history becomes the newest one: the system
  /// clipboard now holds it, and the capture that would have moved it to the
  /// front is suppressed to keep the item's identity and metadata.
  pub fn touch_item(
    &mut self,
    id: &str,
    copied_at: DateTime<Utc>,
  ) -> Result<bool, String> {
    let Some(index) = self.items.iter().position(|item| item.id() == id) else {
      return Ok(false);
    };
    let checkpoint = self.checkpoint();
    let mut item = self.items.remove(index);
    item.set_copied_at(copied_at);
    self.items.insert(0, item);
    self.persist_or_restore(checkpoint)?;
    Ok(true)
  }

  pub fn clear(&mut self) -> Result<(), String> {
    let checkpoint = self.checkpoint();
    self.items.clear();
    self.source_app_visuals.clear();
    if let ClipboardPersistence::DeletionOnly(path) = &self.persistence {
      if let Err(error) = ClipboardStore::remove(path) {
        self.restore(checkpoint);
        return Err(error);
      }
      self.persistence = ClipboardPersistence::MemoryOnly;
      return Ok(());
    }
    self.persist_or_restore(checkpoint)
  }

  pub fn create_group(
    &mut self,
    name: &str,
    color: ClipboardGroupColor,
  ) -> Result<String, String> {
    if self.groups.len() >= MAX_GROUPS {
      return Err("clipboard group limit reached".to_string());
    }
    let name = self.valid_group_name(name, None)?;
    let id = uuid::Uuid::new_v4().to_string();
    let checkpoint = self.checkpoint();
    self.groups.push(ClipboardGroup {
      color,
      id: id.clone(),
      name,
    });
    self.persist_or_restore(checkpoint)?;
    Ok(id)
  }

  pub fn rename_group(&mut self, id: &str, name: &str) -> Result<bool, String> {
    if !self.groups.iter().any(|group| group.id == id) {
      return Ok(false);
    }
    let name = self.valid_group_name(name, Some(id))?;
    let checkpoint = self.checkpoint();
    let Some(group) = self.groups.iter_mut().find(|group| group.id == id) else {
      return Ok(false);
    };
    group.name = name;
    self.persist_or_restore(checkpoint)?;
    Ok(true)
  }

  fn valid_group_name(
    &self,
    name: &str,
    excluded_group_id: Option<&str>,
  ) -> Result<String, String> {
    let name = name.trim();
    if name.is_empty() || name.chars().count() > MAX_GROUP_NAME_CHARACTERS {
      return Err("clipboard group name is invalid".to_string());
    }
    let normalized_name = name.to_lowercase();
    if self.groups.iter().any(|group| {
      Some(group.id.as_str()) != excluded_group_id
        && group.name.to_lowercase() == normalized_name
    }) {
      return Err("clipboard group name already exists".to_string());
    }
    Ok(name.to_string())
  }

  pub fn delete_group(
    &mut self,
    id: &str,
    mode: ClipboardGroupDeletionMode,
  ) -> Result<bool, String> {
    let original_len = self.groups.len();
    let checkpoint = self.checkpoint();
    self.groups.retain(|group| group.id != id);
    if original_len == self.groups.len() {
      return Ok(false);
    }

    match mode {
      ClipboardGroupDeletionMode::DeleteClips => {
        self.items.retain(|item| item.group_id() != Some(id));
      }
      ClipboardGroupDeletionMode::KeepClips => {
        for item in &mut self.items {
          if item.group_id() == Some(id) {
            item.set_group_id(None);
            item.set_retention_class(ClipboardItemRetentionClass::Kept);
          }
        }
      }
    }
    self.persist_or_restore(checkpoint)?;
    Ok(true)
  }

  pub fn update_item(
    &mut self,
    id: &str,
    plain_text: &str,
    html: Option<&str>,
    group_id: Option<String>,
  ) -> Result<bool, String> {
    if plain_text.trim().is_empty() || plain_text.len() > MAX_ITEM_TEXT_BYTES {
      return Err("clipboard item text is invalid".to_string());
    }
    if let Some(group_id) = &group_id
      && !self.groups.iter().any(|group| group.id == *group_id)
    {
      return Err("clipboard group does not exist".to_string());
    }
    if html.is_some_and(|html| html.len() > MAX_ITEM_HTML_BYTES) {
      return Err("clipboard item formatting is invalid".to_string());
    }
    let html = html.and_then(sanitized_html);
    let checkpoint = self.checkpoint();
    let Some(item) = self.items.iter_mut().find(|item| item.id() == id) else {
      return Ok(false);
    };
    if matches!(&*item, ClipboardItem::Image { .. }) {
      return Err("clipboard image cannot be edited as text".to_string());
    }
    if !item.same_text_content(plain_text, html.as_deref()) {
      item.replace_content(plain_text.to_string(), html);
    }
    if item.group_id() != group_id.as_deref() {
      item.set_group_id(group_id);
    }
    prune_items_preserving(&mut self.items, self.retention, Utc::now(), Some(id));
    self.persist_or_restore(checkpoint)?;
    Ok(true)
  }

  pub fn set_item_group(
    &mut self,
    id: &str,
    group_id: Option<String>,
  ) -> Result<bool, String> {
    if let Some(group_id) = &group_id
      && !self.groups.iter().any(|group| group.id == *group_id)
    {
      return Err("clipboard group does not exist".to_string());
    }
    let Some(item_index) = self.items.iter().position(|item| item.id() == id) else {
      return Ok(false);
    };
    if self.items[item_index].group_id() == group_id.as_deref() {
      return Ok(true);
    }
    let checkpoint = self.checkpoint();
    self.items[item_index].set_group_id(group_id);
    // Ungrouping puts the clip back under the history rules.
    prune_items(&mut self.items, self.retention, Utc::now());
    self.persist_or_restore(checkpoint)?;
    Ok(true)
  }

  pub fn set_item_name(&mut self, id: &str, name: &str) -> Result<bool, String> {
    let name = name.trim();
    if name.chars().count() > MAX_ITEM_NAME_CHARACTERS {
      return Err("clipboard item name is invalid".to_string());
    }
    let checkpoint = self.checkpoint();
    let Some(item) = self.items.iter_mut().find(|item| item.id() == id) else {
      return Ok(false);
    };
    item.set_name((!name.is_empty()).then(|| name.to_string()));
    prune_items_preserving(&mut self.items, self.retention, Utc::now(), Some(id));
    self.persist_or_restore(checkpoint)?;
    Ok(true)
  }

  pub fn item(&self, id: &str) -> Option<ClipboardItem> {
    self.items.iter().find(|item| item.id() == id).cloned()
  }

  pub fn item_for_webview(&self, id: &str) -> Option<ClipboardItem> {
    self
      .items
      .iter()
      .find(|item| item.id() == id)
      .map(ClipboardItem::for_webview)
  }

  pub fn groups(&self) -> &[ClipboardGroup] {
    &self.groups
  }

  pub fn source_app_visual(
    &self,
    item: &ClipboardItem,
  ) -> Option<ClipboardSourceAppVisual> {
    item
      .source_visual_key()
      .and_then(|key| self.source_app_visuals.get(key))
      .cloned()
  }

  pub(crate) fn image(&self, id: &str) -> Result<ClipboardImageRead, String> {
    let item = self
      .items
      .iter()
      .find(|item| item.id() == id)
      .ok_or_else(|| "clipboard item no longer exists".to_string())?;
    let ClipboardItem::Image { blob_id, image, .. } = item else {
      return Err("clipboard item is not an image".to_string());
    };
    if let Some(image) = image {
      return Ok(ClipboardImageRead::Cached(Arc::clone(image)));
    }
    let ClipboardPersistence::Encrypted(store) = &self.persistence else {
      return Err("clipboard image is unavailable".to_string());
    };
    Ok(ClipboardImageRead::EncryptedImage {
      blob_id: blob_id.clone(),
      store: store.clone(),
    })
  }

  pub(crate) fn image_preview(&self, id: &str) -> Result<ClipboardImageRead, String> {
    let item = self
      .items
      .iter()
      .find(|item| item.id() == id)
      .ok_or_else(|| "clipboard item no longer exists".to_string())?;
    let ClipboardItem::Image {
      blob_id, preview, ..
    } = item
    else {
      return Err("clipboard item is not an image".to_string());
    };
    if let Some(preview) = preview {
      return Ok(ClipboardImageRead::Cached(Arc::clone(preview)));
    }
    let ClipboardPersistence::Encrypted(store) = &self.persistence else {
      return Err("clipboard image preview is unavailable".to_string());
    };
    Ok(ClipboardImageRead::EncryptedPreview {
      blob_id: blob_id.clone(),
      store: store.clone(),
    })
  }

  pub fn suppress_next(&mut self, item: &ClipboardItem, plain_text_only: bool) {
    self.suppressed_content = match item {
      ClipboardItem::Text { plain_text, .. }
      | ClipboardItem::FormattedText { plain_text, .. } => {
        Some(ClipboardSuppression::Text {
          html: if plain_text_only {
            None
          } else {
            item.html().map(str::to_string)
          },
          plain_text: plain_text.clone(),
        })
      }
      ClipboardItem::Image { checksum, .. } => Some(ClipboardSuppression::Image {
        checksum: checksum.clone(),
      }),
    };
  }

  pub fn clear_suppression(&mut self) {
    self.suppressed_content = None;
  }

  fn capture(&mut self, capture: ClipboardCapture) -> Result<bool, String> {
    if self.capture_status == ClipboardCaptureStatus::Paused {
      return Ok(false);
    }
    match capture {
      ClipboardCapture::Image(capture) => self.capture_image(capture),
      ClipboardCapture::Text(capture) => self.capture_text(capture),
    }
  }

  fn capture_text(&mut self, capture: ClipboardTextCapture) -> Result<bool, String> {
    let ClipboardTextCapture {
      copied_at,
      html,
      plain_text,
      rtf,
      source_app,
      source_app_visual,
    } = capture;
    if matches!(
      &self.suppressed_content,
      Some(ClipboardSuppression::Text {
        html: suppressed_html,
        plain_text: suppressed_text,
      }) if suppressed_text == &plain_text && suppressed_html == &html
    ) {
      self.suppressed_content = None;
      return Ok(false);
    }
    let checkpoint = self.checkpoint();
    self.suppressed_content = None;

    if let Some(source_app_visual) = source_app_visual
      && (self.source_app_visuals.contains_key(&source_app_visual.key)
        || self.source_app_visuals.len() < MAX_SOURCE_APP_VISUALS)
    {
      self
        .source_app_visuals
        .insert(source_app_visual.key.clone(), source_app_visual);
    }

    let preserved_metadata = self
      .items
      .iter()
      .find(|item| item.same_text_content(&plain_text, html.as_deref()))
      .map(|item| {
        (
          item.group_id().map(str::to_string),
          item.name().map(str::to_string),
          item.retention_class(),
        )
      });
    self
      .items
      .retain(|item| !item.same_text_content(&plain_text, html.as_deref()));
    let id = uuid::Uuid::new_v4().to_string();
    let (group_id, name, retention_class) =
      preserved_metadata.unwrap_or((None, None, ClipboardItemRetentionClass::History));
    let item = match html {
      Some(html) => ClipboardItem::FormattedText {
        copied_at,
        group_id,
        html,
        id,
        name,
        plain_text,
        retention_class,
        rtf,
        source_app,
      },
      None => ClipboardItem::Text {
        copied_at,
        group_id,
        id,
        name,
        plain_text,
        retention_class,
        source_app,
      },
    };
    self.items.insert(0, item);
    prune_items(&mut self.items, self.retention, copied_at);
    self.persist_or_restore(checkpoint)?;
    Ok(true)
  }

  fn capture_image(&mut self, capture: ClipboardImageCapture) -> Result<bool, String> {
    let ClipboardImageCapture {
      checksum,
      copied_at,
      height,
      image,
      preview,
      source_app,
      source_app_visual,
      width,
    } = capture;
    if matches!(
      &self.suppressed_content,
      Some(ClipboardSuppression::Image { checksum: suppressed }) if suppressed == &checksum
    ) {
      self.suppressed_content = None;
      return Ok(false);
    }
    let checkpoint = self.checkpoint();
    self.suppressed_content = None;

    if let Some(source_app_visual) = source_app_visual
      && (self.source_app_visuals.contains_key(&source_app_visual.key)
        || self.source_app_visuals.len() < MAX_SOURCE_APP_VISUALS)
    {
      self
        .source_app_visuals
        .insert(source_app_visual.key.clone(), source_app_visual);
    }

    let existing = self
      .items
      .iter()
      .find(|item| item.image_checksum() == Some(checksum.as_str()))
      .map(|item| match item {
        ClipboardItem::Image {
          blob_id,
          byte_size,
          group_id,
          name,
          retention_class,
          ..
        } => (
          blob_id.clone(),
          *byte_size,
          group_id.clone(),
          name.clone(),
          *retention_class,
        ),
        ClipboardItem::Text { .. } | ClipboardItem::FormattedText { .. } => {
          unreachable!("only image items have image checksums")
        }
      });
    self
      .items
      .retain(|item| item.image_checksum() != Some(checksum.as_str()));
    let id = uuid::Uuid::new_v4().to_string();
    let (blob_id, byte_size, group_id, name, retention_class) = match existing {
      Some(existing) => existing,
      None => (
        uuid::Uuid::new_v4().to_string(),
        image.len(),
        None,
        None,
        ClipboardItemRetentionClass::History,
      ),
    };
    self.items.insert(
      0,
      ClipboardItem::Image {
        blob_id,
        byte_size,
        checksum,
        copied_at,
        group_id,
        height,
        id: id.clone(),
        image: Some(image.into()),
        name,
        preview: Some(preview.into()),
        retention_class,
        source_app,
        width,
      },
    );
    prune_items(&mut self.items, self.retention, copied_at);
    prune_image_history(&mut self.items);
    if !self.items.iter().any(|item| item.id() == id) {
      self.restore(checkpoint);
      return Ok(false);
    }
    self.persist_or_restore(checkpoint)?;
    Ok(true)
  }

  pub fn prune_expired(&mut self, now: DateTime<Utc>) -> Result<bool, String> {
    let checkpoint = self.checkpoint();
    let items_changed = prune_items(&mut self.items, self.retention, now);
    let cleanup_was_pending = !self.pending_image_blob_ids.is_empty()
      || self.image_discovery_status == ClipboardImageCleanupStatus::PendingRetry;
    if !items_changed && !cleanup_was_pending {
      return Ok(false);
    }
    self.persist_or_restore(checkpoint)?;
    let cleanup_is_pending = !self.pending_image_blob_ids.is_empty()
      || self.image_discovery_status == ClipboardImageCleanupStatus::PendingRetry;
    Ok(items_changed || cleanup_was_pending != cleanup_is_pending)
  }

  fn checkpoint(&self) -> ClipboardManagerCheckpoint {
    ClipboardManagerCheckpoint {
      capture_status: self.capture_status,
      groups: self.groups.clone(),
      image_discovery_status: self.image_discovery_status,
      items: self.items.clone(),
      pending_image_blob_ids: self.pending_image_blob_ids.clone(),
      retention: self.retention,
      source_app_visuals: self.source_app_visuals.clone(),
      suppressed_content: self.suppressed_content.clone(),
    }
  }

  fn restore(&mut self, checkpoint: ClipboardManagerCheckpoint) {
    self.capture_status = checkpoint.capture_status;
    self.groups = checkpoint.groups;
    self.image_discovery_status = checkpoint.image_discovery_status;
    self.items = checkpoint.items;
    self.pending_image_blob_ids = checkpoint.pending_image_blob_ids;
    self.retention = checkpoint.retention;
    self.source_app_visuals = checkpoint.source_app_visuals;
    self.suppressed_content = checkpoint.suppressed_content;
  }

  fn persist_or_restore(
    &mut self,
    checkpoint: ClipboardManagerCheckpoint,
  ) -> Result<(), String> {
    if matches!(self.persistence, ClipboardPersistence::Encrypted(_)) {
      let previous_live_blob_ids = image_blob_ids(&checkpoint.items);
      let live_blob_ids = image_blob_ids(&self.items);
      // A shared blob enters the journal only after its final item reference is
      // gone; the journal is committed atomically with the new item metadata.
      self
        .pending_image_blob_ids
        .retain(|blob_id| !live_blob_ids.contains(blob_id));
      self.pending_image_blob_ids.extend(
        previous_live_blob_ids
          .difference(&live_blob_ids)
          .filter(|blob_id| uuid::Uuid::parse_str(blob_id).is_ok())
          .cloned(),
      );
    } else {
      self.pending_image_blob_ids.clear();
    }
    if let Err(error) = self.persist() {
      let pending_after_failure = self.pending_image_blob_ids.clone();
      let discovery_after_failure = self.image_discovery_status;
      self.restore(checkpoint);
      if matches!(self.persistence, ClipboardPersistence::Encrypted(_)) {
        let live_blob_ids = image_blob_ids(&self.items);
        self.pending_image_blob_ids.extend(
          pending_after_failure
            .into_iter()
            .filter(|blob_id| !live_blob_ids.contains(blob_id)),
        );
      }
      if discovery_after_failure == ClipboardImageCleanupStatus::PendingRetry {
        self.image_discovery_status = ClipboardImageCleanupStatus::PendingRetry;
      }
      return Err(error);
    }
    Ok(())
  }

  fn persist(&mut self) -> Result<(), String> {
    // Rejecting the write makes `persist_or_restore` roll the mutation
    // back, so `install` can never overwrite a change made before the
    // persisted history arrived.
    if matches!(self.persistence, ClipboardPersistence::Initializing) {
      return Err(HISTORY_LOADING_ERROR.to_string());
    }
    // Visuals whose source app no longer backs any item leave the capped map
    // on every persisted mutation; stale entries would otherwise block icons
    // for new source apps once the cap fills. A failed store write restores
    // them through the caller's checkpoint.
    let referenced_keys: HashSet<&str> = self
      .items
      .iter()
      .filter_map(ClipboardItem::source_visual_key)
      .collect();
    self
      .source_app_visuals
      .retain(|key, _| referenced_keys.contains(key.as_str()));
    let ClipboardPersistence::Encrypted(store) = &self.persistence else {
      // MemoryOnly and DeletionOnly keep nothing on disk.
      self.image_discovery_status = ClipboardImageCleanupStatus::Idle;
      self.pending_image_blob_ids.clear();
      return Ok(());
    };
    let mut created_blob_ids = Vec::new();
    for item in &self.items {
      let Some(blob_id) = item.image_blob_id() else {
        continue;
      };
      let Some(payload) = item.image_payload() else {
        continue;
      };
      match store.persist_image(blob_id, payload) {
        Ok(ClipboardImagePersistStatus::Created) => {
          created_blob_ids.push(blob_id.to_string());
        }
        Ok(ClipboardImagePersistStatus::Existing) => {}
        Err(error) => {
          // A failed blob write may have left an interrupted-write artifact;
          // keep scheduled discovery active even when immediate cleanup fails.
          self.image_discovery_status = ClipboardImageCleanupStatus::PendingRetry;
          let cleanup_errors = remove_created_image_blobs(
            store,
            &created_blob_ids,
            &mut self.pending_image_blob_ids,
          );
          if !cleanup_errors.is_empty() {
            return Err(format!("{error}; {}", cleanup_errors.join("; ")));
          }
          return Err(error);
        }
      }
    }
    let live_blob_ids = image_blob_ids(&self.items);
    if let Err(error) = queue_discovered_orphaned_image_blobs(
      &mut self.pending_image_blob_ids,
      store,
      &live_blob_ids,
    ) {
      self.image_discovery_status = ClipboardImageCleanupStatus::PendingRetry;
      let cleanup_errors = remove_created_image_blobs(
        store,
        &created_blob_ids,
        &mut self.pending_image_blob_ids,
      );
      if cleanup_errors.is_empty() {
        return Err(error);
      }
      return Err(format!("{error}; {}", cleanup_errors.join("; ")));
    }
    self.image_discovery_status = ClipboardImageCleanupStatus::Idle;
    let mut source_app_visuals: Vec<ClipboardSourceAppVisual> =
      self.source_app_visuals.values().cloned().collect();
    source_app_visuals.sort_by(|left, right| left.key.cmp(&right.key));
    let state = PersistedClipboardState {
      capture_status: self.capture_status,
      groups: self.groups.clone(),
      items: self.items.clone(),
      pending_image_blob_ids: self.pending_image_blob_ids.clone(),
      retention: self.retention,
      source_app_visuals,
    };
    if let Err(error) = store.persist(&state) {
      let cleanup_errors = remove_created_image_blobs(
        store,
        &created_blob_ids,
        &mut self.pending_image_blob_ids,
      );
      tracing::warn!(error = %error, "clipboard history persistence failed");
      if !cleanup_errors.is_empty() {
        return Err(format!("{error}; {}", cleanup_errors.join("; ")));
      }
      return Err(error);
    }
    if !self.pending_image_blob_ids.is_empty()
      && remove_pending_image_blobs(store, &self.pending_image_blob_ids)
    {
      let pending_image_blob_ids = std::mem::take(&mut self.pending_image_blob_ids);
      let mut completed_state = state.clone();
      completed_state.pending_image_blob_ids.clear();
      if let Err(error) = store.persist(&completed_state) {
        self.pending_image_blob_ids = pending_image_blob_ids;
        tracing::warn!(
          error = %error,
          "completed clipboard image cleanup could not be checkpointed"
        );
      }
    }
    for item in &mut self.items {
      item.clear_image_payload();
    }
    Ok(())
  }
}

fn prune_items(
  items: &mut Vec<ClipboardItem>,
  retention: ClipboardRetention,
  now: DateTime<Utc>,
) -> bool {
  prune_items_preserving(items, retention, now, None)
}

fn image_blob_ids(items: &[ClipboardItem]) -> HashSet<String> {
  items
    .iter()
    .filter_map(ClipboardItem::image_blob_id)
    .map(str::to_string)
    .collect()
}

fn remove_created_image_blobs(
  store: &ClipboardStore,
  created_blob_ids: &[String],
  pending_image_blob_ids: &mut BTreeSet<String>,
) -> Vec<String> {
  let mut cleanup_errors = Vec::new();
  for created_blob_id in created_blob_ids {
    if let Err(error) = store.remove_image(created_blob_id) {
      pending_image_blob_ids.insert(created_blob_id.clone());
      cleanup_errors.push(error);
    }
  }
  cleanup_errors
}

fn remove_pending_image_blobs(
  store: &ClipboardStore,
  pending_blob_ids: &BTreeSet<String>,
) -> bool {
  let mut completed = true;
  for blob_id in pending_blob_ids {
    if let Err(error) = store.remove_image(blob_id) {
      completed = false;
      tracing::warn!(
        error = %error,
        blob_id,
        "pending clipboard image cleanup will be retried"
      );
    }
  }
  completed
}

fn queue_discovered_orphaned_image_blobs(
  pending_blob_ids: &mut BTreeSet<String>,
  store: &ClipboardStore,
  live_blob_ids: &HashSet<String>,
) -> Result<(), String> {
  pending_blob_ids.extend(store.discover_orphaned_image_blob_ids(live_blob_ids)?);
  Ok(())
}

fn image_blob_validation(
  item: &ClipboardItem,
) -> Result<Option<(&str, ClipboardImageValidation)>, String> {
  let ClipboardItem::Image {
    blob_id,
    byte_size,
    checksum,
    height,
    width,
    ..
  } = item
  else {
    return Ok(None);
  };
  let pixels = u64::from(*width) * u64::from(*height);
  if *byte_size == 0
    || *byte_size > MAX_ITEM_IMAGE_BYTES
    || checksum.len() != 64
    || !checksum.bytes().all(|byte| byte.is_ascii_hexdigit())
    || *width == 0
    || *height == 0
    || *width > MAX_ITEM_IMAGE_DIMENSION
    || *height > MAX_ITEM_IMAGE_DIMENSION
    || pixels > MAX_ITEM_IMAGE_PIXELS
  {
    return Err("clipboard image metadata is invalid".to_string());
  }
  Ok(Some((
    blob_id,
    ClipboardImageValidation {
      byte_size: *byte_size,
      checksum: checksum.clone(),
    },
  )))
}

fn retain_valid_images(items: &mut Vec<ClipboardItem>, store: &ClipboardStore) -> bool {
  #[derive(Clone, Copy)]
  enum ValidationDisposition {
    Invalid,
    Unavailable,
    Valid,
  }

  let original_len = items.len();
  let mut validations = HashMap::new();
  items.retain(|item| {
    let (blob_id, validation) = match image_blob_validation(item) {
      Ok(Some(validation)) => validation,
      Ok(None) => return true,
      Err(error) => {
        tracing::warn!(error = %error, "invalid clipboard image metadata was removed");
        return false;
      }
    };
    let cache_key = (blob_id.to_string(), validation.clone());
    match *validations.entry(cache_key).or_insert_with(|| {
      match store.validate_image(blob_id, &validation, MAX_ITEM_IMAGE_PREVIEW_BYTES) {
        Ok(()) => ValidationDisposition::Valid,
        Err(ClipboardImageValidationError::Invalid(error)) => {
          tracing::warn!(error = %error, "invalid clipboard image payload was removed");
          ValidationDisposition::Invalid
        }
        Err(ClipboardImageValidationError::Unavailable(error)) => {
          tracing::warn!(
            error = %error,
            "clipboard image validation is temporarily unavailable"
          );
          ValidationDisposition::Unavailable
        }
      }
    }) {
      ValidationDisposition::Invalid => false,
      ValidationDisposition::Unavailable | ValidationDisposition::Valid => true,
    }
  });
  items.len() != original_len
}

fn prune_image_history(items: &mut Vec<ClipboardItem>) -> bool {
  let original_len = items.len();
  while image_history_bytes(items) > MAX_HISTORY_IMAGE_BYTES {
    let Some(index) = items
      .iter()
      .rposition(|item| item.image_byte_size() > 0 && !item.is_organised())
    else {
      break;
    };
    items.remove(index);
  }
  items.len() != original_len
}

fn image_history_bytes(items: &[ClipboardItem]) -> usize {
  let mut seen = HashSet::new();
  items
    .iter()
    .filter_map(|item| {
      let blob_id = item.image_blob_id()?;
      // Preview size is deliberately not persisted as metadata. Charging its
      // enforced maximum keeps the total blob-store budget bounded.
      seen.insert(blob_id).then(|| {
        item
          .image_byte_size()
          .saturating_add(MAX_ITEM_IMAGE_PREVIEW_BYTES)
      })
    })
    .fold(0, usize::saturating_add)
}

fn prune_items_preserving(
  items: &mut Vec<ClipboardItem>,
  retention: ClipboardRetention,
  now: DateTime<Utc>,
  preserved_id: Option<&str>,
) -> bool {
  let original_len = items.len();
  let oldest = now - Duration::days(retention.days());
  items.retain(|item| {
    Some(item.id()) == preserved_id || item.is_organised() || item.copied_at() >= oldest
  });

  // Items are newest first, so `rposition` picks the oldest candidate.
  let is_plain =
    |item: &ClipboardItem| Some(item.id()) != preserved_id && !item.is_organised();

  // The count cap bounds plain history; organised items sit outside it.
  let mut plain_count = items.iter().filter(|item| is_plain(item)).count();
  while plain_count > MAX_HISTORY_ITEMS {
    let Some(index) = items.iter().rposition(is_plain) else {
      break;
    };
    items.remove(index);
    plain_count -= 1;
  }

  // The byte cap is the one hard limit: it removes plain history first and
  // touches organised items only once none is left.
  let mut total_bytes = items.iter().map(ClipboardItem::byte_len).sum::<usize>();
  while total_bytes > MAX_HISTORY_BYTES {
    let Some(index) = items.iter().rposition(is_plain).or_else(|| {
      items
        .iter()
        .rposition(|item| Some(item.id()) != preserved_id)
    }) else {
      break;
    };
    total_bytes -= items.remove(index).byte_len();
  }
  items.len() != original_len
}

fn sanitized_html(raw_html: &str) -> Option<String> {
  if raw_html.len() > MAX_ITEM_HTML_BYTES {
    return None;
  }
  let allowed_tags = HashSet::from([
    "b",
    "blockquote",
    "br",
    "code",
    "div",
    "em",
    "i",
    "li",
    "ol",
    "p",
    "pre",
    "s",
    "span",
    "strike",
    "strong",
    "u",
    "ul",
  ]);
  let html = HtmlSanitizer::new()
    .tags(allowed_tags)
    .clean(&without_word_list_spacers(raw_html))
    .to_string();
  let html = collapse_html_whitespace(&html);
  let has_formatting = [
    "b",
    "blockquote",
    "code",
    "em",
    "i",
    "li",
    "ol",
    "pre",
    "s",
    "strong",
    "u",
    "ul",
  ]
  .iter()
  .any(|tag| find_opening_tag(&html, tag).is_some());
  if has_formatting { Some(html) } else { None }
}

/// Word separates an auto-numbered list label from its paragraph with a span in
/// this font holding a run of `&nbsp;`; the run is layout, not text.
const WORD_LIST_SPACER_FONTS: [&str; 2] = [
  "font:7.0pt \"Times New Roman\"",
  "font:7.0pt &quot;Times New Roman&quot;",
];

fn without_word_list_spacers(raw_html: &str) -> String {
  let mut output = String::with_capacity(raw_html.len());
  let mut rest = raw_html;
  while let Some((start, end)) = next_word_list_spacer(rest) {
    output.push_str(&rest[..start]);
    output.push(' ');
    rest = &rest[end..];
  }
  output.push_str(rest);
  output
}

/// Byte range of the next spacer `<span>` whose content is only `&nbsp;` and
/// whitespace. Every index used to slice lands on ASCII, so the slices are valid.
fn next_word_list_spacer(html: &str) -> Option<(usize, usize)> {
  let mut search_from = 0;
  while let Some(offset) = WORD_LIST_SPACER_FONTS
    .iter()
    .filter_map(|font| html[search_from..].find(font))
    .min()
  {
    let font_index = search_from + offset;
    search_from = font_index + 1;
    let Some(span_start) = html[..font_index].rfind("<span") else {
      continue;
    };
    if html[span_start..font_index].contains('>') {
      continue;
    }
    let content_start = font_index + html[font_index..].find('>')? + 1;
    let content_len = html[content_start..].find("</span>")?;
    let content = &html[content_start..content_start + content_len];
    if content
      .split("&nbsp;")
      .all(|chunk| chunk.chars().all(char::is_whitespace))
    {
      return Some((span_start, content_start + content_len + "</span>".len()));
    }
  }
  None
}

/// Collapses source whitespace outside `<pre>` the way HTML renders it, so
/// previews and derived plain text never inherit the source line wrapping that
/// Word and browsers put in clipboard HTML.
fn collapse_html_whitespace(html: &str) -> String {
  let mut output = String::with_capacity(html.len());
  let mut rest = html;
  while let Some(pre_start) = find_opening_tag(rest, "pre") {
    let pre_end = rest[pre_start..]
      .find("</pre>")
      .map_or(rest.len(), |index| pre_start + index + "</pre>".len());
    push_collapsed_whitespace(&mut output, &rest[..pre_start]);
    output.push_str(&rest[pre_start..pre_end]);
    rest = &rest[pre_end..];
  }
  push_collapsed_whitespace(&mut output, rest);
  output.trim().to_string()
}

fn push_collapsed_whitespace(output: &mut String, html: &str) {
  let mut pending_space = false;
  for character in html.chars() {
    if character.is_ascii_whitespace() {
      pending_space = true;
      continue;
    }
    if pending_space {
      output.push(' ');
      pending_space = false;
    }
    output.push(character);
  }
  if pending_space {
    output.push(' ');
  }
}

fn find_opening_tag(html: &str, tag: &str) -> Option<usize> {
  let prefix = format!("<{tag}");
  html.match_indices(&prefix).find_map(|(index, _)| {
    html
      .as_bytes()
      .get(index + prefix.len())
      .is_some_and(|byte| *byte == b'>' || byte.is_ascii_whitespace())
      .then_some(index)
  })
}

fn should_ignore_formats(formats: &[String]) -> bool {
  formats.iter().any(|format| {
    let normalized = format.to_lowercase();
    format.eq_ignore_ascii_case(WINDOWS_MONITOR_PROCESSING_EXCLUSION_FORMAT)
      || IGNORED_FORMATS.iter().any(|ignored| normalized == *ignored)
  })
}

#[cfg(any(target_os = "windows", test))]
fn windows_history_control_allows_capture(value: &[u8]) -> bool {
  let [first, second, third, fourth, ..] = value else {
    return false;
  };
  u32::from_le_bytes([*first, *second, *third, *fourth]) != 0
}

#[cfg(target_os = "windows")]
fn windows_clipboard_history_allows_capture(
  clipboard: &ClipboardContext,
  formats: &[String],
) -> bool {
  if !formats
    .iter()
    .any(|format| format.eq_ignore_ascii_case(WINDOWS_CLIPBOARD_HISTORY_CONTROL_FORMAT))
  {
    return true;
  }
  clipboard
    .get_buffer(WINDOWS_CLIPBOARD_HISTORY_CONTROL_FORMAT)
    .is_ok_and(|value| windows_history_control_allows_capture(&value))
}

fn bounded_metadata(value: &str, max_bytes: usize) -> Option<String> {
  let value = value.trim();
  if value.is_empty() {
    return None;
  }
  if value.len() <= max_bytes {
    return Some(value.to_string());
  }
  let mut boundary = 0;
  for (index, character) in value.char_indices() {
    let next_boundary = index + character.len_utf8();
    if next_boundary > max_bytes {
      break;
    }
    boundary = next_boundary;
  }
  Some(value[..boundary].to_string())
}

fn dominant_icon_color(icon: &image::RgbaImage) -> Option<String> {
  let mut buckets = HashMap::<(u8, u8, u8), (u64, u64, u64, u64)>::new();
  for pixel in icon.pixels() {
    let [red, green, blue, alpha] = pixel.0;
    if alpha < 48 {
      continue;
    }
    let maximum = red.max(green).max(blue);
    let minimum = red.min(green).min(blue);
    let chroma = maximum - minimum;
    let weight = u64::from(alpha) * u64::from(chroma.saturating_add(24));
    let bucket = (red / 32, green / 32, blue / 32);
    let entry = buckets.entry(bucket).or_default();
    entry.0 += weight;
    entry.1 += u64::from(red) * weight;
    entry.2 += u64::from(green) * weight;
    entry.3 += u64::from(blue) * weight;
  }
  let (_, (weight, red, green, blue)) =
    buckets.into_iter().max_by_key(|(_, values)| values.0)?;
  if weight == 0 {
    return None;
  }
  Some(format!(
    "#{:02x}{:02x}{:02x}",
    red / weight,
    green / weight,
    blue / weight
  ))
}

fn source_app_visual(icon: image::RgbaImage) -> (Option<String>, Option<String>) {
  let icon = image::DynamicImage::ImageRgba8(icon)
    .thumbnail(SOURCE_APP_ICON_SIZE, SOURCE_APP_ICON_SIZE)
    .to_rgba8();
  let color = dominant_icon_color(&icon);
  let mut png = Cursor::new(Vec::new());
  let icon_data_url = image::DynamicImage::ImageRgba8(icon)
    .write_to(&mut png, image::ImageFormat::Png)
    .ok()
    .and_then(|()| {
      let value = format!(
        "data:image/png;base64,{}",
        STANDARD.encode(png.into_inner())
      );
      (value.len() <= MAX_SOURCE_APP_ICON_DATA_URL_BYTES).then_some(value)
    });
  (icon_data_url, color)
}

