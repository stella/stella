// The mobile app's icons: the web's icon module, drawn by lucide's React
// Native build.
//
// `packages/ui/src/icons.ts` decides once what every glyph means (a chat is
// `MessageSquareIcon`, a new chat `NewChatIcon`, ...). The app reads the same
// module with `lucide-react` swapped for `lucide-react-native`, which the
// root catalog pins to the same version, so a glyph and its meaning are the
// same on the phone and a change on the web fails the generated-files check
// until the app takes it too.

import { panic } from "better-result";
import { readFile } from "node:fs/promises";
import path from "node:path";

import { writeOrCheckArtifacts } from "./generated-artifacts";

const REPO_ROOT = path.resolve(import.meta.dirname, "..");
const WEB_ICONS = path.join(REPO_ROOT, "packages/ui/src/icons.ts");
const OUTPUT = path.join(REPO_ROOT, "apps/mobile/src/icons.gen.ts");
const WEB_WORDMARK = path.join(
  REPO_ROOT,
  "packages/ui/src/components/stella-wordmark.tsx",
);
const WORDMARK_OUTPUT = path.join(REPO_ROOT, "apps/mobile/src/brand.gen.ts");

/** The web module with every `lucide-react` import read from the native build. */
export const mobileIcons = (webIcons: string): string => {
  const native = webIcons.replaceAll(
    'from "lucide-react";',
    'from "lucide-react-native";',
  );
  if (native.includes('"lucide-react"')) {
    return panic(
      "The web icon module imports lucide-react in a form not mapped",
    );
  }
  return [
    "// Generated by scripts/generate-mobile-icons.ts from",
    "// packages/ui/src/icons.ts. Do not edit; run it with --write.",
    "",
    native,
  ].join("\n");
};

/**
 * The web's stella wordmark (`StellaWordmarkLatin`) as its view box and path
 * data, which the app draws with react-native-svg.
 */
export const mobileWordmark = (webWordmark: string): string => {
  const viewBox = /viewBox="([\d .]+)"/u.exec(webWordmark)?.[1];
  const paths = [...webWordmark.matchAll(/<path d="([^"]+)"/gu)].map(
    ([, d]) => d ?? "",
  );
  if (viewBox === undefined || paths.length === 0) {
    return panic("The web wordmark is not a view box of plain paths");
  }
  return [
    "// Generated by scripts/generate-mobile-icons.ts from",
    "// packages/ui/src/components/stella-wordmark.tsx. Do not edit; run it with --write.",
    "",
    "export const STELLA_WORDMARK = {",
    `  viewBox: ${JSON.stringify(viewBox)},`,
    "  paths: [",
    ...paths.map((d) => `    ${JSON.stringify(d)},`),
    "  ],",
    "} as const;",
    "",
  ].join("\n");
};

export const generateMobileIcons = async (write: boolean) =>
  await writeOrCheckArtifacts(
    [
      {
        path: OUTPUT,
        contents: mobileIcons(await readFile(WEB_ICONS, "utf-8")),
      },
      {
        path: WORDMARK_OUTPUT,
        contents: mobileWordmark(await readFile(WEB_WORDMARK, "utf-8")),
      },
    ],
    { matched: "the web's icons", write },
  );

if (import.meta.main) {
  process.exitCode = await generateMobileIcons(
    process.argv.includes("--write"),
  );
}
