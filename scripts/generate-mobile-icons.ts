// The mobile app's icons: the web's icon module, drawn by lucide's React
// Native build.
//
// `packages/ui/src/icons.ts` decides once what every glyph means (a chat is
// `MessageSquareIcon`, a new chat `NewChatIcon`, ...). The app reads the same
// module with `lucide-react` swapped for `lucide-react-native`, which the
// root catalog pins to the same version, so a glyph and its meaning are the
// same on the phone and a change on the web fails the generated-files check
// until the app takes it too.
//
// The platform's own bars (the header's buttons, the tab bar) take an image
// rather than a component. Those glyphs become images in the iOS asset
// catalog, which UIKit loads by name, synchronously, as it builds a bar; see
// `barGlyphAssets` below.

import { panic } from "better-result";
import { mkdir, readdir, readFile, rm } from "node:fs/promises";
import { createRequire } from "node:module";
import path from "node:path";

import { repoRelativePath } from "@stll/portable-path";

import type { GeneratedArtifact } from "../packages/scripts/src/generated-artifact-format.ts";
import {
  formattedArtifactsLikeRepository,
  writeOrCheckArtifacts,
} from "./generated-artifacts";

const REPO_ROOT = path.resolve(import.meta.dirname, "..");
const MOBILE_ROOT = path.join(REPO_ROOT, "apps/mobile");
const WEB_ICONS = path.join(REPO_ROOT, "packages/ui/src/icons.ts");
const OUTPUT = path.join(REPO_ROOT, "apps/mobile/src/icons.gen.ts");
const WEB_WORDMARK = path.join(
  REPO_ROOT,
  "packages/ui/src/components/stella-wordmark.tsx",
);
const WORDMARK_OUTPUT = path.join(REPO_ROOT, "apps/mobile/src/brand.gen.ts");

/** The web module with every `lucide-react` import read from the native build. */
export const mobileIcons = (webIcons: string): string => {
  const native = webIcons.replaceAll(
    'from "lucide-react";',
    'from "lucide-react-native";',
  );
  if (native.includes('"lucide-react"')) {
    return panic(
      "The web icon module imports lucide-react in a form not mapped",
    );
  }
  return [
    "// Generated by scripts/generate-mobile-icons.ts from",
    "// packages/ui/src/icons.ts. Do not edit; run it with --write.",
    "",
    native,
  ].join("\n");
};

/**
 * The web's stella wordmark (`StellaWordmarkLatin`) as its view box and path
 * data, which the app draws with react-native-svg.
 */
export const mobileWordmark = (webWordmark: string): string => {
  const viewBox = /viewBox="([\d .]+)"/u.exec(webWordmark)?.[1];
  const paths = [...webWordmark.matchAll(/<path d="([^"]+)"/gu)].map(
    ([, d]) => d ?? "",
  );
  if (viewBox === undefined || paths.length === 0) {
    return panic("The web wordmark is not a view box of plain paths");
  }
  return [
    "// Generated by scripts/generate-mobile-icons.ts from",
    "// packages/ui/src/components/stella-wordmark.tsx. Do not edit; run it with --write.",
    "",
    "export const STELLA_WORDMARK = {",
    `  viewBox: ${JSON.stringify(viewBox)},`,
    "  paths: [",
    ...paths.map((d) => `    ${JSON.stringify(d)},`),
    "  ],",
    "} as const;",
    "",
  ].join("\n");
};

/**
 * The lucide glyphs the platform's own bars draw, each with the size in
 * points it is drawn at: 22 on a header's button, 24 in the tab bar.
 */
export const BAR_GLYPH_SIZES = {
  "circle-user-round": 22,
  plus: 22,
  share: 22,
  "sliders-horizontal": 22,
  x: 22,
  "grid-2x2-plus": 24,
  layers: 24,
  "list-todo": 24,
  "message-square": 24,
} as const satisfies Record<string, number>;

/** Where the asset catalog folder is generated; prebuild copies it into the app (app.config.ts). */
const BAR_GLYPHS_DIR = path.join(MOBILE_ROOT, "assets/bar-glyphs");
const BAR_GLYPHS_MODULE = path.join(MOBILE_ROOT, "src/bar-glyphs.gen.ts");

/** The asset catalog's name for a lucide glyph. */
const assetName = (glyph: string) => `lucide-${glyph}`;

/**
 * lucide's outline of a glyph: the filled path data its icon font is built
 * from (`lucide-static/font/lucide.symbol.svg`), on lucide's 24-unit grid
 * and filled even-odd. The same shapes the app's font draws, with every
 * stroke already expanded, so nothing downstream has to stroke a path.
 */
export const glyphOutline = (sprite: string, glyph: string): string[] => {
  if (!/^[a-z\d]+(?:-[a-z\d]+)*$/u.test(glyph)) {
    return panic(`${glyph} is not a lucide glyph name`);
  }
  const symbol =
    new RegExp(
      `<symbol viewBox="0 0 24 24" id="icon-${glyph}">(.*?)</symbol>`,
      "su",
    ).exec(sprite)?.[1] ??
    panic(`lucide-static has no outlined glyph ${glyph} on its 24-unit grid`);
  const paths = [
    ...symbol.matchAll(
      /<path d="([^"]+)" stroke="none" fill-rule="evenodd" fill="black"><\/path>/gu,
    ),
  ].map(([, d]) => (d ?? "").trim());
  if (paths.length === 0 || paths.join("").length === 0) {
    return panic(`lucide-static's ${glyph} has no outline`);
  }
  if (symbol.replaceAll(/<path [^>]*><\/path>/gu, "") !== "") {
    return panic(`lucide-static's ${glyph} holds more than filled paths`);
  }
  return paths;
};

/**
 * A glyph as a vector image `size` points square, black on clear: the asset
 * catalog marks it a template, so the bar tints it to its own colour.
 */
export const glyphSvg = (
  paths: readonly string[],
  size: number,
  lucideVersion: string,
): string =>
  [
    `<svg xmlns="http://www.w3.org/2000/svg" width="${String(size)}" height="${String(size)}" viewBox="0 0 24 24">`,
    `  <!-- lucide-static v${lucideVersion} (ISC). Generated by scripts/generate-mobile-icons.ts; do not edit. -->`,
    ...paths.map((d) => `  <path fill-rule="evenodd" d="${d}"/>`),
    "</svg>",
    "",
  ].join("\n");

/**
 * Each bar glyph as an image set in an asset catalog folder, and the module
 * that names them for the app. The images keep their vector data, so they
 * stay sharp when the system enlarges a bar button for accessibility.
 *
 * Why images rather than custom SF Symbols: a header bar button in Expo
 * Router 58 names an asset only as an image source (`{ uri: name }`), which
 * React Native resolves with `[UIImage imageNamed:]` but only for image
 * sets; a symbol set never loads that way.
 */
export const barGlyphAssets = (
  sprite: string,
  lucideVersion: string,
): GeneratedArtifact[] => {
  // Glyph names are ASCII identifiers, so code-unit order is their order.
  const glyphs = Object.entries(BAR_GLYPH_SIZES).toSorted(([a], [b]) =>
    a < b ? -1 : 1,
  );
  return [
    {
      path: path.join(BAR_GLYPHS_DIR, "Contents.json"),
      contents: JSON.stringify({ info: { author: "xcode", version: 1 } }),
    },
    ...glyphs.flatMap(([glyph, size]): GeneratedArtifact[] => {
      const imageset = path.join(
        BAR_GLYPHS_DIR,
        `${assetName(glyph)}.imageset`,
      );
      return [
        {
          path: path.join(imageset, "Contents.json"),
          contents: JSON.stringify({
            images: [
              { filename: `${assetName(glyph)}.svg`, idiom: "universal" },
            ],
            info: { author: "xcode", version: 1 },
            properties: {
              "preserves-vector-representation": true,
              "template-rendering-intent": "template",
            },
          }),
        },
        {
          path: path.join(imageset, `${assetName(glyph)}.svg`),
          contents: glyphSvg(glyphOutline(sprite, glyph), size, lucideVersion),
        },
      ];
    }),
    {
      path: BAR_GLYPHS_MODULE,
      contents: [
        "// Generated by scripts/generate-mobile-icons.ts from lucide-static's",
        "// outlined glyphs. Do not edit; run it with --write.",
        "",
        "/**",
        " * The asset catalog's name for each lucide glyph the platform's own bars",
        " * draw, for `Stack.Toolbar.Icon`'s and `NativeTabs.Trigger.Icon`'s",
        " * `xcasset`. The images are generated into assets/bar-glyphs, which",
        " * prebuild copies into the iOS asset catalog (app.config.ts).",
        " */",
        "export const BAR_GLYPHS = {",
        ...glyphs.map(
          ([glyph]) =>
            `  ${JSON.stringify(glyph)}: ${JSON.stringify(assetName(glyph))},`,
        ),
        "} as const;",
        "",
      ].join("\n"),
    },
  ];
};

/** Every file under `dir`, recursively; none when it does not exist. */
const filesUnder = async (dir: string): Promise<string[]> =>
  (await readdir(dir, { recursive: true, withFileTypes: true }).catch(() => []))
    .filter((entry) => entry.isFile())
    .map((entry) => path.join(entry.parentPath, entry.name));

/** A package manifest's version. */
const versionOf = (manifest: string): string => {
  const parsed: unknown = JSON.parse(manifest);
  return typeof parsed === "object" &&
    parsed !== null &&
    "version" in parsed &&
    typeof parsed.version === "string"
    ? parsed.version
    : panic("lucide-static's manifest names no version");
};

/** The repository formatter has no parser for SVG; the rest it lays out. */
const formattedGlyphAssets = async (
  artifacts: readonly GeneratedArtifact[],
): Promise<GeneratedArtifact[]> => {
  const isSvg = (artifact: GeneratedArtifact) => artifact.path.endsWith(".svg");
  return [
    ...artifacts.filter((artifact) => isSvg(artifact)),
    ...(await formattedArtifactsLikeRepository(
      artifacts.filter((artifact) => !isSvg(artifact)),
    )),
  ];
};

export const generateMobileIcons = async (write: boolean) => {
  // lucide as the app resolves it: the version the root catalog pins for it.
  const lucide = createRequire(path.join(MOBILE_ROOT, "package.json"));
  const glyphAssets = await formattedGlyphAssets(
    barGlyphAssets(
      await readFile(
        lucide.resolve("lucide-static/font/lucide.symbol.svg"),
        "utf-8",
      ),
      versionOf(
        await readFile(lucide.resolve("lucide-static/package.json"), "utf-8"),
      ),
    ),
  );
  const stale = (await filesUnder(BAR_GLYPHS_DIR)).filter(
    (file) => !glyphAssets.some((artifact) => artifact.path === file),
  );
  if (write) {
    await rm(BAR_GLYPHS_DIR, { force: true, recursive: true });
    await Promise.all(
      glyphAssets.map(
        async ({ path: file }) =>
          await mkdir(path.dirname(file), { recursive: true }),
      ),
    );
  } else {
    for (const file of stale) {
      console.error(`stale: ${repoRelativePath(REPO_ROOT, file)}`);
    }
  }
  const drifted = await writeOrCheckArtifacts(
    [
      {
        path: OUTPUT,
        contents: mobileIcons(await readFile(WEB_ICONS, "utf-8")),
      },
      {
        path: WORDMARK_OUTPUT,
        contents: mobileWordmark(await readFile(WEB_WORDMARK, "utf-8")),
      },
      ...glyphAssets,
    ],
    { matched: "the web's icons and lucide's glyphs", write },
  );
  return write || stale.length === 0 ? drifted : 1;
};

if (import.meta.main) {
  process.exitCode = await generateMobileIcons(
    process.argv.includes("--write"),
  );
}
