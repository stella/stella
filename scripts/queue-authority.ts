const parseBaseline = (text: string, label: string): Baseline => {
  const parsed = v.safeParse(BASELINE_SCHEMA, JSON.parse(text));
  if (!parsed.success) {
    return panic(`${label}: ${v.summarize(parsed.issues)}`);
  }
  return parsed.output;
};

const readBaseline = (ledger: Ledger): Baseline => {
  const text = readRepoFile(ledger.path);
  return text === null
    ? { comment: ledger.comment, members: {} }
    : parseBaseline(text, ledger.path);
};

const reportErrors = (errors: readonly string[]): boolean => {
  for (const error of errors) {
    console.error(error);
  }
  return errors.length > 0;
};

const write = (): number => {
  const ledgers = treeLedgers();
  if (reportErrors(ledgers.flatMap(({ audit }) => audit.errors))) {
    return 1;
  }
  for (const ledger of ledgers) {
    const previous = readBaseline(ledger);
    const next: Baseline = {
      comment: previous.comment,
      members: Object.fromEntries(
        ledger.audit.members.map(({ key, reason }) => [
          key,
          previous.members[key] ?? reason,
        ]),
      ),
    };
    writeFileSync(
      path.join(ROOT, ledger.path),
      `${JSON.stringify(next, null, 2)}\n`,
    );
    console.log(
      `${ledger.path} written: ${String(ledger.audit.members.length)} members.`,
    );
  }
  return 0;
};

/** Members found but not listed, and listed members no longer found. */
const baselineDifference = (
  found: readonly string[],
  listed: readonly string[],
) => ({
  added: found.filter((key) => !listed.includes(key)),
  stale: listed.filter((key) => !found.includes(key)),
});

const check = (args: readonly string[]): number => {
  const baseIndex = args.indexOf("--base");
  const base =
    (baseIndex === -1 ? undefined : args[baseIndex + 1]) ??
    process.env["BASE_SHA"] ??
    "origin/main";
  let failed = false;
  let baselined = 0;
  for (const ledger of treeLedgers()) {
    const { errors, members } = ledger.audit;
    const { added, stale } = baselineDifference(
      members.map(({ key }) => key),
      Object.keys(readBaseline(ledger).members),
    );
    const failures = [
      ...errors,
      ...added.map((key) => `${ledger.newGap}: ${key}`),
      ...stale.map((key) => `${ledger.closedGap}: ${key}`),
    ];
    reportErrors(failures);
    const membership =
      readRepoFile(ledger.path) === null
        ? 0
        : runLedgerMembershipGuard({
            ledgerRel: ledger.path,
            repoRoot: ROOT,
            parseLedger: (text, label) =>
              Object.keys(parseBaseline(text, label).members),
            label: ledger.label,
            remediation: ledger.remediation,
            args: ["--base", base === "" ? "origin/main" : base],
          });
    failed ||= failures.length > 0 || membership !== 0;
    baselined += members.length;
  }
  if (failed) {
    return 1;
  }
  console.log(
    `Queue authority: ${String(Object.keys(QUEUE_AUTHORITY).length)} queues and ${String(Object.keys(SCHEDULER_TASK_AUTHORITY).length)} scheduler tasks classified, ${String(baselined)} baselined members, exact sets verified.`,
  );
  return 0;
};

