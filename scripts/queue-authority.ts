type Member = { key: string; reason: string };
type Audit = { errors: string[]; members: Member[] };

const auditRegistry = (input: AuditInput, errors: string[]) => {
  const hosted = new Set(input.hostQueues);
  for (const queue of input.hostQueues) {
    if (!(queue in input.registry)) {
      errors.push(`Queue without an authority row: ${queue}`);
    }
  }
  for (const [queue, entry] of Object.entries(input.registry)) {
    if (!hosted.has(queue)) {
      errors.push(`Authority row for a queue the host table lacks: ${queue}`);
    }
    if (entry.reason.trim() === "") {
      errors.push(`Authority row without a reason: ${queue}`);
    }
    const consumed = input.workerQueues.get(entry.worker);
    if (consumed === undefined) {
      errors.push(
        `Declared worker module constructs no BullMQ Worker: ${queue} -> ${entry.worker}`,
      );
    } else if (consumed !== null && !consumed.includes(queue)) {
      errors.push(
        `Declared worker module has no Worker on its queue: ${queue} -> ${entry.worker}`,
      );
    }
    for (const executor of entry.executors ?? []) {
      if (input.readFile(executor) === null) {
        errors.push(
          `Declared executor does not exist: ${queue} -> ${executor}`,
        );
      }
    }
  }
  for (const [module, queues] of input.workerQueues) {
    if (queues === null) {
      errors.push(
        `BullMQ Worker queue name does not resolve to string literals: ${module}`,
      );
      continue;
    }
    for (const queue of queues) {
      const owner = input.registry[queue]?.worker;
      if (owner !== module) {
        errors.push(
          owner === undefined
            ? `BullMQ Worker outside the queue authority registry: ${module} (${queue})`
            : `BullMQ Worker on ${queue} in ${module}, but the registry assigns it to ${owner}`,
        );
      }
    }
  }
  for (const { queue, module } of input.memberRunQueues) {
    const entry = input.registry[queue];
    if (entry?.authority !== "member-run" || entry.worker !== module) {
      errors.push(
        `MEMBER_RUN_QUEUES lists ${queue} (${module}), but the registry does not classify it as a member run of that module`,
      );
    }
  }
};

const unwrap = (node: Expression): Expression =>
  node.type === "TSSatisfiesExpression" ||
  node.type === "TSAsExpression" ||
  node.type === "ParenthesizedExpression"
    ? unwrap(node.expression)
    : node;
const propertyName = (name: Node): string | null => {
  if (name.type === "Identifier") {
    return name.name;
  }
  return name.type === "Literal" && typeof name.value === "string"
    ? name.value
    : null;
};
const isPropertyAssignment = (node: Node): node is Property =>
  node.type === "Property" &&
  !node.shorthand &&
  !node.method &&
  node.kind === "init";
const literalString = (node: Node | null | undefined): string | undefined => {
  if (node?.type === "Literal" && typeof node.value === "string") {
    return node.value;
  }
  if (node?.type === "TemplateLiteral" && node.expressions.length === 0) {
    return node.quasis.at(0)?.value.cooked ?? undefined;
  }
  return undefined;
};
const parents = new WeakMap<Node, Node>();
const sourceTexts = new WeakMap<Node, string>();
const parseSource = (name: string, source: string): Program => {
  const parsed = parseSyntax(name, source);
  walk(parsed.program, (node, ancestors) => {
    const parent = ancestors.at(-1);
    if (parent) {
      parents.set(node, parent);
    }
    sourceTexts.set(node, source.slice(node.start, node.end));
  });
  return parsed.program;
};
const hasNodeType = <T extends Node["type"]>(
  node: Node,
  type: T,
): node is Extract<Node, { type: T }> => node.type === type;
const findNodes = <T extends Node["type"]>(
  root: Node,
  type: T,
): Extract<Node, { type: T }>[] => {
  const found: Extract<Node, { type: T }>[] = [];
  walk(root, (node) => {
    if (hasNodeType(node, type)) {
      found.push(node);
    }
  });
  return found;
};

type ImportBinding = { module: string; imported: string };

/** Value (not type-only) named imports, keyed by local name. */
const importBindings = (file: Program): Map<string, ImportBinding> => {
  const bindings = new Map<string, ImportBinding>();
  for (const statement of file.body) {
    if (
      statement.type !== "ImportDeclaration" ||
      statement.importKind === "type"
    ) {
      continue;
    }
    for (const element of statement.specifiers) {
      if (element.type === "ImportSpecifier" && element.importKind !== "type") {
        bindings.set(element.local.name, {
          module: statement.source.value,
          imported:
            element.imported.type === "Identifier"
              ? element.imported.name
              : element.imported.value,
        });
      }
    }
  }
  return bindings;
};

/** Local names bound to `imported` from `module`. */
const importedAs = (
  file: Program,
  module: string,
  imported: string,
): Set<string> =>
  new Set(
    [...importBindings(file)]
      .filter(
        ([, binding]) =>
          binding.module === module && binding.imported === imported,
      )
      .map(([local]) => local),
  );

/** Whether the module calls the `createRootRunActor` it imports. */
const callsRunActor = (source: string): boolean => {
  const file = parseSource("worker.ts", source);
  const locals = importedAs(file, RUN_ACTOR_MODULE, RUN_ACTOR);
  return findNodes(file, "CallExpression").some(
    (call) => call.callee.type === "Identifier" && locals.has(call.callee.name),
  );
};

const INACTIVE_MODIFIERS = new Set([
  "if",
  "skip",
  "skipIf",
  "todo",
  "todoIf",
  "failing",
]);

/** Whether `node` sits inside a skipped, conditional or todo suite or test. */
const insideInactiveBlock = (node: Node): boolean => {
  let current = parents.get(node);
  while (current && current.type !== "Program") {
    if (current.type === "CallExpression") {
      const callee =
        current.callee.type === "CallExpression"
          ? current.callee.callee
          : current.callee;
      if (
        callee.type === "MemberExpression" &&
        !callee.computed &&
        callee.property.type === "Identifier" &&
        INACTIVE_MODIFIERS.has(callee.property.name)
      ) {
        return true;
      }
    }
    current = parents.get(current);
  }
  return false;
};

/**
 * Titles of the active bun:test cases in `source`: a plain `test`/`it` call
 * imported from bun:test with a literal title and a function body, outside
 * any skipped or conditional block. Comments and constants do not count.
 */
const activeTestTitles = (source: string): Set<string> => {
  const file = parseSource("revocation.test.ts", source);
  const runners = new Set([
    ...importedAs(file, "bun:test", "test"),
    ...importedAs(file, "bun:test", "it"),
  ]);
  const titles = new Set<string>();
  for (const call of findNodes(file, "CallExpression")) {
    const [title, body] = call.arguments;
    if (
      call.callee.type === "Identifier" &&
      runners.has(call.callee.name) &&
      title !== undefined &&
      literalString(title) !== undefined &&
      body !== undefined &&
      (body.type === "ArrowFunctionExpression" ||
        body.type === "FunctionExpression") &&
      !insideInactiveBlock(call)
    ) {
      const titleText = literalString(title);
      if (titleText !== undefined) {
        titles.add(titleText);
      }
    }
  }
  return titles;
};

const API_ALIAS = "@/api/";
const MAX_RESOLVE_DEPTH = 6;

const resolveModulePath = (from: string, specifier: string): string | null => {
  let base: string;
  if (specifier.startsWith(API_ALIAS)) {
    base = path.posix.join(API_SOURCE, specifier.slice(API_ALIAS.length));
  } else if (specifier.startsWith(".")) {
    base = path.posix.join(path.posix.dirname(from), specifier);
  } else {
    return null;
  }
  return `${base.replace(/\.ts$/u, "")}.ts`;
};

const declarationInitializer = (
  file: Program,
  name: string,
): Expression | undefined =>
  findNodes(file, "VariableDeclarator").find(
    (declaration) =>
      declaration.id.type === "Identifier" && declaration.id.name === name,
  )?.init ?? undefined;

type ResolveContext = {
  relativePath: string;
  file: Program;
  readFile: AuditInput["readFile"];
  depth: number;
};

/**
 * The string literals an expression can evaluate to, following local
 * constants, named imports (relative or `@/api/`), element access into an
 * object literal and its values. `null` when any step is not a literal.
 */
const resolveStrings = (
  expression: Expression,
  context: ResolveContext,
): string[] | null => {
  const node = unwrap(expression);
  const text = literalString(node);
  if (text !== undefined) {
    return [text];
  }
  if (context.depth > MAX_RESOLVE_DEPTH) {
    return null;
  }
  const deeper = { ...context, depth: context.depth + 1 };
  if (node.type === "MemberExpression" && node.computed) {
    return resolveStrings(node.object, deeper);
  }
  if (node.type === "ObjectExpression") {
    const values: string[] = [];
    for (const property of node.properties) {
      const resolved = isPropertyAssignment(property)
        ? resolveStrings(property.value, deeper)
        : null;
      if (resolved === null) {
        return null;
      }
      values.push(...resolved);
    }
    return values;
  }
  if (node.type !== "Identifier") {
    return null;
  }
  const local = declarationInitializer(context.file, node.name);
  if (local !== undefined) {
    return resolveStrings(local, deeper);
  }
  const binding = importBindings(context.file).get(node.name);
  const target =
    binding === undefined
      ? null
      : resolveModulePath(context.relativePath, binding.module);
  const source = target === null ? null : context.readFile(target);
  if (binding === undefined || target === null || source === null) {
    return null;
  }
  const file = parseSource(target, source);
  const exported = declarationInitializer(file, binding.imported);
  return exported === undefined
    ? null
    : resolveStrings(exported, { ...deeper, relativePath: target, file });
};

const accessedMemberName = (node: Node | undefined): string | null => {
  if (node?.type !== "MemberExpression") {
    return null;
  }
  if (node.computed) {
    return literalString(node.property) ?? null;
  }
  return node.property.type === "Identifier" ? node.property.name : null;
};

/**
 * Queue names consumed by the owned BullMQ workers a module constructs:
 * `undefined` when it constructs none, `null` when a queue name does not
 * resolve statically.
 */
const workerQueueNames = (
  relativePath: string,
  source: string,
  readFile: AuditInput["readFile"],
): readonly string[] | null | undefined => {
  if (!source.includes("bullmq-queue")) {
    return undefined;
  }
  const file = parseSource(relativePath, source);
  const bindings = importBindings(file);
  const namespaces = new Map<string, string>();
  for (const statement of file.body) {
    if (
      statement.type !== "ImportDeclaration" ||
      statement.importKind === "type"
    ) {
      continue;
    }
    for (const specifier of statement.specifiers) {
      if (specifier.type === "ImportNamespaceSpecifier") {
        namespaces.set(specifier.local.name, statement.source.value);
      }
    }
  }
  const isOwnedConstructor = (expression: Expression, depth = 0): boolean => {
    if (depth > MAX_RESOLVE_DEPTH) {
      return false;
    }
    const node = unwrap(expression);
    if (node.type === "Identifier") {
      const binding = bindings.get(node.name);
      if (binding !== undefined) {
        return (
          binding.imported === WORKER_CONSTRUCTOR &&
          resolveModulePath(relativePath, binding.module) === HOST_TABLE_FILE
        );
      }
      const initializer = declarationInitializer(file, node.name);
      return (
        initializer !== undefined && isOwnedConstructor(initializer, depth + 1)
      );
    }
    const namespace =
      node.type === "MemberExpression" && node.object.type === "Identifier"
        ? namespaces.get(node.object.name)
        : undefined;
    const member = accessedMemberName(node);
    return (
      namespace !== undefined &&
      member === WORKER_CONSTRUCTOR &&
      resolveModulePath(relativePath, namespace) === HOST_TABLE_FILE
    );
  };
  const constructions = findNodes(file, "NewExpression").filter((node) =>
    isOwnedConstructor(node.callee),
  );
  if (constructions.length === 0) {
    return undefined;
  }
  const queues = new Set<string>();
  for (const construction of constructions) {
    const first = construction.arguments.at(0);
    const names =
      first === undefined
        ? null
        : resolveStrings(first, { relativePath, file, readFile, depth: 0 });
    if (names === null) {
      return null;
    }
    for (const name of names) {
      queues.add(name);
    }
  }
  return [...queues].toSorted();
};

const dynamicBullMqImportReachesWorker = (
  call: CallExpression | ImportExpression,
): boolean => {
  const specifier =
    call.type === "ImportExpression" ? call.source : call.arguments.at(0);
  if (
    (call.type === "CallExpression" &&
      !(call.callee.type === "Identifier" && call.callee.name === "require")) ||
    specifier?.type !== "Literal" ||
    typeof specifier.value !== "string" ||
    !(specifier.value === "bullmq" || specifier.value.startsWith("bullmq/"))
  ) {
    return false;
  }
  let parent = parents.get(call);
  while (
    parent &&
    [
      "AwaitExpression",
      "ParenthesizedExpression",
      "TSAsExpression",
      "TSSatisfiesExpression",
    ].includes(parent.type)
  ) {
    parent = parents.get(parent);
  }
  const member = accessedMemberName(parent);
  if (member !== null && member !== "Worker") {
    return false;
  }
  if (
    parent?.type === "VariableDeclarator" &&
    parent.id.type === "ObjectPattern"
  ) {
    return !parent.id.properties.every((element) => {
      if (element.type !== "Property") {
        return false;
      }
      const name = propertyName(element.key);
      return name !== null && name !== "Worker";
    });
  }
  return true;
};
const rawWorkerImports = (relativePath: string, source: string): string[] => {
  if (relativePath === HOST_TABLE_FILE || !source.includes("bullmq")) {
    return [];
  }
  const file = parseSource(relativePath, source);
  const violations: string[] = [];
  for (const statement of file.body) {
    if (
      statement.type !== "ImportDeclaration" &&
      statement.type !== "ExportNamedDeclaration" &&
      statement.type !== "ExportAllDeclaration"
    ) {
      continue;
    }
    const moduleName = statement.source?.value;
    if (
      moduleName === undefined ||
      !(moduleName === "bullmq" || moduleName.startsWith("bullmq/"))
    ) {
      continue;
    }
    let reachesWorker = statement.type === "ExportAllDeclaration";
    if (statement.type === "ImportDeclaration") {
      reachesWorker = statement.specifiers.some(
        (specifier) =>
          specifier.type === "ImportNamespaceSpecifier" ||
          (specifier.type === "ImportSpecifier" &&
            (specifier.imported.type === "Identifier"
              ? specifier.imported.name
              : specifier.imported.value) === "Worker"),
      );
    } else if (statement.type === "ExportNamedDeclaration") {
      reachesWorker = statement.specifiers.some(
        (specifier) =>
          (specifier.local.type === "Identifier"
            ? specifier.local.name
            : specifier.local.value) === "Worker",
      );
    }
    if (reachesWorker) {
      violations.push(
        `BullMQ Worker imports use ${HOST_TABLE_FILE}: ${relativePath}`,
      );
    }
  }
  walk(file, (call) => {
    if (
      (call.type === "CallExpression" || call.type === "ImportExpression") &&
      dynamicBullMqImportReachesWorker(call)
    ) {
      violations.push(
        `BullMQ Worker imports use ${HOST_TABLE_FILE}: ${relativePath}`,
      );
    }
  });
  return violations;
};

const revocationGap = (
  entry: QueueAuthorityEntry,
  readFile: AuditInput["readFile"],
): string | null => {
  if (entry.revocationTest === undefined) {
    return REASONS.revocationTest;
  }
  if (!entry.revocationTest.endsWith(REVOCATION_TEST_SUFFIX)) {
    return `revocationTest ${entry.revocationTest} is not an integration test (*${REVOCATION_TEST_SUFFIX}).`;
  }
  const source = readFile(entry.revocationTest);
  if (source === null) {
    return `revocationTest ${entry.revocationTest} does not exist.`;
  }
  const active = activeTestTitles(source);
  const missing = MEMBER_RUN_REVOCATION_CASES.filter(
    (title) => !active.has(title),
  );
  return missing.length === 0
    ? null
    : `${entry.revocationTest} lacks: ${missing.join("; ")}.`;
};

const auditQueueAuthority = (input: AuditInput): Audit => {
  const errors: string[] = [];
  auditRegistry(input, errors);
  const onActor = new Set(input.memberRunQueues.map(({ queue }) => queue));
  const members: Member[] = [];
  for (const [queue, entry] of Object.entries(input.registry)) {
    if (entry.authority !== "member-run") {
      continue;
    }
    const usesActor =
      onActor.has(queue) && callsRunActor(input.readFile(entry.worker) ?? "");
    if (!usesActor) {
      members.push({ key: `${queue}::run-actor`, reason: REASONS.runActor });
    }
    for (const file of [entry.worker, ...(entry.executors ?? [])]) {
      if (input.pinnedAllowed.has(file)) {
        members.push({
          key: `${queue}::pinned-handles::${file}`,
          reason: REASONS.pinnedHandles,
        });
      }
    }
    const gap = revocationGap(entry, input.readFile);
    if (gap !== null) {
      members.push({ key: `${queue}::revocation-test`, reason: gap });
    }
  }
  members.sort((left, right) => compareCodeUnit(left.key, right.key));
  return { errors, members };
};

/** Keys of the object literal assigned to `name` in `source`. */
const objectKeys = (source: string, name: string): string[] | null => {
  const file = parseSource("host.ts", source);
  for (const entry of file.body) {
    const statement =
      entry.type === "ExportNamedDeclaration" && entry.declaration
        ? entry.declaration
        : entry;
    if (statement.type !== "VariableDeclaration") {
      continue;
    }
    for (const declaration of statement.declarations) {
      if (
        declaration.id.type === "Identifier" &&
        declaration.id.name === name &&
        declaration.init !== null
      ) {
        const value = unwrap(declaration.init);
        if (value.type !== "ObjectExpression") {
          return null;
        }
        return value.properties.flatMap((property) => {
          const key =
            isPropertyAssignment(property) &&
            !property.computed &&
            propertyName(property.key);
          return typeof key === "string" ? [key] : [];
        });
      }
    }
  }
  return null;
};

type RegisteredTask = { name: string; module: string };

/** Value imports of `file` resolved to repository-relative modules. */
const namedImports = (
  file: Program,
  relativePath: string,
): Map<string, string> => {
  const imports = new Map<string, string>();
  for (const [local, binding] of importBindings(file)) {
    const module = resolveModulePath(relativePath, binding.module);
    if (module !== null) {
      imports.set(local, module);
    }
  }
  return imports;
};

/** The string literal `source` assigns to the constant `name`. */
const constantString = (source: string, name: string): string | null => {
  const initializer = declarationInitializer(
    parseSource("task.ts", source),
    name,
  );
  const value = initializer === undefined ? undefined : unwrap(initializer);
  return literalString(value) ?? null;
};

/** Whether `source` calls the `resolver` it imports. */
const callsImported = (source: string, resolver: string): boolean => {
  const file = parseSource("run-actor.ts", source);
  const locals = new Set(
    [...importBindings(file)]
      .filter(([, binding]) => binding.imported === resolver)
      .map(([local]) => local),
  );
  return findNodes(file, "CallExpression").some(
    (call) => call.callee.type === "Identifier" && locals.has(call.callee.name),
  );
};

/** Whether the module at `from` calls a function it imports from `target`. */
const callsInto = (from: string, source: string, target: string): boolean => {
  const file = parseSource(from, source);
  const imports = namedImports(file, from);
  return findNodes(file, "CallExpression").some(
    (call) =>
      call.callee.type === "Identifier" &&
      imports.get(call.callee.name) === target,
  );
};

/** Object literals of the registry's task tables. */
const registryTables = (file: Program): ObjectExpression[] => {
  const tables: ObjectExpression[] = [];
  const collect = (root: Node) => {
    walk(root, (node) => {
      if (node.type === "ObjectExpression") {
        tables.push(node);
        return "skip-children";
      }
      return undefined;
    });
  };
  for (const entry of file.body) {
    const statement =
      entry.type === "ExportNamedDeclaration" && entry.declaration
        ? entry.declaration
        : entry;
    if (statement.type !== "VariableDeclaration") {
      continue;
    }
    for (const declaration of statement.declarations) {
      if (
        declaration.id.type === "Identifier" &&
        SCHEDULER_REGISTRY_TABLES.includes(declaration.id.name) &&
        declaration.init !== null
      ) {
        collect(declaration.init);
      }
    }
  }
  return tables;
};

/** The identifier a registry value names: `task` or `createTask()`. */
const valueIdentifier = (value: Expression): string | null => {
  const inner = unwrap(value);
  if (inner.type === "Identifier") {
    return inner.name;
  }
  return inner.type === "CallExpression" && inner.callee.type === "Identifier"
    ? inner.callee.name
    : null;
};

type FunctionLike =
  ArrowFunctionExpression | FunctionExpression | FunctionDeclaration;
const isFunctionLike = (node: Node): node is FunctionLike =>
  node.type === "ArrowFunctionExpression" ||
  node.type === "FunctionExpression" ||
  node.type === "FunctionDeclaration";
const enclosingFunction = (node: Node): FunctionLike | undefined => {
  let parent = parents.get(node);
  while (parent) {
    if (isFunctionLike(parent)) {
      return parent;
    }
    parent = parents.get(parent);
  }
  return undefined;
};
const functionName = (fn: FunctionLike): string | null => {
  if (fn.type === "FunctionDeclaration") {
    return fn.id?.name ?? null;
  }
  const parent = parents.get(fn);
  return parent?.type === "VariableDeclarator" &&
    parent.id.type === "Identifier"
    ? parent.id.name
    : null;
};
const parameterIndex = (fn: FunctionLike | undefined, name: string): number =>
  fn === undefined
    ? -1
    : fn.params.findIndex(
        (parameter) =>
          parameter.type === "Identifier" && parameter.name === name,
      );

/**
 * The module implementing a task the registry receives as the parameter
 * `value` of the table function around `property`: follow the registry
 * factory that forwards that parameter to the boot file's call of it, and
 * take the module the boot file imports the argument from. `null` unless
 * every boot call resolves to the same single module.
 */
const injectedTaskModule = (
  property: Property,
  value: string,
  registry: { file: Program; path: string },
  readFile: AuditInput["readFile"],
): string | null => {
  const table = enclosingFunction(property);
  const tableName = table === undefined ? null : functionName(table);
  const position = parameterIndex(table, value);
  if (tableName === null || position < 0) {
    return null;
  }
  const factories: { name: string; position: number }[] = [];
  for (const call of findNodes(registry.file, "CallExpression")) {
    const argument = call.arguments[position];
    if (
      call.callee.type !== "Identifier" ||
      call.callee.name !== tableName ||
      argument?.type !== "Identifier"
    ) {
      continue;
    }
    const caller = enclosingFunction(call);
    const callerName = caller === undefined ? null : functionName(caller);
    const forwarded = parameterIndex(caller, argument.name);
    if (callerName !== null && forwarded >= 0) {
      factories.push({ name: callerName, position: forwarded });
    }
  }
  const bootSource = readFile(SCHEDULER_BOOT_FILE);
  if (bootSource === null || factories.length === 0) {
    return null;
  }
  const boot = parseSource(SCHEDULER_BOOT_FILE, bootSource);
  const bootImports = namedImports(boot, SCHEDULER_BOOT_FILE);
  const bindings = importBindings(boot);
  const modules = new Set<string>();
  for (const call of findNodes(boot, "CallExpression")) {
    if (
      call.callee.type !== "Identifier" ||
      bootImports.get(call.callee.name) !== registry.path
    ) {
      continue;
    }
    const imported = bindings.get(call.callee.name)?.imported;
    const factory = factories.find(({ name }) => name === imported);
    if (factory === undefined) {
      continue;
    }
    const argument = call.arguments[factory.position];
    const supplied = argument === undefined ? null : valueIdentifier(argument);
    modules.add(
      (supplied === null ? undefined : bootImports.get(supplied)) ??
        SCHEDULER_BOOT_FILE,
    );
  }
  const [only, ...rest] = modules;
  return rest.length === 0 ? (only ?? null) : null;
};

/**
 * Every task the scheduler registry runs, with the module that implements it:
 * the module the task's value is imported from; for a task the registry
 * receives at boot, the module the boot file imports it from; else the
 * registry itself.
 */
const registeredTasks = (
  registryFile: string,
  readFile: AuditInput["readFile"],
): { tasks: RegisteredTask[]; errors: string[] } => {
  const source = readFile(registryFile);
  if (source === null) {
    return {
      tasks: [],
      errors: [`Scheduler registry missing: ${registryFile}`],
    };
  }
  const file = parseSource(registryFile, source);
  const imports = namedImports(file, registryFile);
  const tasks: RegisteredTask[] = [];
  const errors: string[] = [];
  for (const table of registryTables(file)) {
    for (const property of table.properties) {
      if (!isPropertyAssignment(property)) {
        continue;
      }
      const literal = property.computed ? null : propertyName(property.key);
      const keyConstant =
        property.computed && property.key.type === "Identifier"
          ? property.key.name
          : null;
      const keyModule =
        keyConstant === null ? registryFile : imports.get(keyConstant);
      const name =
        literal ??
        (keyConstant === null || keyModule === undefined
          ? null
          : constantString(readFile(keyModule) ?? "", keyConstant));
      if (name === null || keyModule === undefined) {
        errors.push(
          `Scheduler registry key not resolvable to a task name: ${sourceTexts.get(property.key) ?? panic("Parsed property must have source text")}`,
        );
        continue;
      }
      const initializer = unwrap(property.value);
      const typedEntry = initializer.type === "ObjectExpression";
      let value = valueIdentifier(property.value);
      if (typedEntry) {
        const taskProperty = initializer.properties.find(
          (entry) =>
            entry.type === "Property" &&
            !entry.computed &&
            !entry.method &&
            entry.kind === "init" &&
            propertyName(entry.key) === "task",
        );
        value = null;
        if (taskProperty?.type === "Property") {
          value = valueIdentifier(taskProperty.value);
        }
      }
      const imported = value === null ? undefined : imports.get(value);
      if (
        typedEntry &&
        (value === null ||
          (imported === undefined &&
            parameterIndex(enclosingFunction(property), value) < 0))
      ) {
        errors.push(
          `Scheduler typed registry task not resolvable to one module: ${name}`,
        );
        continue;
      }
      if (
        value === null ||
        imported !== undefined ||
        parameterIndex(enclosingFunction(property), value) < 0
      ) {
        tasks.push({ name, module: imported ?? registryFile });
        continue;
      }
      const injected = injectedTaskModule(
        property,
        value,
        { file, path: registryFile },
        readFile,
      );
      if (injected === null) {
        errors.push(
          `Scheduler task supplied at boot not traceable to one module: ${name} (${value} from ${SCHEDULER_BOOT_FILE})`,
        );
        continue;
      }
      tasks.push({ name, module: injected });
    }
  }
  return { tasks, errors };
};

type TaskAuditInput = {
  tasks: readonly RegisteredTask[];
  registry: Readonly<Record<string, SchedulerTaskAuthorityEntry>>;
  pinnedAllowed: ReadonlySet<string>;
  readFile: AuditInput["readFile"];
};

const auditSchedulerTaskAuthority = (input: TaskAuditInput): Audit => {
  const errors: string[] = [];
  const members: Member[] = [];
  const registered = new Map(
    input.tasks.map(({ name, module }) => [name, module]),
  );
  for (const { name } of input.tasks) {
    if (!(name in input.registry)) {
      errors.push(`Scheduler task without an authority row: ${name}`);
    }
  }
  for (const [name, entry] of Object.entries(input.registry)) {
    const runs = registered.get(name);
    if (runs === undefined) {
      errors.push(
        `Authority row for a task the scheduler registry lacks: ${name}`,
      );
    } else if (runs !== entry.module) {
      errors.push(
        `Declared module is not the one the registry runs: ${name} -> ${entry.module} (registry runs ${runs})`,
      );
    }
    if (entry.reason.trim() === "") {
      errors.push(`Authority row without a reason: ${name}`);
    }
    if (entry.authority === "unclassified") {
      members.push({ key: `task:${name}::unclassified`, reason: entry.reason });
      continue;
    }
    if (entry.authority !== "member-run") {
      continue;
    }
    if (entry.runActor === null) {
      members.push({
        key: `task:${name}::run-actor`,
        reason: REASONS.taskRunActor,
      });
    } else if (
      entry.runActor.module !== entry.module &&
      !callsInto(
        entry.module,
        input.readFile(entry.module) ?? "",
        entry.runActor.module,
      )
    ) {
      errors.push(
        `Declared run actor is off the task's call path: ${name} -> ${entry.module} calls nothing from ${entry.runActor.module}`,
      );
    } else if (
      !callsImported(
        input.readFile(entry.runActor.module) ?? "",
        entry.runActor.resolver,
      )
    ) {
      errors.push(
        `Declared run actor not found: ${name} -> ${entry.runActor.module} does not call ${entry.runActor.resolver}`,
      );
    }
    if (input.pinnedAllowed.has(entry.module)) {
      members.push({
        key: `task:${name}::pinned-handles::${entry.module}`,
        reason: REASONS.taskPinnedHandles,
      });
    }
  }
  return { errors, members };
};

const isProductionSource = (relativePath: string): boolean =>
  !/\.(test|type-test)\.[cm]?[jt]sx?$/u.test(relativePath) &&
  !/(^|\/)(__fixtures__|__tests__|test-fixtures|tests|node_modules|dist)\//u.test(
    relativePath,
  );

const readRepoFile = (relativePath: string): string | null => {
  const absolute = path.join(ROOT, relativePath);
  return existsSync(absolute) ? readFileSync(absolute, "utf-8") : null;
};

const treeInput = () => {
  const hostQueues = objectKeys(
    readRepoFile(HOST_TABLE_FILE) ?? "",
    HOST_TABLE_NAME,
  );
  if (hostQueues === null) {
    return panic(`${HOST_TABLE_NAME} not found in ${HOST_TABLE_FILE}`);
  }
  const workerQueues = new Map<string, readonly string[] | null>();
  const workerOwnershipErrors: string[] = [];
  const sources = Bun.spawnSync(
    [
      "git",
      "ls-files",
      "--cached",
      "--others",
      "--exclude-standard",
      "-z",
      "--",
      "apps",
      "packages",
      "scripts",
    ],
    { cwd: ROOT },
  );
  if (sources.exitCode !== 0) {
    return panic("Cannot enumerate BullMQ worker source files");
  }
  for (const file of sources.stdout
    .toString()
    .split("\0")
    .filter((filename) => /\.[cm]?[jt]sx?$/u.test(filename))
    .filter(isProductionSource)
    .toSorted()) {
    const source = readRepoFile(file) ?? "";
    workerOwnershipErrors.push(...rawWorkerImports(file, source));
    const queues = workerQueueNames(file, source, readRepoFile);
    if (queues !== undefined) {
      workerQueues.set(file, queues);
    }
  }
  const pinnedRow = OWNERSHIP.find(({ id }) => id === PINNED_HANDLES_ROW);
  if (pinnedRow?.enforcement.kind !== "import") {
    return panic(`ownership row ${PINNED_HANDLES_ROW} is not an import row`);
  }
  return {
    hostQueues,
    registry: QUEUE_AUTHORITY,
    memberRunQueues: MEMBER_RUN_QUEUES,
    workerQueues,
    workerOwnershipErrors,
    pinnedAllowed: new Set(
      pinnedRow.enforcement.allowed.map(({ path: file }) => file),
    ),
    readFile: readRepoFile,
  } satisfies AuditInput & { workerOwnershipErrors: string[] };
};

