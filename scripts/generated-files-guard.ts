const ROOT = new URL("..", import.meta.url);
const decode = (value: Uint8Array) => new TextDecoder().decode(value);
const splitPaths = (value: Uint8Array) =>
  decode(value).split("\0").filter(Boolean);
const isRecord = (value: unknown): value is Record<string, unknown> =>
  typeof value === "object" && value !== null && !Array.isArray(value);

export const isGeneratedCandidate = (file: string, header: string): boolean => {
  if (/\.(?:gen|generated)\.[^./]+$/u.test(file)) {
    return true;
  }
  return header
    .split("\n")
    .slice(0, 10)
    .some((line) => {
      const trimmed = line.trimStart();
      const comment = /^(?:\/\/|\/\*+|\*+|#|<!--)/u.exec(trimmed)?.[0];
      return (
        comment !== undefined &&
        /^(?:generated by\b|@generated\b|do not edit\.)/iu.test(
          trimmed.slice(comment.length).trimStart(),
        )
      );
    });
};

export const isRegisteredGeneratedFile = (file: string): boolean =>
  GENERATORS.some((generator) =>
    generator.outputs.some((glob) => matchesGeneratedGlob(glob, file)),
  ) || GUARD_A_EXCLUSIONS.some(({ glob }) => matchesGeneratedGlob(glob, file));

export const isUnregisteredGeneratedFile = (
  file: string,
  header: string,
): boolean =>
  isGeneratedCandidate(file, header) && !isRegisteredGeneratedFile(file);

const git = (args: string[]) => {
  const result = Bun.spawnSync(["git", ...args], {
    cwd: ROOT.pathname,
    stdout: "pipe",
    stderr: "pipe",
  });
  if (result.exitCode !== 0) {
    panic(`git ${args.at(0) ?? ""} failed: ${decode(result.stderr)}`);
  }
  return result.stdout;
};

const guardA = async () => {
  const files = splitPaths(git(["ls-files", "-z"]));
  const suspected = new Set(
    files.filter((file) => /\.(?:gen|generated)\.[^./]+$/u.test(file)),
  );
  const grep = Bun.spawnSync(
    [
      "git",
      "grep",
      "-IlziE",
      "@generated|generated by|do not edit\\.",
      "--",
      ".",
    ],
    { cwd: ROOT.pathname, stdout: "pipe", stderr: "pipe" },
  );
  if (grep.exitCode !== 0 && grep.exitCode !== 1) {
    panic(`git grep failed: ${decode(grep.stderr)}`);
  }
  for (const file of splitPaths(grep.stdout)) {
    suspected.add(file);
  }
  const unregistered: string[] = [];
  for (const file of suspected) {
    const header = await Bun.file(new URL(file, ROOT)).slice(0, 4096).text();
    if (isUnregisteredGeneratedFile(file, header)) {
      unregistered.push(file);
    }
  }
  if (unregistered.length > 0) {
    panic(
      `Unregistered generated files:\n${unregistered.toSorted().join("\n")}`,
    );
  }
  console.log(`Guard A: ${suspected.size} candidates registered or excluded`);
};

export const routeGeneratorVersionsMatch = (
  direct: unknown,
  pluginVersion: unknown,
  resolved: unknown,
): boolean =>
  typeof direct === "string" &&
  typeof pluginVersion === "string" &&
  direct === pluginVersion &&
  resolved === `@tanstack/router-generator@${direct}`;

export const checkRouteGeneratorVersion = async (root = ROOT) => {
  const webPackage: unknown = await Bun.file(
    new URL("apps/web/package.json", root),
  ).json();
  const lock: unknown = Bun.JSONC.parse(
    await Bun.file(new URL("bun.lock", root)).text(),
  );
  if (
    !isRecord(webPackage) ||
    !isRecord(webPackage["devDependencies"]) ||
    !isRecord(lock) ||
    !isRecord(lock["packages"])
  ) {
    panic("Cannot read web dependencies or Bun lockfile");
  }
  const direct = webPackage["devDependencies"]["@tanstack/router-generator"];
  const script = Bun.file(
    new URL("apps/web/scripts/generate-route-tree.ts", root),
  );
  if (!(await script.exists())) {
    panic("The route-tree generator script is missing");
  }
  if (typeof direct !== "string") {
    panic("The direct router-generator pin is missing");
  }
  const plugin = lock["packages"]["@tanstack/router-plugin"];
  const generator = lock["packages"]["@tanstack/router-generator"];
  if (
    !Array.isArray(plugin) ||
    !isRecord(plugin[2]) ||
    !isRecord(plugin[2]["dependencies"]) ||
    !Array.isArray(generator)
  ) {
    panic("Cannot resolve TanStack router generator from bun.lock");
  }
  const pluginVersion = plugin[2]["dependencies"]["@tanstack/router-generator"];
  const resolved = generator[0];
  if (!routeGeneratorVersionsMatch(direct, pluginVersion, resolved)) {
    panic(
      "The direct router-generator pin must equal the router-plugin version resolved in bun.lock",
    );
  }
};

const checkManifest = async () => {
  const ids = new Set<string>();
  for (const generator of orderGenerators(GENERATORS)) {
    if (
      ids.has(generator.id) ||
      generator.outputs.length === 0 ||
      generator.inputs.length === 0 ||
      generator.write.length === 0
    ) {
      panic(`Invalid generator entry: ${generator.id}`);
    }
    ids.add(generator.id);
    if (
      generator.check === null &&
      !(generator.checkedBy?.trim() || generator.unchecked?.trim())
    ) {
      panic(`Generator ${generator.id} has no check or unchecked reason`);
    }
    for (const block of generator.blocks ?? []) {
      if (
        !generator.outputs.some((glob) =>
          matchesGeneratedGlob(glob, block.path),
        )
      ) {
        panic(`Block ${block.path} is outside ${generator.id} outputs`);
      }
      const contents = await Bun.file(new URL(block.path, ROOT)).text();
      const begin = contents.indexOf(block.begin);
      const end = contents.indexOf(block.end);
      if (
        begin === -1 ||
        end <= begin ||
        contents.includes(block.begin, begin + 1) ||
        contents.includes(block.end, end + 1)
      ) {
        panic(`Block markers are missing or repeated: ${block.path}`);
      }
    }
  }
  for (const generator of GENERATORS) {
    for (const dependency of generator.after) {
      if (!ids.has(dependency)) {
        panic(`Generator ${generator.id} orders after unknown ${dependency}`);
      }
    }
  }
  orderGenerators(GENERATORS);
  for (const exclusion of GUARD_A_EXCLUSIONS) {
    if (exclusion.reason.trim() === "") {
      panic(`Guard A exclusion ${exclusion.glob} needs a reason`);
    }
  }
  await checkRouteGeneratorVersion();
  const censusFailures = generatorInputCensus(GENERATORS);
  if (censusFailures.length > 0) {
    panic(`Generator input census failed:\n${censusFailures.join("\n")}`);
  }
  console.log(`Manifest: ${GENERATORS.length} generator families`);
};

const packageScript = (directory: string, name: string): string => {
  const manifest: unknown = JSON.parse(
    readFileSync(path.join(ROOT.pathname, directory, "package.json"), "utf-8"),
  );
  const scripts = isRecord(manifest) ? manifest["scripts"] : undefined;
  const command = isRecord(scripts) ? scripts[name] : undefined;
  if (typeof command !== "string") {
    panic(`Cannot resolve package script ${directory}:${name}`);
  }
  return command;
};

const commandModules = (command: readonly string[], base = "."): string[] => {
  const joined = command.join(" ");
  const cwdMatch = /\bbun\s+--cwd(?:=|\s+)([^\s]+)\s+(?:run\s+)?([^\s;&|]+)/gu;
  const rootRunMatch = /\bbun\s+run\s+([^\s;&|]+)/gu;
  const fileMatch =
    /\bbun\s+(?!run\b|--cwd\b)(?:--[^\s]+\s+)*([^\s;&|]+\.[cm]?[jt]sx?)/gu;
  const modules: string[] = [];
  const cwdRanges: (readonly [number, number])[] = [];
  const cwdAt = (index: number) => {
    let directory = base;
    for (const match of joined
      .slice(0, index)
      .matchAll(/(?:^|[;&|]\s*)cd\s+([^\s;&|]+)/gu)) {
      directory = path.posix.normalize(
        path.posix.join(directory, match[1] ?? ""),
      );
    }
    return directory;
  };
  for (const match of joined.matchAll(cwdMatch)) {
    cwdRanges.push([match.index, match.index + match[0].length]);
    const directory = path.posix.normalize(
      path.posix.join(
        cwdAt(match.index),
        match[1] ?? panic("Missing command cwd"),
      ),
    );
    const target = match[2] ?? panic("Missing cwd command target");
    if (/\.[cm]?[jt]sx?$/u.test(target)) {
      modules.push(path.posix.join(directory, target));
    } else {
      modules.push(
        ...commandModules([packageScript(directory, target)], directory),
      );
    }
  }
  for (const match of joined.matchAll(rootRunMatch)) {
    if (
      cwdRanges.some(
        ([start, end]) => match.index >= start && match.index < end,
      )
    ) {
      continue;
    }
    const name = match[1] ?? panic("Missing root script name");
    if (/\.[cm]?[jt]sx?$/u.test(name)) {
      modules.push(
        path.posix.normalize(path.posix.join(cwdAt(match.index), name)),
      );
    } else {
      modules.push(...commandModules([packageScript(".", name)]));
    }
  }
  for (const match of joined.matchAll(fileMatch)) {
    if (
      cwdRanges.some(
        ([start, end]) => match.index >= start && match.index < end,
      )
    ) {
      continue;
    }
    const file = match[1];
    if (file !== undefined && !file.startsWith("-")) {
      modules.push(
        path.posix.normalize(path.posix.join(cwdAt(match.index), file)),
      );
    }
  }
  // Every `bun` invocation must resolve to modules: `--filter <package>
  // <script>` through that workspace's package script, the forms above as
  // matched. Any other form fails, so the census never skips a command.
  const tokens = joined.split(/\s+/u);
  for (const [index, token] of tokens.entries()) {
    if (token !== "bun") {
      continue;
    }
    const next = tokens[index + 1] ?? "";
    if (next === "--filter" || next.startsWith("--filter=")) {
      const name =
        next === "--filter"
          ? tokens[index + 2]
          : next.slice("--filter=".length);
      let scriptIndex = next === "--filter" ? index + 3 : index + 2;
      if (tokens[scriptIndex] === "run") {
        scriptIndex += 1;
      }
      const script = tokens[scriptIndex];
      if (name === undefined || script === undefined) {
        panic(`Census cannot resolve the command: ${joined}`);
      }
      const directory = workspaceDirectory(name);
      modules.push(
        ...commandModules([packageScript(directory, script)], directory),
      );
      continue;
    }
    const resolved =
      BUN_BUILTIN_COMMANDS.has(next) ||
      next === "run" ||
      next.startsWith("--cwd") ||
      tokens
        .slice(index + 1)
        .some((argument) => /\.[cm]?[jt]sx?$/u.test(argument));
    if (!resolved) {
      panic(`Census cannot resolve the command: ${joined}`);
    }
  }
  return [...new Set(modules)];
};

/**
 * Bun's own subcommands that run no repository module (the formatter reads
 * only its configuration). Extend deliberately: an unlisted form fails.
 */
const BUN_BUILTIN_COMMANDS: ReadonlySet<string> = new Set(["fmt"]);

/** The workspace directory of a package, by its manifest name. */
const workspaceDirectory = (name: string): string => {
  for (const manifest of new Bun.Glob(
    "{apps,packages}/*/package.json",
  ).scanSync({ cwd: ROOT.pathname })) {
    const parsed: unknown = JSON.parse(
      readFileSync(path.join(ROOT.pathname, manifest), "utf-8"),
    );
    if (
      typeof parsed === "object" &&
      parsed !== null &&
      "name" in parsed &&
      parsed.name === name
    ) {
      return path.posix.dirname(manifest);
    }
  }
  return panic(`No workspace package named ${name}`);
};

