// Writes scripts/guard-rollouts.gen.ts: one static import per
// scripts/guard-rollouts/<id>.ts, sorted by id. Static imports keep the
// rollout graph enumerable for offline checks and Node-loaded lint plugins.
//   --write  overwrite the manifest
//   --check  exit 1 when the committed manifest drifted
import { panic } from "better-result";
import { readdirSync } from "node:fs";
import path from "node:path";

import {
  formattedLikeRepository,
  writeOrCheckArtifacts,
} from "./generated-artifacts.ts";

const ROOT = path.resolve(import.meta.dirname, "..");
// Spelled here, not imported from guard-rollout-policy.ts: that module loads
// the manifest this script repairs.
const ROLLOUT_DIRECTORY = "scripts/guard-rollouts";
const GUARD_ROLLOUT_MANIFEST = "scripts/guard-rollouts.gen.ts";

// Each segment starts with a letter, so the camel-case import name maps back to
// exactly one id and the object key iterates in insertion order.
const ROLLOUT_FILE = /^([a-z][a-z0-9]*(?:-[a-z][a-z0-9]*)*)\.ts$/u;

const identifier = (id: string) =>
  id.replaceAll(/-([a-z])/gu, (_, next) => next.toUpperCase());

export const renderGuardRolloutManifest = (
  files: readonly string[],
): string => {
  const ids = files
    .toSorted()
    .map(
      (file) =>
        ROLLOUT_FILE.exec(file)?.[1] ??
        panic(`guard rollout file must be <kebab-case-id>.ts: ${file}`),
    );
  return [
    "// Generated by scripts/generate-guard-rollouts.ts. Do not edit.",
    ...ids.map(
      (id) => `import ${identifier(id)} from "./guard-rollouts/${id}.ts";`,
    ),
    "",
    "export const GUARD_ROLLOUT_FILES = {",
    ...ids.map((id) => `  ${JSON.stringify(id)}: ${identifier(id)},`),
    "};",
    "",
  ].join("\n");
};

if (import.meta.main) {
  const write = process.argv.includes("--write");
  if (!write && !process.argv.includes("--check")) {
    panic("Usage: bun scripts/generate-guard-rollouts.ts --write|--check");
  }
  const contents = await formattedLikeRepository(
    renderGuardRolloutManifest(readdirSync(path.join(ROOT, ROLLOUT_DIRECTORY))),
    ".ts",
  );
  process.exitCode = await writeOrCheckArtifacts(
    [{ path: path.join(ROOT, GUARD_ROLLOUT_MANIFEST), contents }],
    { matched: "the rollout directory", write },
  );
}
