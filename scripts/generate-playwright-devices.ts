import { panic } from "better-result";
import { execFileSync } from "node:child_process";
import { readFileSync } from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";
import * as v from "valibot";

import { parseSource, walk } from "../packages/scripts/src/syntax-tree";
import {
  formattedLikeRepository,
  writeOrCheckArtifacts,
} from "./generated-artifacts";

const ROOT = path.resolve(import.meta.dirname, "..");
export const DEVICE_OUTPUT = "packages/playwright-tools/src/devices.gen.ts";
const DEVICE_OWNER = "@stll/playwright-tools/devices";

export const usedPlaywrightDevices = (root = ROOT) => {
  const files = execFileSync(
    "git",
    [
      "ls-files",
      "-z",
      "--",
      "apps/**/playwright*.config.*",
      "packages/**/playwright*.config.*",
      "packages/playwright-tools/src/marketing-config.ts",
    ],
    { cwd: root, encoding: "utf-8" },
  )
    .split("\0")
    .filter(Boolean);
  const names = new Set<string>();
  for (const file of files) {
    const source = parseSource(
      file,
      readFileSync(path.join(root, file), "utf-8"),
    );
    const bindings = new Set<string>();
    for (const statement of source.program.body) {
      if (
        statement.type !== "ImportDeclaration" ||
        !["@playwright/test", DEVICE_OWNER, "./devices"].includes(
          statement.source.value,
        )
      ) {
        continue;
      }
      for (const specifier of statement.specifiers) {
        if (
          specifier.type === "ImportSpecifier" &&
          specifier.imported.type === "Identifier" &&
          specifier.imported.name === "devices"
        ) {
          bindings.add(specifier.local.name);
        }
      }
    }
    walk(source.program, (node) => {
      if (
        node.type !== "MemberExpression" ||
        node.object.type !== "Identifier" ||
        !bindings.has(node.object.name)
      ) {
        return;
      }
      if (
        !node.computed ||
        node.property.type !== "Literal" ||
        typeof node.property.value !== "string"
      ) {
        panic(`Device preset name must be literal in ${file}`);
      }
      names.add(node.property.value);
    });
  }
  if (names.size === 0) {
    panic("No configured device presets");
  }
  return [...names].toSorted();
};

const frozenDataExpression = (value: unknown): string => {
  if (
    value === null ||
    typeof value === "string" ||
    typeof value === "boolean" ||
    (typeof value === "number" && Number.isFinite(value))
  ) {
    return JSON.stringify(value);
  }
  if (Array.isArray(value)) {
    return `Object.freeze([${value.map(frozenDataExpression).join(",")} ] as const)`;
  }
  if (
    typeof value !== "object" ||
    value === null ||
    (Object.getPrototypeOf(value) !== Object.prototype &&
      Object.getPrototypeOf(value) !== null)
  ) {
    return panic("Device descriptor must contain plain JSON data");
  }
  const properties = Reflect.ownKeys(value).map((key) => {
    const descriptor = Object.getOwnPropertyDescriptor(value, key);
    if (
      typeof key !== "string" ||
      descriptor === undefined ||
      !descriptor.enumerable ||
      !("value" in descriptor)
    ) {
      return panic("Device descriptor properties must be enumerable JSON data");
    }
    const entry: unknown = descriptor.value;
    const property =
      key === "__proto__" ? `[${JSON.stringify(key)}]` : JSON.stringify(key);
    return `${property}:${frozenDataExpression(entry)}`;
  });
  return `Object.freeze({${properties.join(",")}} as const)`;
};

export const configuredPlaywrightDevices = (root = ROOT) => {
  // Resolve the SDK declared by the package that owns the generated data.
  const require = createRequire(
    path.join(root, "packages/playwright-tools/package.json"),
  );
  const sdk: unknown = require("@playwright/test");
  if ((typeof sdk !== "object" || sdk === null) && typeof sdk !== "function") {
    panic("Cannot read Playwright's public device export");
  }
  const presets = v.parse(
    v.record(v.string(), v.unknown()),
    Reflect.get(sdk, "devices"),
  );
  return Object.fromEntries(
    usedPlaywrightDevices(root).map((name) => {
      const preset = presets[name];
      if (preset === undefined) {
        panic(`Unknown Playwright device preset: ${name}`);
      }
      return [name, preset];
    }),
  );
};

export const renderPlaywrightDevices = async (root = ROOT) =>
  formattedLikeRepository(
    `// Generated by scripts/generate-playwright-devices.ts from Playwright device descriptors (Apache-2.0).\n// Do not edit by hand.\nexport const devices = ${frozenDataExpression(configuredPlaywrightDevices(root))};\n`,
    ".ts",
  );

if (import.meta.main) {
  process.exitCode = await writeOrCheckArtifacts(
    [
      {
        path: path.join(ROOT, DEVICE_OUTPUT),
        contents: await renderPlaywrightDevices(),
      },
    ],
    {
      write: process.argv.includes("--write"),
      matched: "the configured public Playwright device descriptors",
    },
  );
}
