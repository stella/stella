import { panic } from "better-result";
import path from "node:path";

import { caseLawPublicationFunctionSql } from "../apps/api/src/lib/case-law/published-decisions-sql";

const PREVIOUS_MIGRATION = "20260916110000_published_statute_citation_counts";
const OUTPUT_MIGRATION = "20261010212100_case_law_publication_filter";
const migrationRoot = path.resolve(import.meta.dir, "../apps/api/drizzle");
const previous = await Bun.file(
  path.join(migrationRoot, PREVIOUS_MIGRATION, "migration.sql"),
).text();

const statement = (prefix: string): string => {
  const found = previous
    .split("--> statement-breakpoint")
    .map((part) => part.slice(part.indexOf(prefix)).trim())
    .find((part) => part.startsWith(prefix));
  return found ?? panic(`Missing migration statement: ${prefix}`);
};

const membership = statement(
  'CREATE OR REPLACE FUNCTION "sync_case_law_statute_citation_membership"()',
).replace(
  'case_law_statute_citation_is_published(decision."metadata")',
  'case_law_statute_citation_is_published(decision."metadata", decision."redacted_at")',
);
const refresh = statement(
  'CREATE FUNCTION "refresh_case_law_statute_citation_memberships"',
)
  .replace("CREATE FUNCTION", "CREATE OR REPLACE FUNCTION")
  .replace(
    "case_law_statute_citation_is_published(metadata)",
    "case_law_statute_citation_is_published(metadata, redacted_at)",
  );
const trigger = statement(
  'CREATE TRIGGER "case_law_decision_statute_citation_membership_source"',
)
  .replace(
    '"source_id", "country", "metadata"',
    '"source_id", "country", "metadata", "redacted_at"',
  )
  .replaceAll(
    "case_law_statute_citation_is_published(OLD.metadata)",
    "case_law_statute_citation_is_published(OLD.metadata, OLD.redacted_at)",
  )
  .replaceAll(
    "case_law_statute_citation_is_published(NEW.metadata)",
    "case_law_statute_citation_is_published(NEW.metadata, NEW.redacted_at)",
  );

const output = `${[
  `-- Generated by scripts/generate-case-law-publication-migration.ts.\n-- requires: ${PREVIOUS_MIGRATION}\nSET LOCAL lock_timeout = '5s';`,
  "SET LOCAL statement_timeout = '30s';",
  caseLawPublicationFunctionSql(),
  membership,
  refresh,
  '-- stella-migration-safety: reviewed drop-object - Replace the transition trigger atomically.\nDROP TRIGGER "case_law_decision_statute_citation_membership_source" ON "case_law_decisions";',
  trigger,
  '-- stella-migration-safety: reviewed drop-object - All materializers use the current two-column policy.\nDROP FUNCTION "case_law_statute_citation_is_published"(jsonb);',
  "UPDATE case_law_statute_citation_count_state\nSET status = 'building', cursor_decision_id = NULL, updated_at = DEFAULT\nWHERE key = 'global';",
].join("--> statement-breakpoint\n\n")}\n`;
const outputFile = Bun.file(
  path.join(migrationRoot, OUTPUT_MIGRATION, "migration.sql"),
);
if (process.argv.includes("--check")) {
  if (!(await outputFile.exists()) || (await outputFile.text()) !== output) {
    panic("Case-law publication migration differs from its owner");
  }
} else {
  await Bun.write(outputFile, output);
}
