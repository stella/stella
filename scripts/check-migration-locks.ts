#!/usr/bin/env bun
import { panic } from "better-result";
import { spawnSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

import { MIGRATION_LOCK_BASELINE } from "./migration-lock-baseline";
import {
  checkMigrationLocks,
  migrationLockPairs,
  type MigrationSource,
} from "./migration-lock-census";
import { censusOnlineDdlSource } from "./online-ddl-lock-census";

const ROOT = path.resolve(import.meta.dir, "..");
const BASELINE_PATH = "scripts/migration-lock-baseline.ts";

const git = (args: string[]) =>
  spawnSync("git", args, {
    cwd: ROOT,
    encoding: "utf-8",
    maxBuffer: 64 * 1024 * 1024,
  });
const gitText = (args: string[]) => {
  const result = git(args);
  if (result.status !== 0) {
    panic(`git ${String(args.at(0))} failed: ${result.stderr}`);
  }
  return result.stdout;
};

export const readMigrationLockSources = (): MigrationSource[] =>
  [...new Bun.Glob("apps/api/drizzle/**/*.sql").scanSync(ROOT)]
    .toSorted()
    .map((file) => ({
      file,
      source: readFileSync(path.join(ROOT, file), "utf-8"),
    }));

export const historicalLockSources = (revision: string): MigrationSource[] =>
  gitText(["ls-tree", "-r", "--name-only", revision, "apps/api/drizzle"])
    .trim()
    .split("\n")
    .filter((file) => file.endsWith(".sql"))
    .map((file) => ({
      file,
      source: gitText(["show", `${revision}:${file}`]),
    }));

export const renderLockBaseline = (
  revision: string,
  sources: readonly MigrationSource[],
) => {
  const entries = migrationLockPairs(sources);
  return `// Generated by bun scripts/check-migration-locks.ts --write-baseline.\n// The revision is fixed: regeneration never grandfathers new migrations.\nimport type { LockBaselineEntry } from "./migration-lock-census";\n\nexport const MIGRATION_LOCK_BASELINE = ${JSON.stringify({ revision, entries }, null, 2)} satisfies { revision: string; entries: readonly LockBaselineEntry[] };\n`;
};

const main = () => {
  if (Bun.argv.includes("--write-baseline")) {
    writeFileSync(
      path.join(ROOT, BASELINE_PATH),
      renderLockBaseline(
        MIGRATION_LOCK_BASELINE.revision,
        historicalLockSources(MIGRATION_LOCK_BASELINE.revision),
      ),
    );
    return;
  }
  const baseIndex = Bun.argv.indexOf("--base");
  if (baseIndex !== -1) {
    const base = Bun.argv.at(baseIndex + 1);
    if (!base) {
      panic("--base requires a git revision");
    }
    const baseSnapshot = git(["show", `${base}:${BASELINE_PATH}`]);
    // Normal checks need only the PR base, including in shallow CI checkouts.
    // Regeneration reads the fixed historical revision, never today's main.
    if (baseSnapshot.status === 0) {
      if (
        baseSnapshot.stdout !==
        readFileSync(path.join(ROOT, BASELINE_PATH), "utf-8")
      ) {
        panic("The historical migration lock baseline is immutable");
      }
    } else if (
      git([
        "merge-base",
        "--is-ancestor",
        MIGRATION_LOCK_BASELINE.revision,
        base,
      ]).status !== 0
    ) {
      panic("Migration lock baseline must refer to merged history");
    }
  }
  const sources = readMigrationLockSources();
  const result = checkMigrationLocks({
    sources,
    baseline: MIGRATION_LOCK_BASELINE.entries,
  });
  const baselineFolders = new Set(
    MIGRATION_LOCK_BASELINE.entries.map(({ migration }) => migration),
  );
  const historical = sources.filter(({ file }) =>
    baselineFolders.has(file.split("/").at(3) ?? ""),
  );
  if (
    JSON.stringify(migrationLockPairs(historical)) !==
    JSON.stringify(MIGRATION_LOCK_BASELINE.entries)
  ) {
    result.errors.push(
      "Migration lock baseline drift; regenerate from its fixed historical revision and review the classified forms",
    );
  }
  const ownerPath = path.join(ROOT, "apps/api/src/db/online-ddl.ts");
  if (!existsSync(ownerPath)) {
    panic("Online DDL owner is missing");
  }
  result.errors.push(
    ...censusOnlineDdlSource(readFileSync(ownerPath, "utf-8")),
  );
  for (const mode of [...result.counts.keys()].toSorted()) {
    console.log(`${mode}: ${String(result.counts.get(mode))}`);
  }
  console.log(
    `Baseline: ${MIGRATION_LOCK_BASELINE.entries.length} migration/form pairs`,
  );
  if (result.errors.length > 0) {
    for (const error of result.errors) {
      console.error(error);
    }
    process.exitCode = 1;
  }
};

if (import.meta.main) {
  main();
}
