type EnvUsage = { file: string; line: number; name: string };

const ENV_NAME_PATTERN = /^[A-Z][A-Z0-9_]*$/u;
const SCRIPT_FILE_PATTERN = /\.[cm]?[jt]sx?$/u;

const findComputedEnvUsages = (file: string, text: string): EnvUsage[] => {
  if (!SCRIPT_FILE_PATTERN.test(file)) {
    return [];
  }

  const source = ts.createSourceFile(
    file,
    text,
    ts.ScriptTarget.Latest,
    true,
    file.endsWith("x") ? ts.ScriptKind.TSX : ts.ScriptKind.TS,
  );
  const constants = new Map<string, string>();
  type HelperReference =
    | { parameterIndex: number; type: "positional" }
    | {
        parameterIndex: number;
        propertyName: string;
        type: "object-property";
      };
  const helpers = new Map<string, HelperReference>();
  const usages: EnvUsage[] = [];

  const literalEnvName = (node: ts.Node | undefined) => {
    if (
      node &&
      (ts.isStringLiteral(node) || ts.isNoSubstitutionTemplateLiteral(node))
    ) {
      return ENV_NAME_PATTERN.test(node.text) ? node.text : undefined;
    }
    if (node && ts.isIdentifier(node)) {
      return constants.get(node.text);
    }
    return undefined;
  };

  const collectConstants = (node: ts.Node) => {
    if (ts.isVariableDeclaration(node) && ts.isIdentifier(node.name)) {
      const value = literalEnvName(node.initializer);
      if (value) {
        constants.set(node.name.text, value);
      }
    }
    ts.forEachChild(node, collectConstants);
  };
  collectConstants(source);

  const envArgument = (node: ts.Node) => {
    if (!ts.isElementAccessExpression(node)) {
      return undefined;
    }
    const envAccess = node.expression;
    if (
      !ts.isPropertyAccessExpression(envAccess) ||
      envAccess.name.text !== "env" ||
      !ts.isIdentifier(envAccess.expression) ||
      (envAccess.expression.text !== "process" &&
        envAccess.expression.text !== "Bun")
    ) {
      return undefined;
    }
    return node.argumentExpression;
  };

  type HelperDeclaration =
    | ts.ArrowFunction
    | ts.FunctionDeclaration
    | ts.FunctionExpression;

  const isHelperDeclaration = (node: ts.Node): node is HelperDeclaration =>
    ts.isArrowFunction(node) ||
    ts.isFunctionDeclaration(node) ||
    ts.isFunctionExpression(node);

  // `ts.Node.parent` is declared non-optional but is undefined once the walk
  // reaches the source file. Reading it through a nullable view keeps the
  // termination check meaningful instead of narrowing it away.
  const parentOf = (node: ts.Node): ts.Node | undefined => {
    const { parent }: { parent?: ts.Node } = node;
    return parent;
  };

  const helperName = (node: HelperDeclaration) => {
    if (ts.isFunctionDeclaration(node) && node.name) {
      return node.name.text;
    }
    if (
      (ts.isArrowFunction(node) || ts.isFunctionExpression(node)) &&
      ts.isVariableDeclaration(node.parent) &&
      ts.isIdentifier(node.parent.name)
    ) {
      return node.parent.name.text;
    }
    return undefined;
  };

  const bindingPropertyName = (element: ts.BindingElement) => {
    if (element.propertyName === undefined && ts.isIdentifier(element.name)) {
      return element.name.text;
    }
    if (
      element.propertyName &&
      (ts.isIdentifier(element.propertyName) ||
        ts.isStringLiteral(element.propertyName))
    ) {
      return element.propertyName.text;
    }
    return undefined;
  };

  const helperReference = (
    declaration: HelperDeclaration,
    argumentName: string,
  ): HelperReference | undefined => {
    for (const [
      parameterIndex,
      parameter,
    ] of declaration.parameters.entries()) {
      if (
        ts.isIdentifier(parameter.name) &&
        parameter.name.text === argumentName
      ) {
        return { parameterIndex, type: "positional" };
      }
      if (!ts.isObjectBindingPattern(parameter.name)) {
        continue;
      }
      const element = parameter.name.elements.find(
        ({ name }) => ts.isIdentifier(name) && name.text === argumentName,
      );
      if (!element) {
        continue;
      }
      const propertyName = bindingPropertyName(element);
      if (propertyName) {
        return { parameterIndex, propertyName, type: "object-property" };
      }
    }
    return undefined;
  };

  const collectReads = (node: ts.Node) => {
    const argument = envArgument(node);
    if (argument && ts.isIdentifier(argument)) {
      const constantName = constants.get(argument.text);
      if (constantName) {
        usages.push({
          file,
          line:
            source.getLineAndCharacterOfPosition(argument.getStart(source))
              .line + 1,
          name: constantName,
        });
      } else {
        let parent = parentOf(node);
        while (parent && !isHelperDeclaration(parent)) {
          parent = parentOf(parent);
        }
        if (parent && isHelperDeclaration(parent)) {
          const name = helperName(parent);
          const reference = helperReference(parent, argument.text);
          if (name && reference) {
            helpers.set(name, reference);
          }
        }
      }
    }
    ts.forEachChild(node, collectReads);
  };
  collectReads(source);

  const propertyName = (node: ts.PropertyName) =>
    ts.isIdentifier(node) || ts.isStringLiteral(node) ? node.text : undefined;

  const referencedCallArgument = (
    call: ts.CallExpression,
    reference: HelperReference,
  ) => {
    const argument = call.arguments.at(reference.parameterIndex);
    if (reference.type === "positional") {
      return argument;
    }
    if (!argument || !ts.isObjectLiteralExpression(argument)) {
      return undefined;
    }
    for (const property of argument.properties) {
      if (
        ts.isPropertyAssignment(property) &&
        propertyName(property.name) === reference.propertyName
      ) {
        return property.initializer;
      }
      if (
        ts.isShorthandPropertyAssignment(property) &&
        property.name.text === reference.propertyName
      ) {
        return property.name;
      }
    }
    return undefined;
  };

  const collectCalls = (node: ts.Node) => {
    if (ts.isCallExpression(node) && ts.isIdentifier(node.expression)) {
      const reference = helpers.get(node.expression.text);
      if (reference) {
        const argument = referencedCallArgument(node, reference);
        const name = literalEnvName(argument);
        if (name && argument) {
          usages.push({
            file,
            line:
              source.getLineAndCharacterOfPosition(argument.getStart(source))
                .line + 1,
            name,
          });
        }
      }
    }
    ts.forEachChild(node, collectCalls);
  };
  collectCalls(source);

  return usages;
};

export const findEnvUsages = (file: string, text: string): EnvUsage[] => {
  const usages = findComputedEnvUsages(file, text);
  let patterns = STATIC_ENV_PATTERNS;
  if (file.endsWith(".rs")) {
    patterns = STATIC_RUST_ENV_PATTERNS;
  } else if (file.includes("Dockerfile")) {
    patterns = [
      ...STATIC_ENV_PATTERNS,
      DEPLOYMENT_ENV_PATTERN,
      BARE_DOCKER_ENV_PATTERN,
    ];
  } else if (/\.(?:sh|ya?ml)$/u.test(file)) {
    patterns = [...STATIC_ENV_PATTERNS, DEPLOYMENT_ENV_PATTERN];
  }
  for (const pattern of patterns) {
    for (const match of text.matchAll(pattern)) {
      const name = match.at(1);
      if (!name) {
        continue;
      }
      usages.push({
        file,
        line: text.slice(0, match.index).split("\n").length,
        name,
      });
    }
  }
  return usages;
};

const isKnownEnvName = (name: string) =>
  ENV_CATALOG.some((entry) => entry.name === name) ||
  MANUAL_SCHEMA_KEYS.has(name) ||
  TOOLING_ENV_KEYS.has(name) ||
  DEPLOYMENT_ENV_KEYS.has(name) ||
  AMBIENT_ENV_KEYS.has(name) ||
  /^(?:ACTIONS_|BUN_|GITHUB_|INPUT_|npm_|RAILWAY_|RUNNER_)/u.test(name);

const auditEnvironment = async () => {
  const files = new Set<string>();
  for (const pattern of AUDIT_GLOBS) {
    const glob = new Bun.Glob(pattern);
    // eslint-disable-next-line no-await-in-loop -- each glob is a lazy async iterator
    for await (const file of glob.scan({ cwd: REPO_ROOT, onlyFiles: true })) {
      if (!isIgnoredAuditPath(file) && !AUDIT_IGNORE_FILES.has(file)) {
        files.add(file);
      }
    }
  }
  const unknown: EnvUsage[] = [];
  for (const file of files) {
    const text = readFileSync(path.join(REPO_ROOT, file), "utf-8");
    unknown.push(
      ...findEnvUsages(file, text).filter(({ name }) => !isKnownEnvName(name)),
    );
  }
  const unique = [
    ...new Map(
      unknown.map((usage) => [
        `${usage.file}:${usage.line}:${usage.name}`,
        usage,
      ]),
    ).values(),
  ];
  if (unique.length === 0) {
    console.log("All static environment-variable reads are cataloged.");
    return true;
  }
  for (const usage of unique) {
    console.error(`${usage.file}:${usage.line}: uncataloged env ${usage.name}`);
  }
  return false;
};

const sourceLabel = (name: string, fileValues: Record<string, string>) => {
  if (process.env[name] !== undefined) {
    return "process";
  }
  if (fileValues[name] !== undefined) {
    return "file";
  }
  return "default/unset";
};

export const formatEnvValue = (entry: EnvCatalogEntry, value: unknown) => {
  if (value === undefined) {
    return "<unset>";
  }
  if (entry.exposure === ENV_EXPOSURE.secret) {
    return "<redacted>";
  }
  return JSON.stringify(value);
};

export const formatEnvIssue = (issue: v.BaseIssue<unknown>) => {
  const key = issue.path
    ?.map((item) => item.key)
    .find((itemKey) => typeof itemKey === "string");
  if (typeof key !== "string") {
    return "Invalid environment configuration.";
  }
  const entry = ENV_CATALOG.find(({ name }) => name === key);
  if (entry?.exposure !== ENV_EXPOSURE.public) {
    return `${key}: invalid ${entry?.exposure ?? ENV_EXPOSURE.secret} value.`;
  }
  return `${key}: ${issue.message}`;
};

const ENV_APP = {
  api: "api",
  collab: "collab",
  web: "web",
} as const;

type EnvApp = (typeof ENV_APP)[keyof typeof ENV_APP];
type DoctorInput = Record<string, string | undefined>;
type DoctorValues = Record<string, unknown>;
type DoctorValidationResult =
  | { status: "invalid"; issues: string[]; values: DoctorValues }
  | { status: "valid"; values: DoctorValues };

const isEnvApp = (value: string): value is EnvApp =>
  Object.values(ENV_APP).some((app) => app === value);

export const normalizeEmptyEnvironment = (input: DoctorInput): DoctorInput => {
  const normalized: DoctorInput = {};
  for (const [name, value] of Object.entries(input)) {
    normalized[name] =
      value === "" && !EMPTY_VALUE_VARIABLES.has(name) ? undefined : value;
  }
  return normalized;
};

const validateSchema = (
  schema: Record<string, v.GenericSchema>,
  input: DoctorInput,
): DoctorValidationResult => {
  const result = v.safeParse(v.object(schema), input);
  if (!result.success) {
    return {
      status: "invalid",
      issues: result.issues.map(formatEnvIssue),
      values: input,
    };
  }
  return { status: "valid", values: { ...input, ...result.output } };
};

const validateApiEnvironment = (input: DoctorInput): DoctorValidationResult => {
  // Mirrors apps/api/src/env-base.ts: placeholders go first, so the doctor
  // and the runtime derive DATABASE_URL from the same values.
  const placeholders = resolveApiEnvironmentPlaceholders({
    schema: API_ENV_SCHEMA,
    values: input,
  });
  if (placeholders.violation !== null) {
    return {
      status: "invalid",
      issues: [placeholders.violation],
      values: input,
    };
  }
  const configured = placeholders.runtimeEnv;

  const databaseUrl = Result.try(() => resolveDatabaseUrl(configured));
  if (Result.isError(databaseUrl)) {
    return {
      status: "invalid",
      issues: ["DATABASE_URL: invalid database component settings."],
      values: configured,
    };
  }

  const nodeEnv = configured["NODE_ENV"];
  const nodeEnvKind = classifyNodeEnv(nodeEnv);
  if (nodeEnvKind === NODE_ENV_KIND.unknown) {
    return {
      status: "invalid",
      issues: [
        `NODE_ENV: "${nodeEnv}" is not one of ${KNOWN_NODE_ENVS.join(", ")}.`,
      ],
      values: configured,
    };
  }

  const runtimeInput = {
    ...configured,
    DATABASE_URL: databaseUrl.value,
    isDev: nodeEnvKind === NODE_ENV_KIND.local,
  };
  const parsed = v.safeParse(v.object(API_ENV_SCHEMA), runtimeInput);
  if (!parsed.success) {
    return {
      status: "invalid",
      issues: parsed.issues.map(formatEnvIssue),
      values: runtimeInput,
    };
  }

  const emailProvider = resolveEmailProvider(parsed.output);
  const output = { ...parsed.output, EMAIL_PROVIDER: emailProvider };
  const issues: string[] = [];
  const baseIssue = envBaseInvariantViolation(output);
  if (baseIssue !== null) {
    issues.push(baseIssue);
  }
  const documentProcessingIssue = documentProcessingEnvInvariantViolation({
    contentEncryptionKey: output.CONTENT_ENCRYPTION_KEY,
    nodeEnv,
    redisUrl: output.REDIS_URL,
  });
  if (documentProcessingIssue !== null) {
    issues.push(documentProcessingIssue);
  }
  const apiIssue = envApiInvariantViolation({ ...output, nodeEnv });
  if (apiIssue !== null) {
    issues.push(apiIssue);
  }
  const values = { ...runtimeInput, ...output };
  return issues.length === 0
    ? { status: "valid", values }
    : { status: "invalid", issues, values };
};

const validateWebEnvironment = (input: DoctorInput): DoctorValidationResult => {
  const result = v.safeParse(v.object(WEB_ENV_SCHEMA), input);
  if (!result.success) {
    return {
      status: "invalid",
      issues: result.issues.map(formatEnvIssue),
      values: input,
    };
  }
  const values = { ...input, ...result.output };
  const issue = envWebInvariantViolation(result.output);
  return issue === null
    ? { status: "valid", values }
    : { status: "invalid", issues: [issue], values };
};

