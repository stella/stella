const quoteEnvValue = (value: string) =>
  `"${value.replaceAll("\\", "\\\\").replaceAll('"', '\\"')}"`;

// Catalog entries are typed as `v.GenericSchema`, for which `getDefault`
// resolves to `void` even though it returns the schema's real default at
// runtime. Reading it through this helper makes the value `unknown`, so the
// narrowing at the call site is honest rather than dead code.
const schemaDefault = (schema: v.GenericSchema): unknown =>
  v.getDefault(schema);

export const exampleValueForCatalogEntry = (entry: EnvCatalogEntry) => {
  if (entry.example !== undefined) {
    return entry.example;
  }
  const fallback = schemaDefault(entry.schema);
  if (typeof fallback === "string" || typeof fallback === "number") {
    return String(fallback);
  }
  if (typeof fallback === "boolean") {
    return fallback ? "true" : "false";
  }
  return "";
};

const requirementLabel = (entry: EnvCatalogEntry) => {
  if (entry.requirement === "required") {
    return "Required";
  }
  if (entry.requirement === "conditional") {
    if (!entry.requirementNote) {
      panic(`Conditional environment entry ${entry.name} requires a note.`);
    }
    return `Conditionally required when ${entry.requirementNote}`;
  }
  if (entry.requirement === "defaulted") {
    return "Optional with a default";
  }
  return "Optional";
};

const wrapComment = (text: string, width = 76) => {
  const lines: string[] = [];
  let current = "";
  for (const word of text.split(/\s+/u)) {
    if (current.length === 0) {
      current = word;
      continue;
    }
    if (current.length + word.length + 1 <= width) {
      current += ` ${word}`;
      continue;
    }
    lines.push(`# ${current}`);
    current = word;
  }
  if (current.length > 0) {
    lines.push(`# ${current}`);
  }
  return lines;
};

type RenderEnvironmentEntriesOptions = {
  header?: string;
  isActive?: (entry: EnvCatalogEntry) => boolean;
  valueFor?: (entry: EnvCatalogEntry) => string;
};

export const renderEnvironmentEntries = (
  entries: EnvCatalogEntry[],
  {
    header = GENERATED_HEADER,
    isActive = ({ name }) => isActiveExampleEntry(name),
    valueFor = exampleValueForCatalogEntry,
  }: RenderEnvironmentEntriesOptions = {},
) => {
  const sections = Map.groupBy(entries, ({ section }) => section);
  const lines: string[] = [header];
  for (const [section, sectionEntries] of sections) {
    lines.push(
      `# --- ${section} ${"-".repeat(Math.max(1, 66 - section.length))}`,
    );
    for (const entry of sectionEntries) {
      const active = entry.requirement === "required" || isActive(entry);
      const prefix = active ? "" : "# ";
      lines.push(
        ...wrapComment(
          `[${entry.exposure}] ${requirementLabel(entry)}. ${entry.description}`,
        ),
        `${prefix}${entry.name}=${quoteEnvValue(valueFor(entry))}`,
        "",
      );
    }
  }
  return `${lines.join("\n").trimEnd()}\n`;
};

