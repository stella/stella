const checkExamples = () => {
  const stale = generatedExamples().filter(
    ({ content, path: examplePath }) =>
      !existsSync(examplePath) ||
      readFileSync(examplePath, "utf-8") !== content,
  );
  if (stale.length === 0) {
    console.log("Environment examples match their schemas.");
    return true;
  }
  for (const { path: examplePath } of stale) {
    console.error(`${path.relative(REPO_ROOT, examplePath)} is stale.`);
  }
  console.error("Run `bun run env:generate` and commit the result.");
  return false;
};

