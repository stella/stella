const ENV_MODE = {
  development: "development",
  production: "production",
  test: "test",
} as const;
type EnvMode = (typeof ENV_MODE)[keyof typeof ENV_MODE];

const isEnvMode = (value: string): value is EnvMode =>
  Object.values(ENV_MODE).some((mode) => mode === value);

type ResolveDoctorModeOptions = {
  app: EnvApp;
  nodeEnv: string | undefined;
  requestedMode: EnvMode | undefined;
};

export const resolveDoctorMode = ({
  app,
  nodeEnv,
  requestedMode,
}: ResolveDoctorModeOptions): EnvMode | undefined => {
  if (requestedMode) {
    return requestedMode;
  }
  if (nodeEnv && isEnvMode(nodeEnv)) {
    return nodeEnv;
  }
  return app === ENV_APP.web ? ENV_MODE.development : undefined;
};

export const doctorEnvFileNames = (nodeEnv: string | undefined) => {
  const names = [".env"];
  const mode = nodeEnv && isEnvMode(nodeEnv) ? nodeEnv : undefined;
  if (mode) {
    names.push(`.env.${mode}`);
  }
  names.push(".env.local");
  if (mode) {
    names.push(`.env.${mode}.local`);
  }
  return names;
};

export const validateDoctorEnvironment = (
  app: EnvApp,
  rawInput: DoctorInput,
): DoctorValidationResult =>
  ENV_APP_CONFIG[app].validate(normalizeEmptyEnvironment(rawInput));

const runDoctor = (app: EnvApp, mode: EnvMode | undefined) => {
  const { examplePath, owners } = ENV_APP_CONFIG[app];
  const envDirectory = path.dirname(examplePath);
  const baseEnvPath = path.join(envDirectory, ".env");
  const envPaths = doctorEnvFileNames(mode).map((name) =>
    path.join(envDirectory, name),
  );
  const existingEnvPaths = envPaths.filter(existsSync);
  const fileValues = parseEnvLayers(
    existingEnvPaths.map((envPath) => readFileSync(envPath, "utf-8")),
  );
  const validation = validateDoctorEnvironment(app, {
    ...fileValues,
    ...process.env,
  });
  const displayedEnvPaths = (
    existingEnvPaths.length > 0 ? existingEnvPaths : [baseEnvPath]
  ).map((envPath) => path.relative(REPO_ROOT, envPath));
  console.log(`Environment doctor: ${app} (${displayedEnvPaths.join(", ")})`);
  for (const entry of ENV_CATALOG.filter(
    ({ documented, owner }) => documented && owners.has(owner),
  )) {
    const value = validation.values[entry.name];
    console.log(
      `${entry.name}: ${formatEnvValue(entry, value)} [${sourceLabel(entry.name, fileValues)}; ${entry.exposure}]`,
    );
  }
  switch (validation.status) {
    case "valid":
      console.log(`${app}: valid`);
      return true;
    case "invalid":
      for (const issue of validation.issues) {
        console.error(issue);
      }
      return false;
    default: {
      const exhaustive: never = validation;
      return exhaustive;
    }
  }
};

const main = async () => {
  const command = process.argv.at(2);
  if (command === "generate") {
    generateExamples();
    return;
  }
  if (command === "check") {
    const examplesValid = checkExamples();
    const auditValid = await auditEnvironment();
    if (!(examplesValid && auditValid)) {
      process.exitCode = 1;
    }
    return;
  }
  if (command === "audit") {
    if (!(await auditEnvironment())) {
      process.exitCode = 1;
    }
    return;
  }
  if (command === "doctor") {
    const app = process.argv.at(3) ?? "api";
    const requestedMode = process.argv.at(4);
    if (
      !isEnvApp(app) ||
      (requestedMode !== undefined && !isEnvMode(requestedMode))
    ) {
      console.error(
        "Usage: bun run env:doctor [api|collab|web] [development|production|test]",
      );
      process.exitCode = 1;
      return;
    }
    const mode = resolveDoctorMode({
      app,
      nodeEnv: process.env.NODE_ENV,
      requestedMode,
    });
    if (!runDoctor(app, mode)) {
      process.exitCode = 1;
    }
    return;
  }
  console.error("Usage: env-tool.ts <generate|check|audit|doctor>");
  process.exitCode = 1;
};

if (import.meta.main) {
  await main();
}
