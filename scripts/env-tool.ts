const isEnvNameStart = (character: string | undefined) =>
  character !== undefined &&
  ((character >= "A" && character <= "Z") ||
    (character >= "a" && character <= "z") ||
    character === "_");

const isEnvNameCharacter = (character: string | undefined) =>
  isEnvNameStart(character) ||
  (character !== undefined && character >= "0" && character <= "9");

const findExpansionEnd = (value: string, fallbackStart: number) => {
  let nestedDepth = 0;
  for (let index = fallbackStart; index < value.length; index += 1) {
    if (
      value.at(index) === "$" &&
      value.at(index + 1) === "{" &&
      value.at(index - 1) !== "\\"
    ) {
      nestedDepth += 1;
      index += 1;
      continue;
    }
    if (value.at(index) !== "}") {
      continue;
    }
    if (nestedDepth === 0) {
      return index;
    }
    nestedDepth -= 1;
  }
  return -1;
};

type ExpandEnvReferencesOptions = {
  environment: NodeJS.ProcessEnv;
  value: string;
};

const expandEnvReferences = ({
  environment,
  value,
}: ExpandEnvReferencesOptions) => {
  const output: string[] = [];
  let index = 0;
  while (index < value.length) {
    const character = value.at(index);
    if (character === "\\" && value.at(index + 1) === "$") {
      output.push("$");
      index += 2;
      continue;
    }
    if (character !== "$") {
      output.push(character ?? "");
      index += 1;
      continue;
    }

    const braced = value.at(index + 1) === "{";
    const nameStart = index + (braced ? 2 : 1);
    if (!isEnvNameCharacter(value.at(nameStart))) {
      output.push("$");
      index += 1;
      continue;
    }
    let nameEnd = nameStart + 1;
    while (isEnvNameCharacter(value.at(nameEnd))) {
      nameEnd += 1;
    }
    const name = value.slice(nameStart, nameEnd);
    if (braced && value.slice(nameEnd, nameEnd + 2) === ":-") {
      const fallbackStart = nameEnd + 2;
      const fallbackEnd = findExpansionEnd(value, fallbackStart);
      if (fallbackEnd === -1) {
        output.push("$");
        index += 1;
        continue;
      }
      const fallback = value.slice(fallbackStart, fallbackEnd);
      if (/(?<!\\)\$\{/u.test(fallback)) {
        // Bun does not recursively parse braced fallbacks. Preserve the
        // unsupported expression so schema validation rejects it.
        output.push(value.slice(index, fallbackEnd + 1));
        index = fallbackEnd + 1;
        continue;
      }
      const current = environment[name];
      output.push(current ?? fallback);
      index = fallbackEnd + 1;
      continue;
    }
    if (braced && value.at(nameEnd) !== "}") {
      output.push("$");
      index += 1;
      continue;
    }

    output.push(environment[name] ?? "");
    index = nameEnd + (braced ? 1 : 0);
  }
  return output.join("");
};

export const parseEnvText = (
  text: string,
  ambientEnvironment: NodeJS.ProcessEnv = process.env,
) => {
  const values: Record<string, string> = {};
  const parsed = parseEnv(text);
  const environment = { ...parsed, ...ambientEnvironment };
  const ambientNames = new Set(Object.keys(ambientEnvironment));
  for (const [name, value] of Object.entries(parsed)) {
    const expanded = expandEnvReferences({
      environment,
      value: value ?? "",
    });
    values[name] = expanded;
    if (!ambientNames.has(name)) {
      environment[name] = expanded;
    }
  }
  return values;
};

const generatedExamples = () => [
  { content: renderApiEnvExample(), path: API_EXAMPLE_PATH },
  { content: renderCollabEnvExample(), path: COLLAB_EXAMPLE_PATH },
  { content: renderWebEnvExample(), path: WEB_EXAMPLE_PATH },
];

const generateExamples = () => {
  for (const example of generatedExamples()) {
    writeFileSync(example.path, example.content);
    console.log(`Generated ${path.relative(REPO_ROOT, example.path)}`);
  }
};

const checkExamples = () => {
  const stale = generatedExamples().filter(
    ({ content, path: examplePath }) =>
      !existsSync(examplePath) ||
      readFileSync(examplePath, "utf-8") !== content,
  );
  if (stale.length === 0) {
    console.log("Environment examples match their schemas.");
    return true;
  }
  for (const { path: examplePath } of stale) {
    console.error(`${path.relative(REPO_ROOT, examplePath)} is stale.`);
  }
  console.error("Run `bun run env:generate` and commit the result.");
  return false;
};

const STATIC_ENV_PATTERNS = [
  /\b(?:process|Bun)\.env\.([A-Z][A-Z0-9_]*)/gu,
  /\b(?:process|Bun)\.env\[["']([A-Z][A-Z0-9_]*)["']\]/gu,
  /\bimport\.meta\.env\.([A-Z][A-Z0-9_]*)/gu,
  /\bimport\.meta\.env\[["']([A-Z][A-Z0-9_]*)["']\]/gu,
];

const DEPLOYMENT_ENV_PATTERN = /\$\{([A-Z][A-Z0-9_]*)(?=[:}?])/gu;
const BARE_DOCKER_ENV_PATTERN = /\$(?!\{)([A-Z][A-Z0-9_]*)\b/gu;

const AUDIT_GLOBS = [
  "apps/**/*.{ts,tsx,js,mjs,cjs,yml,yaml}",
  "packages/**/*.{ts,tsx,js,mjs,cjs}",
  "scripts/**/*.{ts,js,sh}",
  "**/Dockerfile*",
  "**/docker-compose*.yml",
];

const AUDIT_IGNORE_FILES = new Set([
  // These tests contain environment syntax as source-text fixtures or use
  // test-process-only variables that are not repository configuration.
  "packages/property-testing/src/ci-gate-coverage.test.ts",
  "scripts/bun-ci-retry.test.sh",
  "scripts/detect-desktop-release-changes.test.sh",
  "scripts/env-tool.test.ts",
]);
const AUDIT_IGNORE_PATH_SEGMENTS = new Set([".cache", "node_modules"]);

export const isIgnoredAuditPath = (file: string) =>
  file.split("/").some((segment) => AUDIT_IGNORE_PATH_SEGMENTS.has(segment));

type EnvUsage = { file: string; line: number; name: string };

const ENV_NAME_PATTERN = /^[A-Z][A-Z0-9_]*$/u;
const SCRIPT_FILE_PATTERN = /\.[cm]?[jt]sx?$/u;

const findComputedEnvUsages = (file: string, text: string): EnvUsage[] => {
  if (!SCRIPT_FILE_PATTERN.test(file)) {
    return [];
  }

  const source = ts.createSourceFile(
    file,
    text,
    ts.ScriptTarget.Latest,
    true,
    file.endsWith("x") ? ts.ScriptKind.TSX : ts.ScriptKind.TS,
  );
  const constants = new Map<string, string>();
  const helpers = new Map<string, number>();
  const usages: EnvUsage[] = [];

  const literalEnvName = (node: ts.Node | undefined) => {
    if (
      node &&
      (ts.isStringLiteral(node) || ts.isNoSubstitutionTemplateLiteral(node))
    ) {
      return ENV_NAME_PATTERN.test(node.text) ? node.text : undefined;
    }
    if (node && ts.isIdentifier(node)) {
      return constants.get(node.text);
    }
    return undefined;
  };

  const collectConstants = (node: ts.Node) => {
    if (ts.isVariableDeclaration(node) && ts.isIdentifier(node.name)) {
      const value = literalEnvName(node.initializer);
      if (value) {
        constants.set(node.name.text, value);
      }
    }
    ts.forEachChild(node, collectConstants);
  };
  collectConstants(source);

  const envArgument = (node: ts.Node) => {
    if (!ts.isElementAccessExpression(node)) {
      return undefined;
    }
    const envAccess = node.expression;
    if (
      !ts.isPropertyAccessExpression(envAccess) ||
      envAccess.name.text !== "env" ||
      !ts.isIdentifier(envAccess.expression) ||
      (envAccess.expression.text !== "process" &&
        envAccess.expression.text !== "Bun")
    ) {
      return undefined;
    }
    return node.argumentExpression;
  };

  type HelperDeclaration =
    | ts.ArrowFunction
    | ts.FunctionDeclaration
    | ts.FunctionExpression;

  const isHelperDeclaration = (node: ts.Node): node is HelperDeclaration =>
    ts.isArrowFunction(node) ||
    ts.isFunctionDeclaration(node) ||
    ts.isFunctionExpression(node);

  const helperName = (node: HelperDeclaration) => {
    if (ts.isFunctionDeclaration(node) && node.name) {
      return node.name.text;
    }
    if (
      (ts.isArrowFunction(node) || ts.isFunctionExpression(node)) &&
      ts.isVariableDeclaration(node.parent) &&
      ts.isIdentifier(node.parent.name)
    ) {
      return node.parent.name.text;
    }
    return undefined;
  };

  const collectReads = (node: ts.Node) => {
    const argument = envArgument(node);
    if (argument && ts.isIdentifier(argument)) {
      const constantName = constants.get(argument.text);
      if (constantName) {
        usages.push({
          file,
          line:
            source.getLineAndCharacterOfPosition(argument.getStart(source))
              .line + 1,
          name: constantName,
        });
      } else {
        let parent = node.parent;
        while (parent && !isHelperDeclaration(parent)) {
          parent = parent.parent;
        }
        if (parent && isHelperDeclaration(parent)) {
          const parameterIndex = parent.parameters.findIndex(
            ({ name }) => ts.isIdentifier(name) && name.text === argument.text,
          );
          const name = helperName(parent);
          if (name && parameterIndex !== -1) {
            helpers.set(name, parameterIndex);
          }
        }
      }
    }
    ts.forEachChild(node, collectReads);
  };
  collectReads(source);

  const collectCalls = (node: ts.Node) => {
    if (ts.isCallExpression(node) && ts.isIdentifier(node.expression)) {
      const parameterIndex = helpers.get(node.expression.text);
      if (parameterIndex !== undefined) {
        const argument = node.arguments.at(parameterIndex);
        const name = literalEnvName(argument);
        if (name && argument) {
          usages.push({
            file,
            line:
              source.getLineAndCharacterOfPosition(argument.getStart(source))
                .line + 1,
            name,
          });
        }
      }
    }
    ts.forEachChild(node, collectCalls);
  };
  collectCalls(source);

  return usages;
};

export const findEnvUsages = (file: string, text: string): EnvUsage[] => {
  const usages = findComputedEnvUsages(file, text);
  let patterns = STATIC_ENV_PATTERNS;
  if (file.includes("Dockerfile")) {
    patterns = [
      ...STATIC_ENV_PATTERNS,
      DEPLOYMENT_ENV_PATTERN,
      BARE_DOCKER_ENV_PATTERN,
    ];
  } else if (/\.(?:sh|ya?ml)$/u.test(file)) {
    patterns = [...STATIC_ENV_PATTERNS, DEPLOYMENT_ENV_PATTERN];
  }
  for (const pattern of patterns) {
    for (const match of text.matchAll(pattern)) {
      const name = match.at(1);
      if (!name) {
        continue;
      }
      usages.push({
        file,
        line: text.slice(0, match.index).split("\n").length,
        name,
      });
    }
  }
  return usages;
};

const isKnownEnvName = (name: string) =>
  ENV_CATALOG.some((entry) => entry.name === name) ||
  MANUAL_SCHEMA_KEYS.has(name) ||
  TOOLING_ENV_KEYS.has(name) ||
  DEPLOYMENT_ENV_KEYS.has(name) ||
  AMBIENT_ENV_KEYS.has(name) ||
  /^(?:ACTIONS_|BUN_|GITHUB_|INPUT_|npm_|RAILWAY_|RUNNER_)/u.test(name);

const auditEnvironment = async () => {
  const files = new Set<string>();
  for (const pattern of AUDIT_GLOBS) {
    const glob = new Bun.Glob(pattern);
    // eslint-disable-next-line no-await-in-loop -- each glob is a lazy async iterator
    for await (const file of glob.scan({ cwd: REPO_ROOT, onlyFiles: true })) {
      if (!isIgnoredAuditPath(file) && !AUDIT_IGNORE_FILES.has(file)) {
        files.add(file);
      }
    }
  }
  const unknown: EnvUsage[] = [];
  for (const file of files) {
    const text = readFileSync(path.join(REPO_ROOT, file), "utf-8");
    unknown.push(
      ...findEnvUsages(file, text).filter(({ name }) => !isKnownEnvName(name)),
    );
  }
  const unique = [
    ...new Map(
      unknown.map((usage) => [
        `${usage.file}:${usage.line}:${usage.name}`,
        usage,
      ]),
    ).values(),
  ];
  if (unique.length === 0) {
    console.log("All static environment-variable reads are cataloged.");
    return true;
  }
  for (const usage of unique) {
    console.error(`${usage.file}:${usage.line}: uncataloged env ${usage.name}`);
  }
  return false;
};

const sourceLabel = (name: string, fileValues: Record<string, string>) => {
  if (process.env[name] !== undefined) {
    return "process";
  }
  if (fileValues[name] !== undefined) {
    return "file";
  }
  return "default/unset";
};

export const formatEnvValue = (entry: EnvCatalogEntry, value: unknown) => {
  if (value === undefined) {
    return "<unset>";
  }
  if (entry.exposure === ENV_EXPOSURE.secret) {
    return "<redacted>";
  }
  return JSON.stringify(value);
};

export const formatEnvIssue = (issue: v.BaseIssue<unknown>) => {
  const key = issue.path
    ?.map((item) => item.key)
    .find((itemKey) => typeof itemKey === "string");
  if (typeof key !== "string") {
    return "Invalid environment configuration.";
  }
  const entry = ENV_CATALOG.find(({ name }) => name === key);
  if (entry?.exposure !== ENV_EXPOSURE.public) {
    return `${key}: invalid ${entry?.exposure ?? ENV_EXPOSURE.secret} value.`;
  }
  return `${key}: ${issue.message}`;
};

const ENV_APP = {
  api: "api",
  collab: "collab",
  web: "web",
} as const;

type EnvApp = (typeof ENV_APP)[keyof typeof ENV_APP];
type DoctorInput = Record<string, string | undefined>;
type DoctorValues = Record<string, unknown>;
type DoctorValidationResult =
  | { status: "invalid"; issues: string[]; values: DoctorValues }
  | { status: "valid"; values: DoctorValues };

const isEnvApp = (value: string): value is EnvApp =>
  Object.values(ENV_APP).some((app) => app === value);

const EMPTY_DATABASE_COMPONENT_KEYS = new Set(["DB_PASSWORD", "DB_SSLMODE"]);

export const normalizeEmptyEnvironment = (input: DoctorInput): DoctorInput => {
  const normalized: DoctorInput = {};
  for (const [name, value] of Object.entries(input)) {
    normalized[name] =
      value === "" && !EMPTY_DATABASE_COMPONENT_KEYS.has(name)
        ? undefined
        : value;
  }
  return normalized;
};

const validateSchema = (
  schema: Record<string, v.GenericSchema>,
  input: DoctorInput,
): DoctorValidationResult => {
  const result = v.safeParse(v.object(schema), input);
  if (!result.success) {
    return {
      status: "invalid",
      issues: result.issues.map(formatEnvIssue),
      values: input,
    };
  }
  return { status: "valid", values: { ...input, ...result.output } };
};

const validateApiEnvironment = (input: DoctorInput): DoctorValidationResult => {
  const databaseUrl = Result.try(() => resolveDatabaseUrl(input));
  if (Result.isError(databaseUrl)) {
    return {
      status: "invalid",
      issues: ["DATABASE_URL: invalid database component settings."],
      values: input,
    };
  }

  const nodeEnv = input["NODE_ENV"];
  const runtimeInput = {
    ...input,
    DATABASE_URL: databaseUrl.value,
    isDev: !DEPLOYED_NODE_ENVS.has(nodeEnv ?? ""),
  };
  const parsed = v.safeParse(v.object(API_ENV_SCHEMA), runtimeInput);
  if (!parsed.success) {
    return {
      status: "invalid",
      issues: parsed.issues.map(formatEnvIssue),
      values: runtimeInput,
    };
  }

  const emailProvider = resolveEmailProvider(parsed.output);
  const output = { ...parsed.output, EMAIL_PROVIDER: emailProvider };
  const issues: string[] = [];
  const baseIssue = envBaseInvariantViolation(output);
  if (baseIssue !== null) {
    issues.push(baseIssue);
  }
  const documentProcessingIssue = documentProcessingEnvInvariantViolation({
    contentEncryptionKey: output.CONTENT_ENCRYPTION_KEY,
    nodeEnv,
  });
  if (documentProcessingIssue !== null) {
    issues.push(documentProcessingIssue);
  }
  const apiIssue = envApiInvariantViolation({ ...output, nodeEnv });
  if (apiIssue !== null) {
    issues.push(apiIssue);
  }
  const values = { ...runtimeInput, ...output };
  return issues.length === 0
    ? { status: "valid", values }
    : { status: "invalid", issues, values };
};

const validateWebEnvironment = (input: DoctorInput): DoctorValidationResult => {
  const result = v.safeParse(v.object(WEB_ENV_SCHEMA), input);
  if (!result.success) {
    return {
      status: "invalid",
      issues: result.issues.map(formatEnvIssue),
      values: input,
    };
  }
  const values = { ...input, ...result.output };
  const issue = envWebInvariantViolation(result.output);
  return issue === null
    ? { status: "valid", values }
    : { status: "invalid", issues: [issue], values };
};

type EnvAppConfig = {
  examplePath: string;
  owners: ReadonlySet<EnvOwner>;
  validate: (input: DoctorInput) => DoctorValidationResult;
};

const ENV_APP_CONFIG = {
  api: {
    examplePath: API_EXAMPLE_PATH,
    owners: new Set<EnvOwner>([
      ENV_OWNER.apiBase,
      ENV_OWNER.documentWorker,
      ENV_OWNER.apiServer,
    ]),
    validate: validateApiEnvironment,
  },
  collab: {
    examplePath: COLLAB_EXAMPLE_PATH,
    owners: new Set<EnvOwner>([ENV_OWNER.collab]),
    validate: (input: DoctorInput) => validateSchema(COLLAB_ENV_SCHEMA, input),
  },
  web: {
    examplePath: WEB_EXAMPLE_PATH,
    owners: new Set<EnvOwner>([ENV_OWNER.web]),
    validate: validateWebEnvironment,
  },
} as const satisfies Record<EnvApp, EnvAppConfig>;

export const validateDoctorEnvironment = (
  app: EnvApp,
  rawInput: DoctorInput,
): DoctorValidationResult =>
  ENV_APP_CONFIG[app].validate(normalizeEmptyEnvironment(rawInput));

const runDoctor = (app: EnvApp) => {
  const { examplePath, owners } = ENV_APP_CONFIG[app];
  const envPath = examplePath.replace(/\.example$/u, "");
  const fileValues = existsSync(envPath)
    ? parseEnvText(readFileSync(envPath, "utf-8"))
    : {};
  const validation = validateDoctorEnvironment(app, {
    ...fileValues,
    ...process.env,
  });
  console.log(
    `Environment doctor: ${app} (${path.relative(REPO_ROOT, envPath)})`,
  );
  for (const entry of ENV_CATALOG.filter(
    ({ documented, owner }) => documented && owners.has(owner),
  )) {
    const value = validation.values[entry.name];
    console.log(
      `${entry.name}: ${formatEnvValue(entry, value)} [${sourceLabel(entry.name, fileValues)}; ${entry.exposure}]`,
    );
  }
  switch (validation.status) {
    case "valid":
      console.log(`${app}: valid`);
      return true;
    case "invalid":
      for (const issue of validation.issues) {
        console.error(issue);
      }
      return false;
    default: {
      const exhaustive: never = validation;
      return exhaustive;
    }
  }
};

const main = async () => {
  const command = process.argv.at(2);
  if (command === "generate") {
    generateExamples();
    return;
  }
  if (command === "check") {
    const examplesValid = checkExamples();
    const auditValid = await auditEnvironment();
    if (!(examplesValid && auditValid)) {
      process.exitCode = 1;
    }
    return;
  }
  if (command === "audit") {
    if (!(await auditEnvironment())) {
      process.exitCode = 1;
    }
    return;
  }
  if (command === "doctor") {
    const app = process.argv.at(3) ?? "api";
    if (!isEnvApp(app)) {
      console.error("Usage: bun run env:doctor [api|collab|web]");
      process.exitCode = 1;
      return;
    }
    if (!runDoctor(app)) {
      process.exitCode = 1;
    }
    return;
  }
  console.error("Usage: env-tool.ts <generate|check|audit|doctor>");
  process.exitCode = 1;
};

if (import.meta.main) {
  await main();
}
