const GENERATED_HEADER = [
  "# Generated by `bun run env:generate`; edit the Valibot schemas or env catalog.",
  "# Required entries are active. Optional entries are commented out unless",
  "# stella's local development stack intentionally enables them.",
  "",
].join("\n");

const quoteEnvValue = (value: string) =>
  `"${value.replaceAll("\\", "\\\\").replaceAll('"', '\\"')}"`;

const defaultExample = (entry: EnvCatalogEntry) => {
  if (entry.example !== undefined) {
    return entry.example;
  }
  const fallback = v.getDefault(entry.schema);
  if (typeof fallback === "string" || typeof fallback === "number") {
    return String(fallback);
  }
  if (typeof fallback === "boolean") {
    return fallback ? "true" : "false";
  }
  return "";
};

const requirementLabel = (entry: EnvCatalogEntry) => {
  if (entry.requirement === "required") {
    return "Required";
  }
  if (entry.requirement === "conditional") {
    if (!entry.requirementNote) {
      panic(`Conditional environment entry ${entry.name} requires a note.`);
    }
    return `Conditionally required when ${entry.requirementNote}`;
  }
  if (entry.requirement === "defaulted") {
    return "Optional with a default";
  }
  return "Optional";
};

const wrapComment = (text: string, width = 76) => {
  const lines: string[] = [];
  let current = "";
  for (const word of text.split(/\s+/u)) {
    if (current.length === 0) {
      current = word;
      continue;
    }
    if (current.length + word.length + 1 <= width) {
      current += ` ${word}`;
      continue;
    }
    lines.push(`# ${current}`);
    current = word;
  }
  if (current.length > 0) {
    lines.push(`# ${current}`);
  }
  return lines;
};

const renderEntries = (entries: EnvCatalogEntry[]) => {
  const sections = Map.groupBy(entries, ({ section }) => section);
  const lines: string[] = [GENERATED_HEADER];
  for (const [section, sectionEntries] of sections) {
    lines.push(
      `# --- ${section} ${"-".repeat(Math.max(1, 66 - section.length))}`,
    );
    for (const entry of sectionEntries) {
      const active =
        entry.requirement === "required" || isActiveExampleEntry(entry.name);
      const prefix = active ? "" : "# ";
      lines.push(
        ...wrapComment(
          `[${entry.exposure}] ${requirementLabel(entry)}. ${entry.description}`,
        ),
        `${prefix}${entry.name}=${quoteEnvValue(defaultExample(entry))}`,
        "",
      );
    }
  }
  return `${lines.join("\n").trimEnd()}\n`;
};

