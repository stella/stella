const REPO_ROOT = path.resolve(import.meta.dir, "..");
const API_EXAMPLE_PATH = path.join(REPO_ROOT, "apps/api/.env.example");
const COLLAB_EXAMPLE_PATH = path.join(REPO_ROOT, "apps/collab/.env.example");
const WEB_EXAMPLE_PATH = path.join(REPO_ROOT, "apps/web/.env.example");
const GENERATED_HEADER = [
  "# Generated by `bun run env:generate`; edit the Valibot schemas or env catalog.",
  "# Required entries are active. Optional entries are commented out unless",
  "# stella's local development stack intentionally enables them.",
  "",
].join("\n");

const quoteEnvValue = (value: string) =>
  `"${value.replaceAll("\\", "\\\\").replaceAll('"', '\\"')}"`;

const defaultExample = (entry: EnvCatalogEntry) => {
  if (entry.example !== undefined) {
    return entry.example;
  }
  const fallback = v.getDefault(entry.schema);
  if (typeof fallback === "string" || typeof fallback === "number") {
    return String(fallback);
  }
  if (typeof fallback === "boolean") {
    return fallback ? "true" : "false";
  }
  return "";
};

const requirementLabel = (entry: EnvCatalogEntry) => {
  if (entry.requirement === "required") {
    return "Required";
  }
  if (entry.requirement === "defaulted") {
    return "Optional with a default";
  }
  return "Optional";
};

const wrapComment = (text: string, width = 76) => {
  const lines: string[] = [];
  let current = "";
  for (const word of text.split(/\s+/u)) {
    if (current.length === 0) {
      current = word;
      continue;
    }
    if (current.length + word.length + 1 <= width) {
      current += ` ${word}`;
      continue;
    }
    lines.push(`# ${current}`);
    current = word;
  }
  if (current.length > 0) {
    lines.push(`# ${current}`);
  }
  return lines;
};

const renderEntries = (entries: EnvCatalogEntry[]) => {
  const sections = Map.groupBy(entries, ({ section }) => section);
  const lines: string[] = [GENERATED_HEADER];
  for (const [section, sectionEntries] of sections) {
    lines.push(
      `# --- ${section} ${"-".repeat(Math.max(1, 66 - section.length))}`,
    );
    for (const entry of sectionEntries) {
      const active =
        entry.requirement === "required" || isActiveExampleEntry(entry.name);
      const prefix = active ? "" : "# ";
      lines.push(
        ...wrapComment(
          `[${entry.exposure}] ${requirementLabel(entry)}. ${entry.description}`,
        ),
        `${prefix}${entry.name}=${quoteEnvValue(defaultExample(entry))}`,
        "",
      );
    }
  }
  return `${lines.join("\n").trimEnd()}\n`;
};

export const renderApiEnvExample = () =>
  renderEntries(
    ENV_CATALOG.filter(
      ({ documented, owner }) =>
        documented && owner !== ENV_OWNER.web && owner !== ENV_OWNER.collab,
    ),
  );

export const renderWebEnvExample = () =>
  renderEntries(
    ENV_CATALOG.filter(
      ({ documented, owner }) => documented && owner === ENV_OWNER.web,
    ),
  );

export const renderCollabEnvExample = () =>
  renderEntries(
    ENV_CATALOG.filter(
      ({ documented, owner }) => documented && owner === ENV_OWNER.collab,
    ),
  );

export const parseEnvText = (text: string) => {
  const values: Record<string, string> = {};
  for (const line of text.split(/\r?\n/u)) {
    const assignment = line.trim().replace(/^export\s+/u, "");
    const separatorIndex = assignment.indexOf("=");
    if (separatorIndex < 1) {
      continue;
    }
    const name = assignment.slice(0, separatorIndex).trim();
    if (!/^[A-Z][A-Z0-9_]*$/u.test(name)) {
      continue;
    }
    const raw = assignment.slice(separatorIndex + 1).trim();
    const quote = raw.at(0);
    const isQuoted =
      raw.length >= 2 &&
      (quote === '"' || quote === "'") &&
      raw.at(-1) === quote;
    values[name] = isQuoted ? raw.slice(1, -1) : raw;
  }
  return values;
};

const generatedExamples = () => [
  { content: renderApiEnvExample(), path: API_EXAMPLE_PATH },
  { content: renderCollabEnvExample(), path: COLLAB_EXAMPLE_PATH },
  { content: renderWebEnvExample(), path: WEB_EXAMPLE_PATH },
];

const generateExamples = () => {
  for (const example of generatedExamples()) {
    writeFileSync(example.path, example.content);
    console.log(`Generated ${path.relative(REPO_ROOT, example.path)}`);
  }
};

const checkExamples = () => {
  const stale = generatedExamples().filter(
    ({ content, path: examplePath }) =>
      !existsSync(examplePath) ||
      readFileSync(examplePath, "utf-8") !== content,
  );
  if (stale.length === 0) {
    console.log("Environment examples match their schemas.");
    return true;
  }
  for (const { path: examplePath } of stale) {
    console.error(`${path.relative(REPO_ROOT, examplePath)} is stale.`);
  }
  console.error("Run `bun run env:generate` and commit the result.");
  return false;
};

const STATIC_ENV_PATTERNS = [
  /\b(?:process|Bun)\.env\.([A-Z][A-Z0-9_]*)/gu,
  /\b(?:process|Bun)\.env\[["']([A-Z][A-Z0-9_]*)["']\]/gu,
  /\bimport\.meta\.env\.([A-Z][A-Z0-9_]*)/gu,
  /\bimport\.meta\.env\[["']([A-Z][A-Z0-9_]*)["']\]/gu,
];

const DEPLOYMENT_ENV_PATTERN = /\$\{([A-Z][A-Z0-9_]*)(?=[:}?])/gu;
const BARE_DOCKER_ENV_PATTERN = /\$(?!\{)([A-Z][A-Z0-9_]*)\b/gu;

const AUDIT_GLOBS = [
  "apps/**/*.{ts,tsx,js,mjs,cjs,yml,yaml}",
  "packages/**/*.{ts,tsx,js,mjs,cjs}",
  "scripts/**/*.{ts,js,sh}",
  "**/Dockerfile*",
  "**/docker-compose*.yml",
];

const AUDIT_IGNORE_FILES = new Set([
  // This invariant test contains process.env syntax as source-text fixtures.
  "packages/property-testing/src/ci-gate-coverage.test.ts",
  "scripts/env-tool.test.ts",
]);

type EnvUsage = { file: string; line: number; name: string };

export const findEnvUsages = (file: string, text: string): EnvUsage[] => {
  const usages: EnvUsage[] = [];
  let patterns = STATIC_ENV_PATTERNS;
  if (file.includes("Dockerfile")) {
    patterns = [
      ...STATIC_ENV_PATTERNS,
      DEPLOYMENT_ENV_PATTERN,
      BARE_DOCKER_ENV_PATTERN,
    ];
  } else if (/\.ya?ml$/u.test(file)) {
    patterns = [...STATIC_ENV_PATTERNS, DEPLOYMENT_ENV_PATTERN];
  }
  for (const pattern of patterns) {
    for (const match of text.matchAll(pattern)) {
      const name = match.at(1);
      if (!name) {
        continue;
      }
      usages.push({
        file,
        line: text.slice(0, match.index).split("\n").length,
        name,
      });
    }
  }
  return usages;
};

const isKnownEnvName = (name: string) =>
  ENV_CATALOG.some((entry) => entry.name === name) ||
  MANUAL_SCHEMA_KEYS.has(name) ||
  TOOLING_ENV_KEYS.has(name) ||
  DEPLOYMENT_ENV_KEYS.has(name) ||
  AMBIENT_ENV_KEYS.has(name) ||
  /^(?:ACTIONS_|BUN_|GITHUB_|INPUT_|npm_|RAILWAY_|RUNNER_)/u.test(name);

const auditEnvironment = async () => {
  const files = new Set<string>();
  for (const pattern of AUDIT_GLOBS) {
    const glob = new Bun.Glob(pattern);
    // eslint-disable-next-line no-await-in-loop -- each glob is a lazy async iterator
    for await (const file of glob.scan({ cwd: REPO_ROOT, onlyFiles: true })) {
      if (
        !file.includes("/node_modules/") &&
        !file.includes("/.cache/") &&
        !AUDIT_IGNORE_FILES.has(file)
      ) {
        files.add(file);
      }
    }
  }
  const unknown: EnvUsage[] = [];
  for (const file of files) {
    const text = readFileSync(path.join(REPO_ROOT, file), "utf-8");
    unknown.push(
      ...findEnvUsages(file, text).filter(({ name }) => !isKnownEnvName(name)),
    );
  }
  const unique = [
    ...new Map(
      unknown.map((usage) => [
        `${usage.file}:${usage.line}:${usage.name}`,
        usage,
      ]),
    ).values(),
  ];
  if (unique.length === 0) {
    console.log("All static environment-variable reads are cataloged.");
    return true;
  }
  for (const usage of unique) {
    console.error(`${usage.file}:${usage.line}: uncataloged env ${usage.name}`);
  }
  return false;
};

const sourceLabel = (name: string, fileValues: Record<string, string>) => {
  if (process.env[name] !== undefined) {
    return "process";
  }
  if (fileValues[name] !== undefined) {
    return "file";
  }
  return "default/unset";
};

export const formatEnvValue = (entry: EnvCatalogEntry, value: unknown) => {
  if (value === undefined) {
    return "<unset>";
  }
  if (entry.exposure === ENV_EXPOSURE.secret) {
    return "<redacted>";
  }
  return JSON.stringify(value);
};

export const formatEnvIssue = (issue: v.BaseIssue<unknown>) => {
  const key = issue.path
    ?.map((item) => item.key)
    .find((itemKey) => typeof itemKey === "string");
  if (typeof key !== "string") {
    return "Invalid environment configuration.";
  }
  const entry = ENV_CATALOG.find(({ name }) => name === key);
  if (entry?.exposure === ENV_EXPOSURE.secret) {
    return `${key}: invalid secret value.`;
  }
  return `${key}: ${issue.message}`;
};

const ENV_APP = {
  api: "api",
  collab: "collab",
  web: "web",
} as const;

type EnvApp = (typeof ENV_APP)[keyof typeof ENV_APP];
type DoctorInput = Record<string, string | undefined>;
type DoctorValues = Record<string, unknown>;
type DoctorValidationResult =
  | { status: "invalid"; issues: string[]; values: DoctorValues }
  | { status: "valid"; values: DoctorValues };

const isEnvApp = (value: string): value is EnvApp =>
  Object.values(ENV_APP).some((app) => app === value);

export const normalizeEmptyEnvironment = (input: DoctorInput): DoctorInput => {
  const normalized: DoctorInput = {};
  for (const [name, value] of Object.entries(input)) {
    normalized[name] =
      value === "" && name !== "DB_PASSWORD" ? undefined : value;
  }
  return normalized;
};

const validateSchema = (
  schema: Record<string, v.GenericSchema>,
  input: DoctorInput,
): DoctorValidationResult => {
  const result = v.safeParse(v.object(schema), input);
  if (!result.success) {
    return {
      status: "invalid",
      issues: result.issues.map(formatEnvIssue),
      values: input,
    };
  }
  return { status: "valid", values: { ...input, ...result.output } };
};

const validateApiEnvironment = (input: DoctorInput): DoctorValidationResult => {
  const databaseUrl = Result.try(() => resolveDatabaseUrl(input));
  if (Result.isError(databaseUrl)) {
    return {
      status: "invalid",
      issues: ["DATABASE_URL: invalid database component settings."],
      values: input,
    };
  }

  const nodeEnv = input["NODE_ENV"];
  const runtimeInput = {
    ...input,
    DATABASE_URL: databaseUrl.value,
    isDev: !DEPLOYED_NODE_ENVS.has(nodeEnv ?? ""),
  };
  const parsed = v.safeParse(v.object(API_ENV_SCHEMA), runtimeInput);
  if (!parsed.success) {
    return {
      status: "invalid",
      issues: parsed.issues.map(formatEnvIssue),
      values: runtimeInput,
    };
  }

  const emailProvider = resolveEmailProvider(parsed.output);
  const output = { ...parsed.output, EMAIL_PROVIDER: emailProvider };
  const issues: string[] = [];
  const baseIssue = envBaseInvariantViolation(output);
  if (baseIssue !== null) {
    issues.push(baseIssue);
  }
  const documentProcessingIssue = documentProcessingEnvInvariantViolation({
    contentEncryptionKey: output.CONTENT_ENCRYPTION_KEY,
    nodeEnv,
  });
  if (documentProcessingIssue !== null) {
    issues.push(documentProcessingIssue);
  }
  const apiIssue = envApiInvariantViolation({ ...output, nodeEnv });
  if (apiIssue !== null) {
    issues.push(apiIssue);
  }
  const values = { ...runtimeInput, ...output };
  return issues.length === 0
    ? { status: "valid", values }
    : { status: "invalid", issues, values };
};

export const validateDoctorEnvironment = (
  app: EnvApp,
  rawInput: DoctorInput,
): DoctorValidationResult => {
  const input = normalizeEmptyEnvironment(rawInput);
  if (app === ENV_APP.api) {
    return validateApiEnvironment(input);
  }
  return validateSchema(
    app === ENV_APP.web ? WEB_ENV_SCHEMA : COLLAB_ENV_SCHEMA,
    input,
  );
};

const runDoctor = (app: EnvApp) => {
  let examplePath = API_EXAMPLE_PATH;
  if (app === ENV_APP.web) {
    examplePath = WEB_EXAMPLE_PATH;
  } else if (app === ENV_APP.collab) {
    examplePath = COLLAB_EXAMPLE_PATH;
  }
  const envPath = examplePath.replace(/\.example$/u, "");
  const fileValues = existsSync(envPath)
    ? parseEnvText(readFileSync(envPath, "utf-8"))
    : {};
  const validation = validateDoctorEnvironment(app, {
    ...fileValues,
    ...process.env,
  });
  let owners = new Set<EnvOwner>([
    ENV_OWNER.apiBase,
    ENV_OWNER.documentWorker,
    ENV_OWNER.apiServer,
  ]);
  if (app === ENV_APP.web) {
    owners = new Set([ENV_OWNER.web]);
  } else if (app === ENV_APP.collab) {
    owners = new Set([ENV_OWNER.collab]);
  }
  console.log(
    `Environment doctor: ${app} (${path.relative(REPO_ROOT, envPath)})`,
  );
  for (const entry of ENV_CATALOG.filter(
    ({ documented, owner }) => documented && owners.has(owner),
  )) {
    const value = validation.values[entry.name];
    console.log(
      `${entry.name}: ${formatEnvValue(entry, value)} [${sourceLabel(entry.name, fileValues)}; ${entry.exposure}]`,
    );
  }
  switch (validation.status) {
    case "valid":
      console.log(`${app}: valid`);
      return true;
    case "invalid":
      for (const issue of validation.issues) {
        console.error(issue);
      }
      return false;
    default: {
      const exhaustive: never = validation;
      return exhaustive;
    }
  }
};

const main = async () => {
  const command = process.argv.at(2);
  if (command === "generate") {
    generateExamples();
    return;
  }
  if (command === "check") {
    const valid = checkExamples() && (await auditEnvironment());
    if (!valid) {
      process.exitCode = 1;
    }
    return;
  }
  if (command === "audit") {
    if (!(await auditEnvironment())) {
      process.exitCode = 1;
    }
    return;
  }
  if (command === "doctor") {
    const app = process.argv.at(3) ?? "api";
    if (!isEnvApp(app)) {
      console.error("Usage: bun run env:doctor [api|collab|web]");
      process.exitCode = 1;
      return;
    }
    if (!runDoctor(app)) {
      process.exitCode = 1;
    }
    return;
  }
  console.error("Usage: env-tool.ts <generate|check|audit|doctor>");
  process.exitCode = 1;
};

if (import.meta.main) {
  await main();
}
