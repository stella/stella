export type SelfhostService =
  (typeof SELFHOST_SERVICE)[keyof typeof SELFHOST_SERVICE];

type SelfhostServiceContract =
  | {
      type: "http-api";
      description: string;
      image: "application";
      readiness: "/ready";
    }
  | {
      type: "queue-worker";
      command: readonly ["bun", "/app/document-processing-worker.js"];
      description: string;
      image: "application";
      readiness: "api-ready";
    }
  | {
      type: "document-converter";
      description: string;
      image: "gotenberg";
      readiness: "/health";
    };

