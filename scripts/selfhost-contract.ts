const commandSchema = v.array(v.string());
const composeServiceSchema = v.looseObject({
  image: v.string(),
  command: v.optional(commandSchema),
  depends_on: v.optional(v.record(v.string(), v.unknown())),
  healthcheck: v.optional(
    v.looseObject({
      test: v.union([v.string(), commandSchema]),
    }),
  ),
});
const composeSchema = v.object({
  services: v.record(v.string(), composeServiceSchema),
});

const sameCommand = (
  actual: readonly string[] | undefined,
  expected: readonly string[],
) => JSON.stringify(actual) === JSON.stringify(expected);

const healthcheckCommand = (
  services: v.InferOutput<typeof composeSchema>["services"],
  service: SelfhostService,
) => {
  const test = services[service]?.healthcheck?.test;
  return Array.isArray(test) ? test : undefined;
};

export const selfhostComposeViolations = (text: string): string[] => {
  const decoded = v.safeParse(composeSchema, Bun.YAML.parse(text));
  if (!decoded.success) {
    return ["Compose does not match the typed self-host schema."];
  }

  const { services } = decoded.output;
  const declaredServices = Object.keys(services).toSorted();
  const expectedServices = Object.keys(SELFHOST_SERVICE_CONTRACT).toSorted();
  const violations: string[] = [];
  if (JSON.stringify(declaredServices) !== JSON.stringify(expectedServices)) {
    violations.push(
      `Compose services must be exactly: ${expectedServices.join(", ")}.`,
    );
  }

  for (const service of [
    SELFHOST_SERVICE.api,
    SELFHOST_SERVICE.documentProcessingWorker,
  ] as const) {
    if (services[service]?.image !== SELFHOST_APPLICATION_IMAGE_EXPRESSION) {
      violations.push(`${service} must use the required application image.`);
    }
  }
  if (
    services[SELFHOST_SERVICE.gotenberg]?.image !== SELFHOST_GOTENBERG_IMAGE
  ) {
    violations.push("gotenberg must use the contract's digest-pinned image.");
  }

  const worker = services[SELFHOST_SERVICE.documentProcessingWorker];
  if (
    !sameCommand(
      worker?.command,
      SELFHOST_SERVICE_CONTRACT[SELFHOST_SERVICE.documentProcessingWorker]
        .command,
    )
  ) {
    violations.push("document-processing-worker has the wrong command.");
  }
  if (
    !sameCommand(healthcheckCommand(services, SELFHOST_SERVICE.api), [
      "CMD",
      "bun",
      "-e",
      API_READINESS_COMMAND,
    ])
  ) {
    violations.push("api healthcheck must probe /ready.");
  }
  if (
    !sameCommand(
      healthcheckCommand(services, SELFHOST_SERVICE.documentProcessingWorker),
      ["CMD", "bun", "-e", WORKER_READINESS_COMMAND],
    )
  ) {
    violations.push("document-processing-worker must depend on API readiness.");
  }
  if (services[SELFHOST_SERVICE.gotenberg]?.healthcheck === undefined) {
    violations.push("gotenberg must declare a healthcheck.");
  }
  return violations;
};

