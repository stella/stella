import { panic } from "better-result";
import { readFile } from "node:fs/promises";
import path from "node:path";

import { compareCodeUnit } from "@stll/collation";

import { parseSource, walk } from "../packages/scripts/src/syntax-tree";

/** Enumerate production error declarations without loading their modules. */
export const failureTagsInSource = (source: string, file: string): string[] => {
  const tags: string[] = [];
  const { program } = parseSource(file, source);
  const factories = new Set<string>();
  const namespaces = new Set<string>();
  for (const statement of program.body) {
    if (
      statement.type !== "ImportDeclaration" ||
      statement.source.value !== "better-result"
    ) {
      continue;
    }
    for (const specifier of statement.specifiers) {
      if (specifier.type === "ImportNamespaceSpecifier") {
        namespaces.add(specifier.local.name);
      } else if (
        specifier.type === "ImportSpecifier" &&
        (specifier.imported.type === "Identifier"
          ? specifier.imported.name
          : specifier.imported.value) === "TaggedError"
      ) {
        factories.add(specifier.local.name);
      }
    }
  }
  walk(program, (node) => {
    if (node.type !== "CallExpression") {
      return;
    }
    const { callee } = node;
    const isFactory =
      callee.type === "Identifier"
        ? factories.has(callee.name)
        : callee.type === "MemberExpression" &&
          !callee.computed &&
          callee.object.type === "Identifier" &&
          namespaces.has(callee.object.name) &&
          callee.property.type === "Identifier" &&
          callee.property.name === "TaggedError";
    if (isFactory) {
      const tag = node.arguments.at(0);
      if (tag?.type !== "Literal" || typeof tag.value !== "string") {
        panic(`Nonliteral TaggedError tag in ${file}`);
      }
      tags.push(tag.value);
    }
  });
  return tags;
};

export const collectFailureTags = async (root: string): Promise<string[]> => {
  const tags = new Set<string>();
  for (const pattern of [
    "apps/api/src/**/*.{ts,tsx}",
    "packages/*/src/**/*.{ts,tsx}",
  ]) {
    const files = new Bun.Glob(pattern);
    for await (const file of files.scan({ cwd: root, onlyFiles: true })) {
      if (
        /(?:\.(?:test|spec)\.|\/(?:tests|__tests__|fixtures)\/)/u.test(file)
      ) {
        continue;
      }
      for (const tag of failureTagsInSource(
        await readFile(path.join(root, file), "utf-8"),
        file,
      )) {
        tags.add(tag);
      }
    }
  }
  return [...tags].toSorted(compareCodeUnit);
};

export const renderFailureTags = (tags: readonly string[]): string =>
  `// Generated by scripts/generate-failure-tags.ts; do not edit.\nexport const FAILURE_TAGS = ${JSON.stringify(tags, null, 2)} as const;\n\nexport type FailureTag = (typeof FAILURE_TAGS)[number];\n`;
