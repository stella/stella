import { panic } from "better-result";
import { readFile } from "node:fs/promises";
import path from "node:path";
import ts from "typescript6";

import { compareCodeUnit } from "@stll/collation";

/** Enumerate production error declarations without loading their modules. */
export const failureTagsInSource = (source: string, file: string): string[] => {
  const tags: string[] = [];
  const parsed = ts.createSourceFile(
    file,
    source,
    ts.ScriptTarget.Latest,
    true,
  );
  const factories = new Set<string>();
  const namespaces = new Set<string>();
  for (const statement of parsed.statements) {
    if (
      !ts.isImportDeclaration(statement) ||
      !ts.isStringLiteral(statement.moduleSpecifier) ||
      statement.moduleSpecifier.text !== "better-result"
    ) {
      continue;
    }
    const bindings = statement.importClause?.namedBindings;
    if (bindings === undefined) {
      continue;
    }
    if (ts.isNamespaceImport(bindings)) {
      namespaces.add(bindings.name.text);
      continue;
    }
    for (const element of bindings.elements) {
      if ((element.propertyName ?? element.name).text === "TaggedError") {
        factories.add(element.name.text);
      }
    }
  }
  const visit = (node: ts.Node) => {
    if (!ts.isCallExpression(node)) {
      ts.forEachChild(node, visit);
      return;
    }
    const callee = node.expression;
    const isFactory = ts.isIdentifier(callee)
      ? factories.has(callee.text)
      : ts.isPropertyAccessExpression(callee) &&
        ts.isIdentifier(callee.expression) &&
        namespaces.has(callee.expression.text) &&
        callee.name.text === "TaggedError";
    if (isFactory) {
      const tag = node.arguments.at(0);
      if (tag === undefined || !ts.isStringLiteral(tag)) {
        panic(`Nonliteral TaggedError tag in ${file}`);
      }
      tags.push(tag.text);
    }
    ts.forEachChild(node, visit);
  };
  visit(parsed);
  return tags;
};

export const collectFailureTags = async (root: string): Promise<string[]> => {
  const tags = new Set<string>();
  for (const pattern of [
    "apps/api/src/**/*.{ts,tsx}",
    "packages/*/src/**/*.{ts,tsx}",
  ]) {
    const files = new Bun.Glob(pattern);
    for await (const file of files.scan({ cwd: root, onlyFiles: true })) {
      if (
        /(?:\.(?:test|spec)\.|\/(?:tests|__tests__|fixtures)\/)/u.test(file)
      ) {
        continue;
      }
      for (const tag of failureTagsInSource(
        await readFile(path.join(root, file), "utf-8"),
        file,
      )) {
        tags.add(tag);
      }
    }
  }
  return [...tags].toSorted(compareCodeUnit);
};

export const renderFailureTags = (tags: readonly string[]): string =>
  `// Generated by scripts/generate-failure-tags.ts; do not edit.\nexport const FAILURE_TAGS = ${JSON.stringify(tags, null, 2)} as const;\n\nexport type FailureTag = (typeof FAILURE_TAGS)[number];\n`;
